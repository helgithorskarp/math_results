"""Entrywise native replay comparison and independent literal book locations.

Imports neither Python generator nor reference verifier. Native input is
regenerated by native_check.cpp, not trusted by this comparison layer.
"""
import argparse
import collections
import hashlib
import itertools
import json
from pathlib import Path
import resource
import time

CASES = [('star4', [0, 1, 2, 3], 105), ('path4', [0, 6, 11, 15], 1260),
         ('fork', [0, 1, 2, 15], 1260), ('cycle4', [0, 2, 6, 11], 105),
         ('paw', [0, 1, 2, 6], 420), ('triangle_edge', [0, 1, 6, 15], 210),
         ('star_edge', [0, 1, 2, 18], 420), ('path_edge', [0, 6, 11, 18], 1260),
         ('two_wedges', [0, 1, 15, 16], 630), ('wedge_two_edges', [0, 1, 15, 20], 315)]
POSITIONS = list(itertools.combinations(range(5), 2))


def need(condition, message):
    if not condition:
        raise AssertionError(message)


def digest(obj):
    return hashlib.sha256(json.dumps(obj, separators=(',', ':')).encode()).hexdigest()


def direct_flags(core, patterns, joining):
    red = set(core)
    for j, pattern in enumerate(patterns):
        red.update((u, 17 + j) for u in range(17) if (pattern >> u) & 1)
    for b, (i, j) in enumerate(POSITIONS):
        if (joining >> b) & 1:
            red.add((17 + i, 17 + j))
    vertices = set(range(22)); neighbors = [set() for _ in range(22)]
    for u, v in red:
        neighbors[u].add(v); neighbors[v].add(u)
    flags = 0
    for u, v in itertools.combinations(range(22), 2):
        color = int((u, v) in red)
        pages = neighbors[u] & neighbors[v] if color else (
            (vertices - {u, v}) - (neighbors[u] | neighbors[v]))
        if len(pages) > (3 if color else 6):
            location = 0 if v < 17 else (1 if u < 17 else 2)
            flags |= 1 << ((0 if color else 3) + location)
    need(flags != 0, 'A final22 candidate is valid')
    return flags


def check_fixture(path):
    fixture = json.loads(path.read_text())
    need(fixture['format'] == 'kneser17-no-cross-book-example-v1', 'Wrong literal fixture format')
    need(fixture['deleted'] == [0, 2, 6, 11], 'Wrong cycle core')
    roots = [frozenset(p) for p in itertools.combinations(range(7), 2)]
    labels = [u for u in range(21) if u not in fixture['deleted']]
    core = {(u, v) for u, v in itertools.combinations(range(17), 2)
            if roots[labels[u]].isdisjoint(roots[labels[v]])}
    patterns = fixture['red_neighbor_masks']; joining = fixture['joining_mask']
    need(len(patterns) == 5 and patterns == sorted(set(patterns)), 'Fixture pattern order')
    need(all(type(p) is int and 0 <= p < (1 << 17) for p in patterns), 'Fixture pattern range')
    need(type(joining) is int and 0 <= joining < 1024, 'Fixture joining range')
    red = set(core)
    for j, p in enumerate(patterns):
        red.update((u, 17 + j) for u in range(17) if (p >> u) & 1)
    red.update((17 + i, 17 + j) for b, (i, j) in enumerate(POSITIONS) if (joining >> b) & 1)
    neighbors = [set() for _ in range(22)]
    for u, v in red:
        neighbors[u].add(v); neighbors[v].add(u)

    def valid_on(vertices):
        for u, v in itertools.combinations(sorted(vertices), 2):
            c = int((u, v) in red)
            pages = (neighbors[u] & neighbors[v] & vertices) if c else (
                (vertices - {u, v}) - (neighbors[u] | neighbors[v]))
            if len(pages) > (3 if c else 6):
                return False
        return True

    for i, j in POSITIONS:
        need(valid_on(set(range(17)) | {17 + i, 17 + j}), 'Fixture incompatible pair')
    need(valid_on(set(range(21))), 'Fixture first-four prefix is invalid')
    need(direct_flags(core, patterns, joining) == fixture['location_flags'] == 32,
         'Fixture has a different or cross-spine obstruction')
    need(all(7 <= len(row) <= 11 for row in neighbors), 'Fixture degree window')
    spine, pages = fixture['blue_book']['spine'], fixture['blue_book']['pages']
    need(len(spine) == 2 and spine == sorted(set(spine)) and all(17 <= u < 22 for u in spine), 'Fixture spine')
    need(len(pages) == 7 and pages == sorted(set(pages)) and not set(pages) & set(spine), 'Fixture pages')
    need(tuple(spine) not in red and all(0 <= w < 22 and w not in neighbors[u] for u in spine for w in pages), 'False blue book')
    print('literal_no_cross_fixture_verified', flush=True)


def compare(scratch, native, names=None):
    completion = json.loads((native / 'completion.json').read_text())
    need(completion['complete'] is True and completion['labeled_cores'] == 5985, 'Incomplete native census')
    need(completion['cohorts'] == [m for n, s, m in CASES], 'Native root-map cohort mismatch')
    chosen = CASES if names is None else [c for c in CASES if c[0] in names]
    need(completion['cases'] == len(chosen), 'Incomplete native case coverage')
    need(completion['scope'] == ('all' if names is None else names[0]), 'Wrong native scope')
    roots = [frozenset(p) for p in itertools.combinations(range(7), 2)]
    diagnostics = []
    for name, deleted, multiplicity in chosen:
        author = json.loads((scratch / ('case-' + name + '.json')).read_text())
        replay = json.loads((native / ('case-' + name + '.json')).read_text())
        need(author['format'] == 'kneser17-prefix-case-v1', 'Wrong author format')
        need(author['complete_through_outside_vertices'] == 5, 'Incomplete author case')
        for document in (author, replay):
            need(document['name'] == name and document['deleted'] == deleted, 'Core identity mismatch')
        for key in ('domain', 'pair_colors', 'levels', 'counts'):
            need(replay[key] == author[key], 'Native entrywise mismatch: ' + name + ':' + key)
        need(len(author['levels']) == 4 and not author['levels'][-1], 'Nonempty or incomplete level5')
        need(all(i != j for i, j, c in author['pair_colors']), 'Repeated-pattern coverage missing')
        allowed = collections.defaultdict(set); neighborhoods = [set() for _ in author['domain']]
        for i, j, color in author['pair_colors']:
            allowed[i, j].add(color); neighborhoods[i].add(j); neighborhoods[j].add(i)
        labels = [u for u in range(21) if u not in deleted]
        core = {(u, v) for u, v in itertools.combinations(range(17), 2)
                if roots[labels[u]].isdisjoint(roots[labels[v]])}
        records = []
        for indices, mask in author['levels'][2]:
            choices = set(range(indices[-1] + 1, len(author['domain'])))
            for i in indices:
                choices.intersection_update(neighborhoods[i])
            for j in sorted(choices):
                for colors in itertools.product(*(sorted(allowed[i, j]) for i in indices)):
                    joining = mask + sum(c << POSITIONS.index((i, 4)) for i, c in enumerate(colors))
                    full_indices = indices + [j]
                    flags = direct_flags(core, [author['domain'][i] for i in full_indices], joining)
                    records.append(full_indices + [joining, flags])
        records.sort()
        need(records == replay['final_flags'], 'False or omitted final book-location record')
        need(len(records) == author['counts'][2]['joining_tests'], 'Missing final joining')
        histogram = collections.Counter(r[-1] for r in records)
        cross_colors = [0] * 4
        for record in records:
            flags = record[-1]; c = int(bool(flags & 2)) + 2 * int(bool(flags & 16))
            cross_colors[c] += 1
        diagnostic = {'name': name, 'deleted': deleted, 'labeled_core_count': multiplicity,
            'patterns': len(author['domain']), 'colored_pairs': len(author['pair_colors']),
            'valid_prefix_counts': [len(level) for level in author['levels']],
            'final22_candidates': len(records), 'final_flags_sha256': digest(records),
            'location_histogram': {str(f): histogram[f] for f in sorted(histogram)},
            'cross_color_counts': cross_colors}
        diagnostics.append(diagnostic)
        print('native_entrywise_verified', name, 'cross_color_counts', cross_colors, flush=True)
    return {'complete': True, 'scope': completion['scope'], 'cohorts': completion['cohorts'], 'cases': diagnostics}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('scratch', type=Path)
    parser.add_argument('native', type=Path)
    parser.add_argument('--case', choices=[c[0] for c in CASES])
    parser.add_argument('--summary', type=Path)
    parser.add_argument('--expected', type=Path)
    args = parser.parse_args(); start = time.perf_counter()
    check_fixture(Path(__file__).parent / 'witness.json')
    result = compare(args.scratch, args.native, None if args.case is None else [args.case])
    if args.expected:
        expected = json.loads(args.expected.read_text())
        if args.case:
            need(result['cases'] == [c for c in expected['cases'] if c['name'] == args.case], 'Selected profile mismatch')
        else:
            need(result == expected, 'Complete native profile mismatch')
    if args.summary:
        args.summary.write_text(json.dumps(result, indent=2) + '\n')
    print('comparison_complete scope', result['scope'], 'seconds', time.perf_counter()-start,
          'maxrss_kib', resource.getrusage(resource.RUSAGE_SELF).ru_maxrss)


if __name__ == '__main__':
    main()
