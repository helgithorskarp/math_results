#!/usr/bin/env python3
"""Clean-room combinatorial audit of the native B503 plus five closure.

The geometry is regenerated by the previously published independent native-host
checker, whose source is byte-pinned here.  No code from the result under review
is imported.  Connected sets are grown as canonical tuples from the definition,
and the last transversal is independently normalized by mask dominance before a
weighted residual search.
"""
