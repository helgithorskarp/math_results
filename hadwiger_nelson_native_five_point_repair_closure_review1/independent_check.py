def require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def file_hash(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for block in iter(lambda: source.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def sequence_hash(groups) -> str:
    digest = hashlib.sha256()
    for group in sorted(groups):
        digest.update((" ".join(map(str, group)) + "\n").encode())
    return digest.hexdigest()


def load_geometry():
    spec = importlib.util.spec_from_file_location("independent_native_geometry", GEOMETRY_SOURCE)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    points = module.generate_host(False)
    edges, survivors = module.strict_edges(points)
    compact = [module.flatten(point) for point in points]
    require(len(points) == 3919, "independent host cardinality")
    require(len(edges) == 29125, "independent edge cardinality")
    require(module.digest_json(compact) == "fa6c2aa721db1dc24bf96ea71bb0b944c50646d0f0276f3d5f47fa8b7cb766a3",
            "independent point hash")
    require(module.digest_json(edges) == "e6e4757bfcb92fc54f2ad57759c16653e75f920073006ef846c9ce2486f1ec3d",
            "independent edge hash")
    return points, edges, survivors


def validate_words(words, edges, base, vertices):
    require(isinstance(words, list) and len(words) == 126 and len(set(words)) == 126,
            "partial-word inventory")
    edge_checks = 0
    transcript = hashlib.sha256()
    for index, word in enumerate(words):
        require(isinstance(word, str) and len(word) == vertices and set(word) <= set("0123."),
                "partial-word syntax")
        require(all(word[v] != "." for v in base), "partial word omits a base point")
        omitted = []
        for a, b in edges:
            if word[a] != "." and word[b] != ".":
                edge_checks += 1
                require(word[a] != word[b], "monochromatic retained edge")
        for v, value in enumerate(word):
            if value == ".":
                omitted.append(v)
        transcript.update(f"{index}:".encode())
        transcript.update((",".join(map(str, omitted)) + "\n").encode())
    return edge_checks, transcript.hexdigest()


def canonical_connected_growth(free, free_adj, base_degree, masks, full_mask):
    """Grow all viable connected sets through size five as sorted tuples.

    A partial k-set is retained only if d_B(v)+d_S(v)+(5-k)>=4 for each
    selected vertex.  This cannot discard a prefix of a degree-qualified
    five-set.  Canonical tuple sets, rather than ESU or tree embeddings, remove
    duplicates by definition.
    """
    frontier = {(v,) for v in free}
    stages = {"1": {"viable": len(frontier)}}
    qualified_by_size = {}
    for size in range(2, 6):
        following = set()
        generated = 0
        for group in frontier:
            boundary = set()
            for v in group:
                boundary.update(free_adj[v])
            boundary.difference_update(group)
            for u in boundary:
                candidate = tuple(sorted((*group, u)))
                generated += 1
                chosen = set(candidate)
                if all(base_degree[v] + len(free_adj[v] & chosen) + (5 - size) >= 4
                       for v in candidate):
                    following.add(candidate)
        frontier = following
        exact = set()
        for group in frontier:
            chosen = set(group)
            if all(base_degree[v] + len(free_adj[v] & chosen) >= 4 for v in group):
                exact.add(group)
        stages[str(size)] = {
            "candidate_attempts": generated,
            "viable": len(frontier),
            "degree_qualified": len(exact),
        }
        if size in (3, 4):
            qualified_by_size[size] = exact
        if size == 5:
            require(exact == frontier, "five-set viability is not exact")
            uncovered = [
                group for group in exact
                if functools.reduce(int.__or__, (masks[v] for v in group), 0) == full_mask
            ]
            require(not uncovered, "uncovered connected degree-qualified five-set")
            stages[str(size)]["inventory_sha256"] = sequence_hash(exact)
    return qualified_by_size, stages


def item_mask(item, masks):
    value = 0
    for vertex in item:
        value |= masks[vertex]
    return value


def residual_completion_check(groups, completion_items, masks, width):
    """Find a completion covering a residual via rare-bit posting lists.

    This is a direct superset query on integer masks, not the target's
    transposed bit table.
    """
    full = (1 << width) - 1
    completion_masks = sorted({item_mask(item, masks) for item in completion_items})
    postings = [[] for _ in range(width)]
    for mask in completion_masks:
        for bit in range(width):
            if mask >> bit & 1:
                postings[bit].append(mask)
    queries = candidates = 0
    for group in groups:
        residual = full & ~item_mask(group, masks)
        require(residual, "large component already hits every omission word")
        active = [bit for bit in range(width) if residual >> bit & 1]
        pivot = min(active, key=lambda bit: len(postings[bit]))
        queries += 1
        for mask in postings[pivot]:
            candidates += 1
            require(mask & residual != residual, "uncovered large-component completion")
    return {
        "items": len(completion_items),
        "unique_masks": len(completion_masks),
        "queries": queries,
        "candidate_masks_tested": candidates,
    }


def maximal_masks(values):
    maximal = []
    for mask in sorted(set(values) - {0}, key=lambda value: (-value.bit_count(), value)):
        if not any(mask & ~other == 0 for other in maximal):
            maximal.append(mask)
    return maximal


def weighted_cover_after_dominance(singletons, pairs, width, budget=5):
    """Return exact feasibility after safe equal/lower-cost dominance deletion."""
    require(budget == 5, "this split checker is specialized to cost five")
    singles = maximal_masks(singletons)
    undominated_pairs = [mask for mask in set(pairs) - {0}
                         if not any(mask & ~single == 0 for single in singles)]
    pair_masks = maximal_masks(undominated_pairs)
    singleton_hits = [
        tuple(mask for mask in singles if mask >> bit & 1) for bit in range(width)
    ]
    bit_order = sorted(range(width), key=lambda bit: (len(singleton_hits[bit]), bit))
    failed = set()
    calls = cache_hits = one_budget_queries = pair_pair_cases = 0

    def singleton_cover(remaining, capacity):
        nonlocal calls, cache_hits, one_budget_queries
        calls += 1
        if not remaining:
            return True
        if capacity <= 0:
            return False
        pivot = next(bit for bit in bit_order if remaining >> bit & 1)
        if capacity == 1:
            one_budget_queries += 1
            return any(mask & remaining == remaining for mask in singleton_hits[pivot])
        key = (remaining, capacity)
        if key in failed:
            cache_hits += 1
            return False
        for mask in singleton_hits[pivot]:
            if singleton_cover(remaining & ~mask, capacity - 1):
                return True
        failed.add(key)
        return False

    full = (1 << width) - 1
    feasible = singleton_cover(full, 5)
    mode = "zero_pairs"
    if not feasible:
        mode = "one_pair"
        for pair in pair_masks:
            if singleton_cover(full & ~pair, 3):
                feasible = True
                break
    if not feasible:
        mode = "two_pairs"
        for high, first in enumerate(pair_masks):
            for second in pair_masks[:high]:
                pair_pair_cases += 1
                if singleton_cover(full & ~first & ~second, 1):
                    feasible = True
                    break
            if feasible:
                break
    return feasible, {
        "original_singleton_masks": len(singletons),
        "original_pair_masks": len(pairs),
        "maximal_singleton_masks": len(singles),
        "maximal_undominated_pair_masks": len(pair_masks),
        "last_mode_checked": mode,
        "singleton_recursion_calls": calls,
        "singleton_failed_states": len(failed),
        "singleton_cache_hits": cache_hits,
        "one_singleton_queries": one_budget_queries,
        "pair_pair_cases": pair_pair_cases,
    }


def validate_search_controls(cases, edges, base, vertices):
    edge_set = set(edges)
    counts = {}
    checks = 0
    for case in cases:
        selected = case["selected"]
        require(selected == sorted(set(selected))
                and all(type(v) is int and 0 <= v < vertices for v in selected)
                and set(selected).isdisjoint(base),
                "search-control selection")
        support = sorted(base | set(selected))
        require(len(support) == case["vertices"], "search-control order")
        word = case["word"]
        require(len(word) == len(support) and set(word) <= set("0123"), "search-control word")
        colour = dict(zip(support, word))
        retained = [(a, b) for a, b in edge_set if a in colour and b in colour]
        require(len(retained) == case["edges"], "search-control edge count")
        for a, b in retained:
            checks += 1
            require(colour[a] != colour[b], "bad search-control colouring")
        counts[str(len(support))] = counts.get(str(len(support)), 0) + 1
    require(counts == {"508": 7, "509": 10}, "search-control inventory")
    return counts, checks


def run_checks():
    for path, expected in PINS.items():
        require(file_hash(path) == expected, f"source pin: {path}")
    points, edges, sieve_survivors = load_geometry()
    parent = json.loads((PARENT / "certificate.json").read_text())
    base_list = parent["untruncated_fixed_503"]
    require(base_list == sorted(set(base_list)) and len(base_list) == 503, "fixed base")
    require(sorted(parent["record_map"].values()) == base_list, "record-map image")
    base = set(base_list)
    certificate = json.loads((TARGET / "certificate.json").read_text())
    require(certificate.get("format") == "native-five-point-repair-cover-v1", "format")
    words = certificate["partial_words"]
    word_edge_checks, omission_hash = validate_words(words, edges, base, len(points))

    adjacency = [set() for _ in points]
    for a, b in edges:
        adjacency[a].add(b)
        adjacency[b].add(a)
    free = sorted(set(range(len(points))) - base)
    free_set = set(free)
    free_adj = {v: adjacency[v] & free_set for v in free}
    base_degree = {v: len(adjacency[v] & base) for v in free}
    high = [v for v in free if base_degree[v] >= 4]
    qualified_edges = sorted((a, b) for a, b in edges if a in free_set and b in free_set
                             and base_degree[a] >= 3 and base_degree[b] >= 3)
    low_pairs = [pair for pair in qualified_edges if any(base_degree[v] == 3 for v in pair)]
    require((len(high), len(qualified_edges), len(low_pairs)) == (585, 2549, 1238),
            "degree atom counts")
    masks = {
        v: sum(1 << index for index, word in enumerate(words) if word[v] == ".")
        for v in free
    }
    width = len(words)
    full = (1 << width) - 1
    groups, connected_stages = canonical_connected_growth(
        free, free_adj, base_degree, masks, full
    )
    require(len(groups[3]) == 18965 and len(groups[4]) == 175654,
            "connected triple/quadruple counts")
    large_checks = {
        "4_plus_1": residual_completion_check(groups[4], [(v,) for v in high], masks, width),
        "3_plus_2": residual_completion_check(
            groups[3], sorted(set(itertools.combinations(high, 2)) | set(qualified_edges)), masks, width
        ),
    }
    singleton_masks = [masks[v] for v in high]
    pair_masks = [masks[a] | masks[b] for a, b in low_pairs]
    feasible, weighted = weighted_cover_after_dominance(singleton_masks, pair_masks, width)
    require(not feasible, "weighted atom cover exists")

    controls = json.loads((TARGET / "search_controls.json").read_text())["cases"]
    control_counts, control_edge_checks = validate_search_controls(
        controls, edges, base, len(points)
    )

    # Definition-level rejection controls for the partial-word checker.
    corruptions_rejected = 0
    omitted_base = list(words[0])
    omitted_base[min(base)] = "."
    bad_edge = next((a, b) for a, b in edges if words[0][a] != "." and words[0][b] != ".")
    monochromatic = list(words[0])
    monochromatic[bad_edge[1]] = monochromatic[bad_edge[0]]
    trials = []
    for replacement in ("".join(omitted_base), "".join(monochromatic), words[0][:-1]):
        trial = list(words)
        trial[0] = replacement
        trials.append(trial)
    for trial in trials:
        try:
            validate_words(trial, edges, base, len(points))
        except ValueError:
            corruptions_rejected += 1
    require(corruptions_rejected == len(trials), "corruption control accepted")

    return {
        "status": "INDEPENDENT FIXED-BASE FIVE-POINT CLOSURE CHECK PASSED",
        "target_commit": "eec9c1061dcbc4bc63e7cbaad44553ce4f47996d",
        "python": f"CPython {sys.version_info.major}.{sys.version_info.minor}.{sys.version_info.micro}",
        "geometry": {
            "vertices": len(points),
            "strict_unit_edges": len(edges),
            "finite_field_sieve_survivors": sieve_survivors,
            "all_pairs": len(points) * (len(points) - 1) // 2,
            "field": "Q(sqrt(3),sqrt(5),sqrt(11))",
            "imports_target_code": False,
        },
        "fixed_vertices": len(base),
        "free_vertices": len(free),
        "partial_colourings": len(words),
        "retained_edge_checks": word_edge_checks,
        "omission_inventory_sha256": omission_hash,
        "high_singletons": len(high),
        "qualified_free_edges": len(qualified_edges),
        "low_involving_pair_atoms": len(low_pairs),
        "connected_growth": connected_stages,
        "large_component_checks": large_checks,
        "weighted_cover_feasible": feasible,
        "weighted_cover": weighted,
        "positive_search_controls": control_counts,
        "positive_search_control_edge_checks": control_edge_checks,
        "corruptions_rejected": corruptions_rejected,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--work", type=Path, required=True)
    parser.add_argument("--check-expected", action="store_true")
    args = parser.parse_args()
    args.work.mkdir(parents=True, exist_ok=True)
    started = time.monotonic()
    result = run_checks()
    result["seconds"] = time.monotonic() - started
    result["maximum_rss_kib"] = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    if args.check_expected:
        expected = json.loads((HERE / "EXPECTED.json").read_text())
        stable = dict(result)
        stable.pop("seconds")
        stable.pop("maximum_rss_kib")
        require(stable == expected, "expected output mismatch")
    (args.work / "independent-output.json").write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
