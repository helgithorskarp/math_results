"""Independent all-unit high-core and zero-block incidence carriers.

Zero blocks are generated by assigning each point its full subset of the
three block labels, not by quadruple-MRV or first-two-block enumeration.
The actual leave-group / two-stage quotient mathematics is shared and explicit.
"""
from collections import Counter
from itertools import combinations,permutations,product
from hashlib import sha256
import time
from exact import insist,encoded

P=tuple(combinations(range(17),2)); H=tuple(range(5)); LOW=tuple(range(5,17))
Q=tuple(combinations(range(17),4))

def digest(x):return sha256(encoded(x)).hexdigest()
def edges(q):return frozenset(combinations(q,2))
def image(q,p):return tuple(sorted(p[x] for x in q))
def action(frame,p):return tuple(sorted(image(q,p) for q in frame))

def cores():
    pairs=tuple(combinations(H,2));group=tuple(permutations(H));domains={}
    for e in range(4,11):
        raw=set(combinations(pairs,e));unseen=set(raw);classes=[]
        while unseen:
            root=min(unseen);orb={tuple(sorted(image(a,p) for a in root)) for p in group}
            insist(orb<=unseen,'high-core orbit intersection');unseen-=orb
            k4=any(edges(q)<=set(root) for q in combinations(H,4))
            classes.append({'edges':root,'orbit':len(orb),'has_k4':k4})
        domains[e]=classes
    allowed={e:[q for q in rows if not q['has_k4']] for e,rows in domains.items()}
    insist([len(allowed[e]) for e in range(4,11)]==[6,6,5,3,1,0,0],'high-core classification')
    return domains

def model(name):
    covered={'triangle':((0,1),(0,2),(1,2)), 'path':((0,1),(1,2),(2,3)),
             'wedge_edge':((0,1),(1,2),(3,4)), 'eight':((0,1),(2,3))}[name]
    degrees=Counter(x for a in covered for x in a);groups=[];z=5
    for h in H:groups.append(tuple(range(z,z+degrees[h])));z+=degrees[h]
    attached=tuple(range(5,z));matching=tuple((v,v+1) for v in range(z,17,2))
    leave=frozenset((set(combinations(H,2))-set(covered))|
                    {(h,v) for h in H for v in groups[h]}|set(matching))
    insist(len(leave)==16 and [sum(v in e for e in leave) for v in range(17)]==[4]*5+[1]*12,'leave degrees')
    return {'name':name,'covered':covered,'fibers':groups,'attached':attached,'matching':matching,'leave':leave}

def legal(m,frame):
    used=set()
    for q in frame:
        insist(len(q)==4 and q==tuple(sorted(set(q))),'quadruple decoding')
        es=edges(q)
        if es&(m['leave']|used):return False
        used.update(es)
    return True

def group(m):
    # All high maps are filtered independently by the actual adjacency matrix.
    result=[];match=m['matching'];r=len(match)
    for hp in permutations(H):
        if tuple(tuple(sorted((hp[a],hp[b]))) in m['leave'] for a,b in combinations(H,2))!=tuple(e in m['leave'] for e in combinations(H,2)):
            continue
        if {image(e,hp) for e in m['covered']}!=set(m['covered']):continue
        target=[tuple(permutations(m['fibers'][hp[h]])) for h in H]
        for fs in product(*target):
            for order in permutations(range(r)):
                for flip in product((0,1),repeat=r):
                    p=list(range(17));p[:5]=hp
                    for h in H:
                        for x,y in zip(m['fibers'][h],fs[h]):p[x]=y
                    for i,old in enumerate(match):
                        for side,x in enumerate(old):p[x]=match[order[i]][side^flip[i]]
                    p=tuple(p)
                    insist(sorted(p)==list(range(17)) and {image(e,p) for e in m['leave']}==set(m['leave']),'literal group map')
                    result.append(p)
    result=tuple(sorted(result));insist(len(result)==len(set(result)) and tuple(range(17)) in result,'group duplicates/identity')
    # Derive a generating list from the listed maps and check its complete closure.
    known={tuple(range(17))};generators=[];listed=set(result)
    for candidate in result:
        if candidate in known:continue
        generators.append(candidate);pending=list(known)
        while pending:
            p=pending.pop()
            for s in generators:
                q=tuple(s[p[i]] for i in range(17))
                insist(q in listed,'group closure escaped')
                if q not in known:known.add(q);pending.append(q)
    insist(known==listed,'full literal group closure')
    return result

def quotient(raw,maps):
    raw=set(raw);unseen=set(raw);result=[]
    while unseen:
        root=min(unseen);orb={action(root,p) for p in maps}
        insist(orb<=unseen,'invalid or overlapping frame orbit')
        stabilizer=tuple(p for p in maps if action(root,p)==root)
        insist(len(orb)*len(stabilizer)==len(maps),'orbit-stabilizer equation')
        unseen-=orb;result.append((root,len(orb),stabilizer))
    insist(sum(n for _,n,_ in result)==len(raw),'quotient coverage')
    return result

def tails(m):
    choices=[]
    for e in m['covered']:
        choices.append([q for q in Q if tuple(x for x in q if x<5)==e and legal(m,(q,))])
    raw=set()
    for qs in product(*choices):
        if legal(m,qs):raw.add(tuple(qs))
    return raw

def zeros(m,tail,cap=200000):
    counts=Counter(m['attached']);counts.update(x for q in tail for x in q if x>=5)
    insist(sum(counts.values())==12,'three-zero-block incidence sum')
    if any(c>3 for c in counts.values()):return set(),{'states':0}
    labels=tuple(sorted(counts,key=lambda x:(-counts[x],x)))
    forbidden=m['leave']|frozenset().union(*(edges(q) for q in tail))
    blocks=[set(),set(),set()];assigned={};found=set();states=0;start=time.monotonic()
    def visit(i):
        nonlocal states
        states+=1
        if states>cap or (states%1024==0 and time.monotonic()-start>10):raise RuntimeError('INCOMPLETE zero-incidence assignment guard')
        if i==len(labels):
            if all(len(q)==4 for q in blocks):
                frame=tuple(sorted(tuple(sorted(q)) for q in blocks))
                insist(legal(m,tail+frame) and Counter(x for q in frame for x in q)==counts,'false zero incidence frame')
                found.add(frame)
            return
        x=labels[i];c=counts[x]
        # The first point's containing labels can be renamed to 0,...,c-1.
        choices=[tuple(range(c))] if i==0 else combinations(range(3),c)
        for chosen in choices:
            if any(len(blocks[j])==4 for j in chosen):continue
            subset=set(chosen)
            if any((tuple(sorted((x,y))) in forbidden and subset&other) or len(subset&other)>1 for y,other in assigned.items()):continue
            assigned[x]=subset
            for j in chosen:blocks[j].add(x)
            visit(i+1)
            for j in chosen:blocks[j].remove(x)
            del assigned[x]
    visit(0)
    return found,{'states':states}

def triple(m):
    raw=set()
    # Broad construction allows any low tail, then exact zero incidences.
    for x in LOW:
        q=(0,1,2,x)
        if not legal(m,(q,)):continue
        counts=Counter(m['attached']);counts[x]+=2
        for z1 in combinations(sorted(counts),4):
            left=counts-Counter(z1)
            if len(left)!=4 or set(left.values())!={1}:continue
            z2=tuple(sorted(left));frame=(q,)+tuple(sorted((z1,z2)))
            if legal(m,frame):raw.add(frame)
    return raw

def instance(m,prefix):
    insist(legal(m,prefix),'invalid matrix prefix');used=set().union(*(edges(q) for q in prefix))
    rows=tuple(e for e in P if e not in used|m['leave']);s=set(rows)
    columns=tuple(q for q in Q if sum(x<5 for x in q)==1 and edges(q)<=s)
    # This filter scans all2380 words, independent of the target's high+tail loops.
    insist(len(rows)%6==0 and all(len(edges(q))==6 for q in columns),'matrix normalization')
    return prefix,rows,columns

def seven():
    cases=[];summaries=[];assignment_states=0;max_states=0
    for name in ('triangle','path','wedge_edge'):
        m=model(name);g=group(m);raw=tails(m);tq=quotient(raw,g)
        if name=='triangle':
            rt=triple(m);rq=quotient(rt,g)
            for f,n,s in rq:cases.append(instance(m,f))
            summaries.append({'model':name,'branch':'triple','group_order':len(g),'group_sha256':digest(g),'raw_prefixes':len(rt),'raw_prefixes_sha256':digest(sorted(rt)),'prefix_orbits':len(rq)})
        start=len(cases);weight=0;fibers=[]
        for tail,n,st in tq:
            z,metrics=zeros(m,tail);assignment_states+=metrics['states'];max_states=max(max_states,metrics['states'])
            zq=quotient(z,st);weight+=n*len(z);fibers.append([tail,n,len(st),sorted(z)])
            for frame,_,_ in zq:cases.append(instance(m,tail+frame))
        summaries.append({'model':name,'branch':'double','group_order':len(g),'group_sha256':digest(g),'raw_tails':len(raw),'raw_tails_sha256':digest(sorted(raw)),'tail_orbits':len(tq),'raw_prefixes':weight,'prefix_orbits':len(cases)-start,'zero_fibers_sha256':digest(fibers)})
        print({'completed_model':name,'cases':len(cases),'zero_assignment_states':assignment_states},flush=True)
    return cases,summaries,{'states':assignment_states,'max_case_states':max_states}

def eight():
    m=model('eight');g=group(m);raw=set();raw_tails=tails(m)
    # Allow all low tails, including attached/shared positions; the incidence
    # equations and literal pairs remove them without importing the simplification.
    for tail in raw_tails:
        counts=Counter(m['attached']);counts.update(x for q in tail for x in q if x>=5)
        insist(sum(counts.values())==8,'two-zero incidence sum')
        for z1 in combinations(sorted(counts),4):
            left=counts-Counter(z1)
            if len(left)!=4 or set(left.values())!={1}:continue
            z2=tuple(sorted(left));prefix=tail+tuple(sorted((z1,z2)))
            if legal(m,prefix):raw.add(prefix)
    q=quotient(raw,g);cases=[instance(m,prefix) for prefix,_,_ in q]
    return cases,{'group_order':len(g),'raw_general_tails':len(raw_tails),'raw_frames':len(raw),'orbits':len(q),
                  'orbit_sizes':[n for _,n,_ in q],'stabilizer_orders':[len(s) for _,_,s in q],
                  'group_sha256':digest(g),'raw_frames_sha256':digest(sorted((f[0][2:],f[1][2:],f[2:]) for f in raw))}
