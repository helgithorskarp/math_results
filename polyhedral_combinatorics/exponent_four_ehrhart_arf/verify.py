"""Definition-level checks independent of the production decomposition.
Run with Python 3.11+, standard library. Frozen expected.json is required.
"""
import hashlib
import itertools
import json
from fractions import Fraction as F
from pathlib import Path
from arf import analyze


def require(condition, message):
    if not condition:
        raise RuntimeError(message)


def span(vectors):
    values = {0}
    for x in vectors:
        values |= {y ^ x for y in values}
    return values


def direct_group(s, classes):
    values = {(0, 0)}
    for a, x in classes:
        values = {((v + j*a) % 4, y ^ (x if j % 2 else 0))
                  for v, y in values for j in range(4)}
    return values


def character_jump(s, classes):
    # Literal product over all odd characters. Gaussian integers are pairs.
    total_real = total_imag = 0
    for a in (1, 3):
        for y in range(1 << s):
            real, imag = 1, 0
            for e, x in classes:
                power = (a*e + 2*((y & x).bit_count() % 2)) % 4
                # (1-i^power)^(-1) represented with common denominator 2.
                require(power != 0, 'nonanalytic selected character')
                u, v = {1: (1, 1), 2: (1, 0), 3: (1, -1)}[power]
                real, imag = real*u-imag*v, real*v+imag*u
            total_real += real
            total_imag += imag
    require(total_imag == 0, 'character sum not real')
    return F(2*total_real, (4 << s) * (1 << len(classes)))


def direct_code(s, classes):
    odd = [(a, x) for a, x in classes if a % 2]
    words = []
    qvalues = {}
    for z in range(1 << len(odd)):
        if z.bit_count() % 2:
            continue
        xor = 0
        phase = 0
        for j, (a, x) in enumerate(odd):
            if z >> j & 1:
                xor ^= x
                phase += a
        if xor == 0:
            words.append(z)
            qvalues[z] = (phase // 2) % 2
    radical = {z for z in words if all((z & w).bit_count() % 2 == 0 for w in words)}
    return set(words), qvalues, radical


def inspect(s, classes):
    cert = analyze(s, classes)
    words, qvalues, radical = direct_code(s, classes)
    require(span(cert['code_basis']) == words, 'wrong code basis')
    require(len(words) == 1 << cert['code_dimension'], 'dependent code basis')
    require(span(cert['radical_basis']) == radical, 'wrong radical')
    pairs = cert['symplectic_pairs']
    allbasis = cert['radical_basis'] + [u for pair in pairs for u in pair]
    require(span(allbasis) == words and len(words) == 1 << len(allbasis), 'bad decomposition')
    for i, (u, v) in enumerate(pairs):
        require((u & v).bit_count() % 2 == 1, 'not symplectic')
        require(all((a & b).bit_count() % 2 == 0
                    for pair in pairs[i+1:] for a in (u, v) for b in pair), 'nonorthogonal planes')
    actual = sum((-1)**qvalues[z] for z in words)
    require(cert['gauss_sum'] == actual, 'Gauss sum mismatch')
    delta = F(*cert['delta'])
    require(delta == F(actual, 1 << len(classes)) == character_jump(s, classes), 'character mismatch')
    witness = cert['cancellation_witness']
    require((witness is not None) == (actual == 0), 'wrong cancellation status')
    if witness is not None:
        require(witness in radical and qvalues[witness] == 1, 'bad cancellation word')
    else:
        require(all(qvalues[z] == 0 for z in radical), 'radical not quadratic-isotropic')
        require(((-1)**cert['arf']) == (1 if actual > 0 else -1), 'wrong Arf sign')
    return cert


def group_obstruction():
    # All involutions for bounded invariant-factor types, independently
    # compute every q with b in <q> and the subgroup generated by those q.
    checked = excluded = 0
    for a, s in [(0,j) for j in range(1,6)] + [(1,j) for j in range(4)] + [(2,j) for j in range(3)] + [(3,0)]:
        mods = [4]*a + [2]*s
        group = list(itertools.product(*(range(m) for m in mods)))
        zero = (0,)*len(mods)
        add = lambda u,v: tuple((x+y)%m for x,y,m in zip(u,v,mods))
        for b in group:
            if b == zero or add(b,b) != zero:
                continue
            eligible = []
            for q in group:
                cyc = {zero}
                t = zero
                for _ in range(4):
                    t=add(t,q);cyc.add(t)
                if b in cyc:eligible.append(q)
            generated={zero}
            for q in eligible:
                generated={tuple((x+j*y)%m for x,y,m in zip(t,q,mods))
                           for t in generated for j in range(4)}
            possible=(len(generated)==len(group))
            predicted=(a==0 and s==1) or (a==1 and b==(2,)+(0,)*s)
            require(possible==predicted, 'group obstruction failed')
            checked+=1;excluded+=not possible
    return checked,excluded


def slack_counts(s, classes, upto):
    # Unbounded knapsack counts every nonnegative slack vector once.
    size=4 << s
    cap=2*upto
    dp=[[0]*size for _ in range(cap+1)]
    dp[0][0]=1
    for a,x in classes:
        cost=2 if a==2 else 1
        for total in range(cost,cap+1):
            for state, count in enumerate(dp[total-cost]):
                if count:
                    v,y=state%4,state//4
                    new=((v+a)%4)+4*(y^x)
                    dp[total][new]+=count
    return [sum(dp[t][2*(n%2)] for t in range(2*n+1)) for n in range(upto+1)]


def literal_count(s, classes, n):
    def visit(j, budget, a, x):
        if j==len(classes):return int(a==2*(n%2) and x==0)
        e,y=classes[j]; cost=2 if e==2 else 1
        return sum(visit(j+1,budget-cost*u,(a+e*u)%4,x^(y if u%2 else 0))
                   for u in range(budget//cost+1))
    return visit(0,2*n,0,0)


def interpolate(points, value):
    total=F(0)
    for i,(x,y) in enumerate(points):
        term=F(y)
        for j,(z,_) in enumerate(points):
            if j!=i:term*=F(value-z,x-z)
        total+=term
    return total


def main():
    h=hashlib.sha256(); counts={'positive':0,'zero':0,'negative':0}; profiles=0;reject_profiles=0
    for s,max_g in [(0,7),(1,6),(2,4)]:
        alphabet=[(2,0)]+[(a,x) for a in (1,3) for x in range(1<<s)]
        for g in range(1,max_g+1):
            for profile in itertools.product(alphabet,repeat=g):
                full=len(direct_group(s,profile))==4 << s
                if not full:
                    try:analyze(s,profile)
                    except ValueError:reject_profiles+=1;continue
                    raise RuntimeError('nongenerating input accepted')
                c=inspect(s,profile);profiles+=1
                val=F(*c['delta']);counts['zero' if val==0 else 'positive' if val>0 else 'negative']+=1
                h.update(json.dumps([s,profile,c],sort_keys=True,separators=(',',':')).encode()+b'\n')
    fixtures=[(0,[(1,0)]),(0,[(1,0),(1,0)]),(0,[(1,0),(3,0),(2,0)]),
              (1,[(1,0),(1,1)]),(1,[(1,0),(1,0),(1,1)]),
              (1,[(1,0)]*3+[(1,1)]),(1,[(1,0),(3,1),(2,0)]),
              (2,[(1,0),(1,1),(1,2),(1,3)]),
              (2,[(1,0),(3,1),(1,2),(1,3),(1,0)]),
              (2,[(1,0),(1,1),(1,2),(3,3),(2,0)])]
    fixture_records=[];holdouts=literal=changes=0
    for s,profile in fixtures:
        cert=inspect(s,profile);g=len(profile);delta=F(*cert['delta']);upto=2*g+9
        values=slack_counts(s,profile,upto)
        even=[(2*i,values[2*i]) for i in range(g+1)]
        odd=[(2*i+1,values[2*i+1]) for i in range(g+1)]
        for n in range(g+1):require(interpolate(even,n)-interpolate(odd,n)==delta,'wrong parity polynomial')
        for n in range(2*g+2,upto+1):
            require(interpolate(odd if n%2 else even,n)==values[n],'Ehrhart holdout failed');holdouts+=1
        for n in range(4):
            require(literal_count(s,profile,n)==values[n],'slack completeness failed');literal+=1
        # Group automorphisms a -> +/-a+2 ell(x), x -> x+(a mod 2)c.
        # Also reverse all coordinate columns. Each must preserve Delta.
        for sign,ell,shift in itertools.product((1,-1),range(1<<s),range(1<<s)):
            altered=[((sign*a+2*((ell&x).bit_count()%2))%4,x^(shift if a%2 else 0)) for a,x in reversed(profile)]
            require(F(*analyze(s,altered)['delta'])==delta,'coordinate dependence');changes+=1
        fixture_records.append({'s':s,'classes':profile,'certificate':cert,'counts':values})
    malformed=[(-1,[(1,0)]),(True,[(1,0)]),(0,[]),(0,[(0,0)]),(0,[(4,0)]),
               (1,[(2,1)]),(1,[(1,2)]),(0,[(True,0)]),(0,[(1,)]),(0,None)]
    for args in malformed:
        try:analyze(*args)
        except ValueError:continue
        raise RuntimeError('malformed input accepted')
    groups,excluded=group_obstruction()
    return {'status':'pass','generating_profiles':profiles,'nongenerating_profiles_rejected':reject_profiles,
            'signs':counts,'group_involutions_checked':groups,'ineligible_involutions':excluded,
            'simplex_fixtures':len(fixtures),'Ehrhart_holdouts':holdouts,'literal_lattice_counts':literal,
            'coordinate_invariance_checks':changes,'malformed_inputs_rejected':len(malformed),
            'entrywise_sha256':h.hexdigest(),'fixtures':fixture_records}


if __name__=='__main__':
    result=main()
