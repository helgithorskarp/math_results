#!/usr/bin/env python3
"""Falsify a precise sufficient completion mechanism on simple inputs.

Input simplicity is checked by every proper consecutive-position interval.
Every132 scaffold is generated by its maximum decomposition. Only its full
root is restricted adjacent to the input maximum; lower choices are free.
Stop on the first failure. This is an exploratory exact certificate, awaiting
a different researcher's check, never a growth solution or a new target.
"""

import argparse
from functools import lru_cache
import hashlib
import itertools
import json
import math
from pathlib import Path
import platform
import resource
import time

from rectangle_checker import boxed_occurrences


def simple(permutation):
    n = len(permutation)
    return all(max(permutation[i:j]) - min(permutation[i:j]) != j - i - 1
               for i in range(n) for j in range(i + 2, n + 1) if j - i < n)


@lru_cache(maxsize=None)
def scaffolds(n):
    if n == 0:
        return ((),)
    output = []
    for k in range(n):
        r = n - k - 1
        for left in scaffolds(k):
            for right in scaffolds(r):
                output.append(tuple(x + r for x in left) + (n,) + right)
    return tuple(sorted(output))


def classical_132(permutation):
    return any(permutation[i] < permutation[k] < permutation[j]
               for i, j, k in itertools.combinations(range(len(permutation)), 3))


def interleave(permutation, scaffold):
    out = []
    for i, value in enumerate(permutation):
        out.append(2 * value - 1)
        if i < len(scaffold):
            out.append(2 * scaffold[i])
    return tuple(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--max-m", type=int, default=8)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if not 4 <= args.max_m <= 8:
        raise ValueError("Explicit finite scope is4<=max_m<=8")
    began = time.perf_counter()
    rows = []
    trials = 0
    stream = hashlib.sha256()
    failure = None
    for m in range(4, args.max_m + 1):
        full = scaffolds(m - 1)
        catalan = math.comb(2 * (m - 1), m - 1) // m
        assert len(full) == len(set(full)) == catalan
        assert all(set(rho) == set(range(1, m)) and not classical_132(rho) for rho in full)
        tested = 0
        for p in itertools.permutations(range(1, m + 1)):
            if not simple(p):
                continue
            tested += 1
            maximum = p.index(m)
            allowed_positions = {maximum - 1, maximum}
            candidates = tuple(rho for rho in full if rho.index(m - 1) in allowed_positions)
            assert candidates
            rejection_witnesses = []
            chosen = None
            for rho in candidates:
                word = interleave(p, rho)
                occurrences = boxed_occurrences(word)
                trials += 1
                if not occurrences:
                    chosen = rho
                    break
                rejection_witnesses.append({"rho": rho, "indices": occurrences[0]})
            stream.update((json.dumps([p, chosen], separators=(",", ":")) + "\n").encode())
            if chosen is None:
                # Separate the root-only failure from full132 completion.
                any_root = next((rho for rho in full if not boxed_occurrences(interleave(p, rho))), None)
                failure = {"input": p, "simple": True, "m": m,
                           "allowed_root_positions_zero_based": sorted(allowed_positions),
                           "all_132_scaffolds": len(full), "adjacent_candidates": len(candidates),
                           "all_candidate_rejection_witnesses": rejection_witnesses,
                           "unrestricted_root_scaffold": any_root,
                           "unrestricted_root_completion": interleave(p, any_root) if any_root else None,
                           "input_occurrences": boxed_occurrences(p),
                           "minimal_length_among_simple_inputs_in_scope": True}
                break
        rows.append({"m": m, "simple_inputs_tested": tested, "complete_length": failure is None})
        print(json.dumps(rows[-1]), flush=True)
        if failure is not None:
            break
    result = {"actor": "literature-researcher-4", "decision_message_id": 410,
              "full_target_solved": False, "checker": None,
              "status": "finite exact proposed-mechanism falsification, awaiting separate review",
              "hypothesis": "Every simple input of length m>=4 has a boxed2143-avoiding alternating odd/even completion with132 even scaffold, full root adjacent to the old maximum, lower choices unrestricted",
              "rows": rows, "scaffold_trials": trials, "input_success_stream_sha256": stream.hexdigest(),
              "failure": failure, "python": platform.python_version(),
              "seconds": time.perf_counter() - began,
              "peak_rss_kib_linux": resource.getrusage(resource.RUSAGE_SELF).ru_maxrss,
              "processes": 1, "native_threads": 1}
    args.output.write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps({k: v for k, v in result.items() if k != "failure"}, indent=2))
    if failure:
        print(json.dumps({k: v for k, v in failure.items() if k != "all_candidate_rejection_witnesses"}, indent=2))


if __name__ == "__main__":
    main()
