#!/usr/bin/env python3
"""Exact finite hypotheses for the analytic local exclusion in PROOF.md.

Python 3.11+, standard library only. No passage search and no floating point.
Elements of Q(phi) are represented as a + b*phi, phi^2 = phi + 1.
"""

from dataclasses import dataclass
from fractions import Fraction
from itertools import product
import argparse
import json


@dataclass(frozen=True)
class QPhi:
    a: Fraction = Fraction(0)
    b: Fraction = Fraction(0)

    def __post_init__(self):
        object.__setattr__(self, "a", Fraction(self.a))
        object.__setattr__(self, "b", Fraction(self.b))

    @staticmethod
    def coerce(x):
        return x if isinstance(x, QPhi) else QPhi(x)

    def __add__(self, other):
        q = self.coerce(other)
        return QPhi(self.a + q.a, self.b + q.b)

    __radd__ = __add__

    def __neg__(self):
        return QPhi(-self.a, -self.b)

    def __sub__(self, other):
        return self + -self.coerce(other)

    def __rsub__(self, other):
        return self.coerce(other) + -self

    def __mul__(self, other):
        q = self.coerce(other)
        return QPhi(self.a * q.a + self.b * q.b,
                    self.a * q.b + self.b * q.a + self.b * q.b)

    __rmul__ = __mul__

    def inverse(self):
        norm = self.a * self.a + self.a * self.b - self.b * self.b
        if not norm:
            raise ZeroDivisionError("zero in Q(phi)")
        return QPhi((self.a + self.b) / norm, -self.b / norm)

    def __truediv__(self, other):
        return self * self.coerce(other).inverse()

    def __pow__(self, n):
        if not isinstance(n, int) or n < 0:
            raise ValueError("nonnegative integer exponent required")
        result = QPhi(1)
        for _ in range(n):
            result *= self
        return result

    def sign(self):
        # a+b*phi = A+B*sqrt(5). Comparisons below are rational.
        A, B = self.a + self.b / 2, self.b / 2
        if not B:
            return (A > 0) - (A < 0)
        if not A:
            return (B > 0) - (B < 0)
        if A > 0 and B > 0:
            return 1
        if A < 0 and B < 0:
            return -1
        difference = A * A - 5 * B * B
        # sqrt(5) is irrational; nonzero rational A,B cannot give equality.
        if not difference:
            raise ArithmeticError("unexpected rational square root of 5")
        if A > 0:
            return 1 if difference > 0 else -1
        return -1 if difference > 0 else 1

    def __lt__(self, other):
        return (self - other).sign() < 0

    def __gt__(self, other):
        return (self - other).sign() > 0

    def __le__(self, other):
        return (self - other).sign() <= 0

    def __ge__(self, other):
        return (self - other).sign() >= 0

    def encode(self):
        return [str(self.a), str(self.b)]


PHI = QPhi(0, 1)
ZERO = QPhi()


def dot(v, w):
    return sum((a * b for a, b in zip(v, w)), ZERO)


def vertices():
    """The three even-permutation families of Steininger--Yurkevich."""
    result = set()
    seeds = [(QPhi(1), QPhi(1), PHI**3),
             (PHI**2, PHI, 2 * PHI),
             (2 + PHI, ZERO, PHI**2)]
    for seed in seeds:
        for signs in product((-1, 1), repeat=3):
            v = tuple(s * x for s, x in zip(signs, seed))
            for k in range(3):
                result.add(v[k:] + v[:k])
    return result


def selected_clusters(V):
    a, b, c = PHI**3, PHI**2, 2 + PHI
    points = set()
    for sx, sy in product((-1, 1), repeat=2):
        points.update([(sx * a, QPhi(sy)),
                       (QPhi(sx), sy * a), (sx * b, sy * c)])
    return {p: {v for v in V if v[:2] == p} for p in points}


def matmul(A, B):
    return tuple(tuple(dot(row, col) for col in zip(*B)) for row in A)


def act(A, v):
    return tuple(dot(row, v) for row in A)


def symmetry_group(V):
    """Exact group generated by a cyclic permutation and a 72-degree turn.

    The second generator rotates about (0,phi,1); Rodrigues' formula simplifies
    over Q(phi), since sin(72 degrees)/sqrt(phi+2) = 1/2.
    """
    one = QPhi(1)
    I = ((one, ZERO, ZERO), (ZERO, one, ZERO), (ZERO, ZERO, one))
    C = ((ZERO, one, ZERO), (ZERO, ZERO, one), (one, ZERO, ZERO))
    axis = (ZERO, PHI, one)
    cross = ((ZERO, -one, PHI), (one, ZERO, ZERO), (-PHI, ZERO, ZERO))
    cosine, rank = (PHI - 1)/2, (2 - PHI)/2
    T = tuple(tuple(cosine*I[i][j] + rank*axis[i]*axis[j] + cross[i][j]/2
                    for j in range(3)) for i in range(3))
    group, queue = {I}, [I]
    while queue:
        current = queue.pop()
        for generator in (C, T):
            nxt = matmul(generator, current)
            if nxt not in group:
                require(len(group) < 60, "rotation closure exceeds expected 60")
                group.add(nxt)
                queue.append(nxt)
    require(len(group) == 60, "rotation closure must have size 60")
    for G in group:
        transpose = tuple(zip(*G))
        require(matmul(G, transpose) == I, "non-orthogonal symmetry")
        determinant = (G[0][0]*(G[1][1]*G[2][2]-G[1][2]*G[2][1])
                       - G[0][1]*(G[1][0]*G[2][2]-G[1][2]*G[2][0])
                       + G[0][2]*(G[1][0]*G[2][1]-G[1][1]*G[2][0]))
        require(determinant == one, "symmetry is not a proper rotation")
        require({act(G, v) for v in V} == V, "rotation does not preserve V")
    ez = (ZERO, ZERO, one)
    normals = {act(G, ez) for G in group}
    require(len(normals) == 30, "expected 30 oriented axis normals")
    require(all(tuple(-x for x in n) in normals for n in normals),
            "axis orbit not antipodal")
    return {"verified_rotations": len(group),
            "oriented_axis_normals": len(normals), "unoriented_axes": len(normals)//2}


def require(condition, message):
    if not condition:
        raise ValueError(message)


def check(V, eta):
    require(0 < eta <= Fraction(1, 100), "unsupported frame radius")
    require(len(V) == 60, "vertex count must be 60")
    radius2 = 8 * PHI + 7
    require(all(dot(v, v) == radius2 for v in V), "unequal vertex radii")
    require(all(tuple(-x for x in v) in V for v in V),
            "central symmetry missing")
    clusters = selected_clusters(V)
    require(len(clusters) == 12, "twelve selected projected classes required")
    singleton = doubleton = comparisons = 0
    margin = None
    for p, C in clusters.items():
        require(len(C) in (1, 2), "missing or unexpected projection class")
        zs = {v[2] for v in C}
        require(zs == ({ZERO} if len(C) == 1 else {QPhi(-1), QPhi(1)}),
                "incorrect class heights")
        singleton += len(C) == 1
        doubleton += len(C) == 2
        for v in V - C:
            gap = dot(p, tuple(x - y for x, y in zip(p, v[:2])))
            require(gap.sign() > 0, "class fails strict radial exposure")
            margin = gap if margin is None or gap < margin else margin
            comparisons += 1
    require((singleton, doubleton) == (4, 8), "incorrect class multiplicities")
    require(margin == QPhi(1), "expected exact minimum radial gap one")
    require(radius2 < 20, "radius squared bound failed")
    perturbation_bound = 4 * 20 * eta + 2 * 20 * eta * eta
    require(perturbation_bound < 1, "support separation lost")

    a, b, c = PHI**3, PHI**2, 2 + PHI
    lam = (a*a*b*b - c*c) / (a**4 - 1)
    mu = (a*a*c*c - b*b) / (a**4 - 1)
    require(lam.sign() > 0 and mu.sign() > 0, "positive stress failed")
    require(lam*a*a + mu == b*b and lam + mu*a*a == c*c,
            "quadratic stress identities failed")
    # Rational upper/lower bounds used in the r>0 proof.
    require(4 < a < 5 and 2 < b < c < 4, "parameter brackets failed")
    require(a*a + 1 < 25, "paired horizontal norm bound failed")
    require(a*a*b*b - c*c > 48, "negative coefficient margin failed")
    require(0 < c*c - b*b < 16, "singleton anisotropy bound failed")
    require(eta <= Fraction(1, 100), "horizontal normal estimate failed")

    return {
        "agent": "six-rupert-3",
        "role": "researcher",
        "claim_status": "analytic_local_exclusion_with_exact_finite_hypotheses",
        "global_non_rupert_proved": False,
        "arithmetic": "Q(phi), phi^2=phi+1, exact rational sign comparisons",
        "vertices": len(V),
        "radius_squared_a_plus_b_phi": radius2.encode(),
        "selected_projected_classes": len(clusters),
        "singleton_classes": singleton,
        "doubleton_classes": doubleton,
        "radial_gap_comparisons": comparisons,
        "minimum_radial_gap_a_plus_b_phi": margin.encode(),
        "frame_operator_norm_radius": str(eta),
        "support_error_strict_upper_bound": str(perturbation_bound),
        "support_gap_strict_lower_bound": str(1 - perturbation_bound),
        "stress_lambda_a_plus_b_phi": lam.encode(),
        "stress_mu_a_plus_b_phi": mu.encode(),
    }


def self_test():
    require(PHI*PHI == PHI + 1, "field relation")
    require(PHI.inverse() == PHI - 1, "field inverse")
    for x in [QPhi(1), PHI, 2-PHI, PHI-Fraction(8, 5), Fraction(13, 8)-PHI]:
        require(x.sign() == 1 and (-x).sign() == -1, "field sign")
    require(ZERO.sign() == 0, "zero sign")
    V = vertices()
    check(V, Fraction(1, 100))
    bad = set(V)
    bad.remove(next(iter(bad)))
    for invalid, eta in [(bad, Fraction(1, 100)), (V, Fraction(1, 10))]:
        try:
            check(invalid, eta)
        except ValueError:
            pass
        else:
            raise ValueError("invalid certificate hypotheses accepted")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.self_test:
        self_test()
    V = vertices()
    result = check(V, Fraction(1, 100))
    result["symmetry_orbit"] = symmetry_group(V)
    print(json.dumps(result, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
