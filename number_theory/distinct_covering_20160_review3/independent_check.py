#!/usr/bin/env python3
"""Independent CRT/binary-tree proof of the literal minimum-eight cover.

No author implementation, expected table or downloaded input is imported.
All decisions use Python integers; --write records this checker's outputs.
"""
import argparse
from collections import Counter
from hashlib import sha256
import json
from math import gcd, lcm
from pathlib import Path

HERE = Path(__file__).resolve().parent
PERIOD, TWO_PART, ODD_PART = 20160, 64, 315


def require(condition, message):
    if not condition:
        raise ValueError(message)


def load():
    rows = []
    for line in (HERE / "cover.tsv").read_text().splitlines():
        if line and not line.startswith("#"):
            pieces = line.split()
            require(len(pieces) == 2, "malformed literal row")
            rows.append(tuple(map(int, pieces)))
    return rows


def decompose(modulus):
    exponent, odd = 0, modulus
    while odd % 2 == 0:
        exponent += 1
        odd //= 2
    require(exponent <= 6 and ODD_PART % odd == 0,
            "modulus outside the CRT domain")
    return exponent, odd


def antichain(patterns):
    """Keep the first label at each shallowest occupied binary prefix."""
    selected = []
    for depth, residue, label in sorted(patterns):
        if not any(residue % (1 << d) == r for d, r, _ in selected):
            selected.append((depth, residue, label))
    return selected


def validate(rows):
    require(bool(rows), "empty certificate")
    require(all(type(a) is int and type(m) is int and
                m >= 8 and 0 <= a < m for a, m in rows),
            "invalid or unnormalized congruence")
    moduli = [m for _, m in rows]
    require(len(set(moduli)) == len(moduli), "repeated modulus")
    require(min(moduli) == 8, "minimum is not exactly eight")
    require(lcm(*moduli) == PERIOD, "incorrect actual LCM")
    eligible = {d for d in range(8, PERIOD + 1) if PERIOD % d == 0}
    require(set(moduli) == eligible, "not the complete eligible divisor set")
    require(len(rows) == 77, "incorrect number of classes")


def audit(rows, full_contract=True):
    if full_contract:
        validate(rows)
    else:
        require(bool(rows) and all(type(a) is int and type(m) is int and
                    m >= 8 and 0 <= a < m and PERIOD % m == 0
                    for a, m in rows), "invalid CRT class")
    decoded = [(a, m, *decompose(m)) for a, m in rows]
    multiplicities = [-1] * PERIOD
    private = [[] for _ in rows]
    partition_sizes, partition_depths = Counter(), Counter()
    partition_records = []
    inverse = pow(ODD_PART, -1, TWO_PART)
    require((ODD_PART * inverse) % TWO_PART == 1, "bad CRT inverse")
    for y in range(ODD_PART):
        active = [(e, a % (1 << e), i)
                  for i, (a, _, e, odd) in enumerate(decoded)
                  if y % odd == a % odd]
        selected = antichain(active)
        # Distinct binary prefixes are disjoint or nested. Pruning leaves
        # disjoint blocks, so their exact sizes certify full fiber coverage.
        weight = sum(1 << (6 - e) for e, _, _ in selected)
        require(weight == TWO_PART, f"uncovered odd fiber {y}: weight {weight}")
        partition_sizes[len(selected)] += 1
        partition_depths.update(e for e, _, _ in selected)
        partition_records.append([y, selected])
        nodes = {}
        for e, residue, label in active:
            nodes.setdefault((e, residue), []).append(label)

        def visit(e, residue, inherited):
            labels = inherited + nodes.get((e, residue), [])
            if e < 6:
                visit(e + 1, residue, labels)
                visit(e + 1, residue + (1 << e), labels)
                return
            # CRT constructs the integer from the binary leaf and odd fiber;
            # it is not generated by marking an arithmetic progression.
            n = y + ODD_PART * (((residue - y) * inverse) % TWO_PART)
            require(n % TWO_PART == residue and n % ODD_PART == y,
                    "CRT round trip failed")
            require(multiplicities[n] == -1, "duplicate CRT cell")
            require(bool(labels), "uncovered binary leaf")
            multiplicities[n] = len(labels)
            if len(labels) == 1:
                private[labels[0]].append(n)

        visit(0, 0, [])
    require(all(c > 0 for c in multiplicities), "incomplete CRT traversal")
    require(all(points for points in private), "redundant class")
    histogram = Counter(multiplicities)
    incidence = sum(multiplicities)
    require(incidence == sum(PERIOD // m for _, m in rows),
            "incidence double-count failed")
    private_records = []
    for (a, m), points in zip(rows, private):
        points.sort()
        # The entire private set in Z is these residues plus PERIOD*Z.
        # Its congruence-span gcd gives all possible one-class replacements.
        span = PERIOD
        for n in points:
            span = gcd(span, n - points[0])
        require(span % m == 0 and PERIOD % span == 0, "bad private span")
        private_records.append({"a": a, "m": m, "private_count": len(points),
                                "first_private": points[0],
                                "private_span_gcd": span})
    folded = {}
    for a, m in rows:
        projected_modulus = gcd(m, PERIOD // 2)
        folded.setdefault(projected_modulus, []).append(a % projected_modulus)
    double_phases = {m: phases for m, phases in folded.items() if len(phases) > 1}
    require(len(double_phases) == 12 and
            all(len(p) == 2 and p[0] != p[1] for p in double_phases.values()),
            "unexpected half-period projection")
    return {
        "schema": 1, "method": "CRT odd fibers and least-significant-bit prefix trees",
        "period": PERIOD, "crt_factors": [TWO_PART, ODD_PART],
        "classes": len(rows), "minimum": min(m for _, m in rows),
        "complete_eligible_divisor_set": True,
        "odd_fibers": ODD_PART, "binary_leaves_per_fiber": TWO_PART,
        "partition_size_histogram": dict(sorted(partition_sizes.items())),
        "partition_depth_histogram": dict(sorted(partition_depths.items())),
        "partition_records_sha256": sha256(json.dumps(
            partition_records, separators=(",", ":")).encode()).hexdigest(),
        "multiplicity_histogram": dict(sorted(histogram.items())),
        "incidences": incidence,
        "multiplicity_bytes_sha256": sha256(bytes(multiplicities)).hexdigest(),
        "private_records": private_records,
        "private_span_gcd_equals_modulus": sum(
            r["m"] == r["private_span_gcd"] for r in private_records),
        "single_class_replacement_rigid": True,
        "half_period_projection": {
            "period": PERIOD // 2, "distinct_moduli": len(folded),
            "duplicate_modulus_phases": double_phases},
    }


def controls(rows):
    # Exhaust the entire family of occupied-prefix subsets of the depth-three
    # binary tree: 15 possible nodes, including the root and all eight leaves.
    all_nodes = [(e, r, 0) for e in range(4) for r in range(1 << e)]
    for subset in range(1 << len(all_nodes)):
        patterns = [p for i, p in enumerate(all_nodes) if subset & (1 << i)]
        kept = antichain(patterns)
        direct = {x for x in range(8)
                  if any(x % (1 << e) == r for e, r, _ in patterns)}
        require(sum(1 << (3 - e) for e, _, _ in kept) == len(direct),
                "prefix antichain disagrees with literal leaf control")
    rejected = 0
    mutations = [
        rows + [rows[0]],
        [(0, 7)] + rows[1:],
        [(-1, rows[0][1])] + rows[1:],
        rows[:-1],
    ]
    # Every congruence has a private point: deletion or a one-step phase
    # change must destroy coverage, not merely alter a checksum.
    mutations += [rows[:i] + [((a + 1) % m, m)] + rows[i + 1:]
                  for i, (a, m) in enumerate(rows)]
    for index, mutated in enumerate(mutations):
        try:
            audit(mutated)
        except ValueError as error:
            if index >= 4:
                require("uncovered odd fiber" in str(error),
                        "phase control did not expose a coverage hole")
            rejected += 1
        else:
            raise ValueError("malformed/noncovering control was accepted")
    for i in range(len(rows)):
        # Skip the saturated-family requirement so that an actual uncovered
        # fiber, rather than just a missing input row, must cause rejection.
        try:
            audit(rows[:i] + rows[i + 1:], full_contract=False)
        except ValueError as error:
            require("uncovered odd fiber" in str(error),
                    "deletion control did not expose a coverage hole")
            rejected += 1
        else:
            raise ValueError("class deletion was accepted")
    return {"all_depth_three_prefix_subsets": 1 << len(all_nodes),
            "rejected_mutations": rejected,
            "all_single_phase_shifts_rejected": len(rows)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true",
                        help="write independently generated expected.json")
    args = parser.parse_args()
    rows = load()
    result = audit(rows)
    result["controls"] = controls(rows)
    encoded = json.dumps(result, indent=2, sort_keys=True) + "\n"
    if args.write:
        (HERE / "expected.json").write_text(encoded)
    else:
        require(json.loads((HERE / "expected.json").read_text()) ==
                json.loads(encoded), "independent expected evidence mismatch")
    print(encoded, end="")


if __name__ == "__main__":
    main()
