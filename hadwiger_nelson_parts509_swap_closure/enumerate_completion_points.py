#!/usr/bin/env python3
"""Exact enumeration of completion points of the Parts-509 graph.

A completion point is a point q of the plane, not itself a Parts vertex, at
Euclidean distance exactly one from at least two Parts vertices.  Every point
at unit distance from three or more vertices is the circumcenter of three of
them and therefore lies in K^2, K = Q(sqrt3, sqrt5, sqrt11).  For each pair of
vertices the two intersection points of their unit circles lie in K^2 exactly
when rho^2 = (4 - d^2)/(4 d^2) is a square in K; that is decided exactly by a
recursive square-root test down the quadratic tower.  Each K-rational
intersection point is keyed by its exact coordinates, so a point with m unit
neighbours is generated by all C(m,2) pairs of them and its neighbour set is the
union of the generating pairs.  No floating point is used in the enumeration;
floats appear only as a convenience column in the output.
"""
from __future__ import annotations
import importlib.util, json, sys, time
from fractions import Fraction
from pathlib import Path
from multiprocessing import Pool

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import kfield as kf

_CANDIDATES = [HERE.parent / 'hadwiger_nelson_parts509_criticality',
               Path.home() / 'math_results' / 'hadwiger_nelson_parts509_criticality']
BASE = next(p for p in _CANDIDATES if (p / 'parts509.py').exists())
K = 3
FOUR = kf.const(K, 4)
HALF = Fraction(1, 2)
POINTS = None


def load_parts():
    spec = importlib.util.spec_from_file_location('parts509', BASE / 'parts509.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def init():
    global POINTS
    POINTS = load_parts().parse_points(BASE / 'parts509.vtx')


def row(i):
    pts = POINTS
    n = len(pts)
    xi, yi = pts[i]
    out = {}
    rational_pairs = 0
    for j in range(i + 1, n):
        xj, yj = pts[j]
        dx = kf.sub(xi, xj)
        dy = kf.sub(yi, yj)
        d2 = kf.add(kf.mul(dx, dx, K), kf.mul(dy, dy, K))
        rho2 = kf.mul(kf.sub(FOUR, d2), kf.inv(kf.scale(d2, 4), K), K)
        r = kf.field_sqrt(rho2, K)
        if r is None:
            continue
        rational_pairs += 1
        mx = kf.scale(kf.add(xi, xj), HALF)
        my = kf.scale(kf.add(yi, yj), HALF)
        rwx = kf.mul(r, kf.neg(dy), K)
        rwy = kf.mul(r, dx, K)
        for s in (1, -1):
            q = (kf.add(mx, kf.scale(rwx, s)), kf.add(my, kf.scale(rwy, s)))
            out.setdefault(q, set()).update((i, j))
    return i, rational_pairs, out


def scan(args):
    """Independent exact neighbour scan of one point against all vertices."""
    q = args
    parts_one = kf.one(K)
    result = []
    for idx, p in enumerate(POINTS):
        dx = kf.sub(q[0], p[0])
        dy = kf.sub(q[1], p[1])
        if kf.add(kf.mul(dx, dx, K), kf.mul(dy, dy, K)) == parts_one:
            result.append(idx)
    return result


def main():
    t0 = time.time()
    parts = load_parts()
    points = parts.parse_points(BASE / 'parts509.vtx')
    edges = parts.build_edges(points)
    n = len(points)
    adj = parts.adjacency(n, edges)
    print(f"loaded {n} points, {len(edges)} edges in {time.time()-t0:.1f}s", flush=True)

    merged = {}
    total_rational_pairs = 0
    with Pool(8, initializer=init) as pool:
        for i, rp, out in pool.imap_unordered(row, range(n), chunksize=4):
            total_rational_pairs += rp
            for q, gens in out.items():
                merged.setdefault(q, set()).update(gens)
    print(f"pairs with K-rational intersections: {total_rational_pairs} of {n*(n-1)//2}; "
          f"distinct K-points: {len(merged)}; {time.time()-t0:.1f}s", flush=True)

    vertex_index = {p: idx for idx, p in enumerate(points)}
    # consistency: every vertex of degree >= 2 must be generated by exactly its neighbourhood
    bad = 0
    seen_vertices = 0
    for q, gens in merged.items():
        if q in vertex_index:
            seen_vertices += 1
            if gens != adj[vertex_index[q]]:
                bad += 1
    expected_vertices = sum(1 for v in range(n) if len(adj[v]) >= 2)
    print(f"vertices recovered as K-points: {seen_vertices} (expected {expected_vertices}), mismatches: {bad}", flush=True)
    assert bad == 0 and seen_vertices == expected_vertices

    completion = {q: gens for q, gens in merged.items() if q not in vertex_index}
    hist = {}
    for gens in completion.values():
        hist[len(gens)] = hist.get(len(gens), 0) + 1
    print("completion-point histogram by number of unit neighbours:", dict(sorted(hist.items())), flush=True)

    q3 = [(q, sorted(gens)) for q, gens in completion.items() if len(gens) >= 3]
    # independent exact rescan of every Q3 point against all vertices
    with Pool(8, initializer=init) as pool:
        scans = pool.map(scan, [q for q, _ in q3], chunksize=8)
    mism = sum(1 for (q, gens), sc in zip(q3, scans) if sc != gens)
    print(f"Q3 size {len(q3)}; exact full-rescan mismatches: {mism}; {time.time()-t0:.1f}s", flush=True)
    assert mism == 0

    records = []
    for q, gens in q3:
        fx, fy = kf.to_float(q[0]), kf.to_float(q[1])
        records.append({
            "x": kf.to_strings(q[0]),
            "y": kf.to_strings(q[1]),
            "x_float": fx,
            "y_float": fy,
            "neighbors": gens,
        })
    records.sort(key=lambda r: (-len(r["neighbors"]), r["x_float"], r["y_float"]))
    out = {
        "field": "Q(sqrt3, sqrt5, sqrt11), basis masks over (3,5,11), coefficient index bit0=sqrt3, bit1=sqrt5, bit2=sqrt11",
        "vertices": n,
        "edges": len(edges),
        "pairs_total": n * (n - 1) // 2,
        "pairs_with_K_rational_intersection": total_rational_pairs,
        "distinct_K_points_on_two_or_more_unit_circles_excluding_vertices": len(completion),
        "histogram_by_neighbors": {str(k): v for k, v in sorted(hist.items())},
        "q3_count": len(q3),
        "q4_count": sum(1 for _, g in q3 if len(g) >= 4),
        "points": records,
    }
    (HERE / 'completion_points.json').write_text(json.dumps(out, indent=1))
    print(f"wrote completion_points.json; total {time.time()-t0:.1f}s", flush=True)


if __name__ == '__main__':
    main()
