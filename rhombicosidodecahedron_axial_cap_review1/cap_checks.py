def squared(x):return dot(x,x)
def identity():return tuple(tuple(ONE if i==j else Z for j in range(3)) for i in range(3))
def mapping(columns,images):
    a,b,c=columns;d=dot(a,cross(b,c));need(d!=Z,'frame basis independent')
    inverse=[scale(cross(b,c),1/d),scale(cross(c,a),1/d),scale(cross(a,b),1/d)]
    return tuple(tuple(sum((images[k][i]*inverse[k][j] for k in range(3)),Z)
                       for j in range(3)) for i in range(3))

def shadow(V,G):
    d=(Z,ONE,-PHI*PHI);dd=squared(d)
    project=lambda v:sub(v,scale(d,dot(v,d)/dd))
    S=set(map(project,V));rho=R2-Q(F(1,3))
    C=sorted(p for p in S if squared(p)==rho)
    need(len(C)==12 and 16<rho<25,'twelve circle points and radius')
    gap=min(rho-squared(p) for p in S if p not in C)
    need(gap==Q(F(4,3)),'exact gap to all other projected vertices')
    active=[v for v in V if dot(v,d)>0 and dot(v,d)*dot(v,d)/dd==Q(F(1,3))]
    stabilizer=[M for M in G if mv(M,d)==d]
    need(len(active)==6 and len(stabilizer)==3,'positive contacts and axial C3')
    tri={project(mv(M,active[0])) for M in stabilizer}
    need(len(tri)==3 and all(squared(x)==rho for x in tri),'active stress triangle')
    need(tuple(sum((p[i] for p in tri),Z) for i in range(3))==(Z,Z,Z),'zero stress sum')
    need(all(dot(p,q)==-rho/2 for p,q in combinations(tri,2)),'equilateral stress triangle')
    p=C[0];good=[];bad=[];valid_rot=[]
    for q in C:
        M=mapping((p,cross(d,p),d),(q,cross(d,q),d))
        need(det(M)==1 and mv(M,d)==d and mv(M,p)==q,'proper candidate roll')
        need(all(dot(M[i],M[j])==(ONE if i==j else Z) for i in range(3) for j in range(3)),
             'candidate roll orthogonal')
        images={mv(M,x) for x in C}
        if images==set(C):
            need({mv(M,x) for x in S}==S,'circle symmetry preserves full shadow')
            good.append(dot(p,q)/rho);valid_rot.append(M)
        else:bad.append(max(min(squared(sub(x,y)) for y in C) for x in images))
    need(len(good)==6 and len(bad)==6,'complete planar roll classification')
    need(sorted(good)==[Q(-1),Q(-F(1,2)),Q(-F(1,2)),Q(F(1,2)),Q(F(1,2)),ONE],
         'valid rolls are C6')
    need(min(bad)==(176-96*PHI)/57 and min(bad)>Q(F(1,100)),'bad-roll defect margin')
    need(set(valid_rot)=={M for H in stabilizer for M in (H,mapping((p,cross(d,p),d),
                       (scale(mv(H,p),-1),scale(mv(H,cross(d,p)),-1),d)))},
         'valid rolls generated by axial body rotations and planar half-turn')
    # Six positive-height tangent vertices: identify every supporting edge
    # by all-point side tests, rather than assuming a cyclic hull order.
    P=sorted(map(project,active));edge_dist=[];edge_count=Counter()
    for i,j in combinations(range(6),2):
        a,b=P[i],P[j];side=[dot(d,cross(sub(b,a),sub(x,a))) for x in P]
        if all(s>=0 for s in side) or all(s<=0 for s in side):
            need(sum(s==Z for s in side)==2,'strict hexagon edge')
            origin=dot(d,cross(sub(b,a),scale(a,-1)))
            need(origin!=Z and all(s*origin>=0 for s in side),'origin inside active hexagon')
            edge_dist.append(squared(cross(a,b))/squared(sub(b,a)))
            edge_count[i]+=1;edge_count[j]+=1
    need(len(edge_dist)==6 and all(edge_count[i]==2 for i in range(6)),'all active hexagon facets')
    h2=Q(F(8,3))+4*PHI
    need(Counter(edge_dist)==Counter({h2:3,Q(F(17,3))+8*PHI:3}),'sharp hexagon inradius')
    return {'projected_points':len(S),'circle_points':12,'circle_radius_squared':rho.encode(),
            'other_radius_gap':gap.encode(),'positive_active_vertices':6,'axial_stabilizer':3,
            'valid_rolls':6,'invalid_rolls':6,'minimum_bad_roll_defect_squared':min(bad).encode(),
            'active_hexagon_facet_distances_squared':[{'squared_distance':q.encode(),'edges':n}
                          for q,n in sorted(Counter(edge_dist).items())]}

def chamber(V,G):
    A=(Z,Z,ONE);B=(Z,1/(PHI*PHI),ONE);D=(1/(PHI*(PHI+2)),1/(PHI+2),ONE)
    walls=[(ONE,Z,Z),(Z,ONE,Z),(-PHI,-PHI*PHI,ONE)]
    GG={tuple(tuple(sign*x for x in row) for row in M) for M in G for sign in (-1,1)}
    for h in walls:
        H=tuple(tuple((ONE if i==j else Z)-2*h[i]*h[j]/squared(h) for j in range(3)) for i in range(3))
        need(H in GG and {mv(H,v) for v in V}==set(V),'all wall reflections are body symmetries')
        need(dot(h,(ONE,ONE,Q(5)))>0,'chamber orbit-maximizing direction')
    orbit={mv(M,B) for M in GG};need(len(orbit)==20,'signed threefold chamber orbit')
    ray=lambda p:scale(p,1/next(x for x in p if x!=Z))
    need(ray(B) in {ray(mv(M,(Z,ONE,-PHI*PHI))) for M in G},'chamber B is an optimal threefold axis')
    margin=[]
    for x in orbit:
        if x==B:continue
        negatives=[dot(x,h)*dot(x,h)/(squared(x)*squared(h))
                   for h in walls if dot(x,h)<0]
        need(negatives,'every other center outside closed chamber')
        margin.append(max(negatives))
    need(min(margin)==(2-PHI)/3 and min(margin)>Q(F(1,10000)),'chamber wall orbit separation')
    need(squared(B)<Q(F(25,16)) and B[1]-D[1]==(7-4*PHI)/5
         and B[1]-D[1]>Q(F(1,10)) and B[1]>Q(F(3,10)),'chart norms and ABD margin')
    # B,D lie on the outer side. Splitting ABC at D gives ABD and ADC;
    # every point of ADC has y<=D_y. No five-cell coverage assumption is needed.
    C=(1/PHI,Z,ONE)
    need(all(dot(walls[2],x)==Z for x in (B,D,C)) and Z<D[0]<C[0]
         and Z<D[1]<B[1],'D lies strictly between B and C')
    return (A,B,D),{'signed_axis_orbit':20,'minimum_negative_wall_distance_squared':min(margin).encode(),
                    'chart_gap_to_ADC':(B[1]-D[1]).encode()}

def probes():
    return [((PHI*PHI,-(2+PHI),Z),(PHI-1,ONE,PHI)),
            ((2*PHI,-PHI*PHI,PHI),(ONE,PHI,1-PHI)),
            ((2*PHI,PHI*PHI,-PHI),(-ONE,PHI,1-PHI)),
            ((PHI*PHI,2+PHI,Z),(1-PHI,ONE,PHI))]

def solve(M,b):
    rows=[list(r)+[v] for r,v in zip(M,b)];N=len(b)
    for k in range(N):
        j=next((j for j in range(k,N) if rows[j][k]!=Z),None)
        need(j is not None,'linear system full rank');rows[k],rows[j]=rows[j],rows[k]
        rows[k]=[x/rows[k][k] for x in rows[k]]
        for i in range(N):
            if i==k:continue
            c=rows[i][k];rows[i]=[x-c*y for x,y in zip(rows[i],rows[k])]
    return [row[-1] for row in rows]

def torque(V,ABD,pairs):
    comparisons=0
    for v,e in pairs:
        need(v in V and squared(e)==4 and (add(v,e) in V or sub(v,e) in V),'original supporting edge data')
        for u in ABD:
            m=cross(e,u)
            need(squared(m)>0,'nonzero weak support at all corners')
            need(dot(m,cross(e,ABD[1]))>0,'probe cannot vanish on the whole closed triangle')
            for w in V:
                need(dot(m,sub(v,w))>=0,'whole ABD supporting probe');comparisons+=1
    T=[cross(v,cross(e,ABD[1])) for v,e in pairs]
    M=[tuple(t[i] for t in T) for i in range(3)]+[(ONE,ONE,ONE,ONE)]
    weights=solve(M,[Z,Z,Z,ONE]);need(all(w>0 for w in weights),'strict positive origin balance')
    need(tuple(sum((w*t[i] for w,t in zip(weights,T)),Z) for i in range(3))==(Z,Z,Z),
         'direct tetrahedron barycentric balance')
    distances=[]
    for omit in range(4):
        p,q,r=[T[j] for j in range(4) if j!=omit];n=cross(sub(q,p),sub(r,p));nn=squared(n)
        need(nn>0 and dot(n,p)*dot(n,sub(T[omit],p))<0,'origin lies strictly inward of torque facet')
        distances.append(dot(n,p)*dot(n,p)/nn)
    a=(18272-11056*PHI)/37561;b=(24160-14640*PHI)/2449
    need(distances==[a,b,b,a] and min(distances)>Q(F(1,100)),'four exact center torque facet distances')
    need(all(squared(u)<Q(F(25,16)) for u in ABD) and R2<25,'remainder norm bound M<25/2')
    return {'whole_ABD_support_comparisons':comparisons,'positive_center_weights':[q.encode() for q in weights],
            'center_facet_distances_squared':[q.encode() for q in distances],
            'center_ball_radius_greater_than_one_tenth':True}

def bounds(delta):
    delta=F(delta);beta=(19-8*PHI)/29;eta=190*delta;e2=1900*delta
    checks={
        'source_winning_region':Q(F(1,3)-50*delta)>beta,
        'source_height_above_one_half':F(1,3)-50*delta>F(1,4),
        'source_chord_36_delta':2*25*25<36*36,
        'circle_radial_gap':10*eta<F(4,3),
        'circle_error_below_1_32':e2<F(1,32)**2,
        'bad_roll_error_below_1_10':4*e2<F(1,100),
        'chamber_gap':delta<F(1,100),
        'receiver_z_above_79_100':F(4,5)-delta>F(79,100),
        'chart_error_below_3_delta':F(9,4)/F(79,100)<3,
        'receiver_in_ABD':3*delta<F(1,10),
        'relative_angle_below_1_63':148*delta+F(1,64)<F(1,63),
        'torque_remainder_margin':F(25,252)<F(1,10)-30*delta,
    }
    need(all(checks.values()),'cap constant exceeds a proved error margin')
    need(148*delta+F(1,64)==F(15699,1000000) if delta==F(1,2000000) else True,
         'printed full angle arithmetic')
    return {'receiver_chord_radius':str(delta),'one_sided_shadow_error':str(eta),
            'squared_circle_error':str(e2),'full_relative_angle_upper':str(148*delta+F(1,64)),
            'perturbed_torque_radius_lower':str(F(1,10)-30*delta),'exact_error_guards':checks}

def winning_radius():
    # Proved refinement: the whole winning-region f^2>=beta components have
    # chord radius <1/25, using the complete six-contact tangent hexagon.
    beta=(19-8*PHI)/29;h2=Q(F(8,3))+4*PHI;delta=F(1,25)
    z=1-delta*delta/2;s2=delta*delta*(1-delta*delta/4)
    need(h2>9 and beta>Q(F(57,125)**2),'coarse orientation positivity guards')
    need(Q(z*z/3)>beta,'positive left side before first squaring')
    # z/sqrt3 - sqrt(beta) < sqrt(h2*s2): the first squared comparison
    # reduces to A < 2*z*sqrt(beta/3), with A positive here.
    A=Q(z*z/3)+beta-h2*s2
    need(A>0 and A*A<4*z*z*beta/3,'strict 1/25 winning-component radius')
    return {'winning_superlevel_squared':beta.encode(),'strict_chord_radius_upper':'1/25',
            'sharp_active_hexagon_inradius_squared':h2.encode(),'squared_comparison_margin':(4*z*z*beta/3-A*A).encode()}

def control_reject(action):
    try:action()
    except ValueError:return True
    raise ValueError('deliberately corrupted input accepted')

def verify(V,G):
    ss=shadow(V,G);ABD,cs=chamber(V,G);pp=probes();ts=torque(V,ABD,pp)
    bc=bounds(F(1,2000000));wr=winning_radius()
    altered=list(pp);altered[0]=(altered[0][0],scale(altered[0][1],-1))
    controls={'reversed_supporting_edge_rejected':control_reject(lambda:torque(V,ABD,altered)),
              'missing_original_vertex_rejected':control_reject(lambda:group(V[:-1])),
              'unsupported_larger_cap_rejected':control_reject(lambda:bounds(F(1,1000)))}
    return {'shadow':ss,'chamber':cs,'support_torque':ts,'cap':bc,'proved_winning_component_refinement':wr,
            'negative_controls':controls}

