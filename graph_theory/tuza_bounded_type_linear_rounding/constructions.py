"""Finite exact witnesses for the two new interfaces and exterior rounding.

This does not implement Keevash's existence theorem or determine its threshold.
All repair traces and triangle lists are transient, regenerated by check.py.
"""
from collections import Counter, defaultdict
from fractions import Fraction
from itertools import combinations, product

from flow import allocate_spokes, avoiding_matching, require


def edge(a, b):
    require(a != b, 'loop in a simple graph')
    return (min(a, b), max(a, b))


def balanced_roles(size, total):
    require(type(size) is int and size > 0 and type(total) is int and total >= 0,
            'bad balanced list')
    q, r = divmod(total, size)
    return [q + (v < r) for v in range(size)]


def pendant_tag(roles):
    """Exact row degrees; missing edges distributed cyclically over columns."""
    require(roles and all(type(x) is int and x >= 0 for x in roles), 'bad roles')
    require(max(roles)-min(roles) <= 1 and max(roles) > 0, 'unbalanced/zero tag')
    a = max(roles)
    missing, cursor = [], 0
    for v, degree in enumerate(roles):
        if degree < a:
            missing.append((v, cursor % a))
            cursor += 1
    return {'columns': a, 'missing': missing}


def type_balanced_coloring(vertex_types, edges, palette, initial=None):
    """Preserve every edge-type/color count while repairing conflicts.

The proof supplies a sufficient domain. Outside it this routine either returns
an explicitly checkable witness or raises; success is not promised there.
"""
    require(type(palette) is int and palette > 0, 'invalid palette')
    n = len(vertex_types)
    edges = [tuple(e) for e in edges]
    require(all(len(e) == 2 and 0 <= e[0] < e[1] < n for e in edges)
            and len(set(edges)) == len(edges), 'invalid simple edge list')
    types = [tuple(sorted((vertex_types[a], vertex_types[b]))) for a, b in edges]
    by_type = defaultdict(list)
    for k, t in enumerate(types):
        by_type[t].append(k)
    if initial is None:
        colors = [0]*len(edges)
        for ids in by_type.values():
            for k, idx in enumerate(ids):
                colors[idx] = k % palette
    else:
        require(len(initial) == len(edges) and
                all(type(c) is int and 0 <= c < palette for c in initial), 'bad colors')
        colors = list(initial)
    for ids in by_type.values():
        counts = Counter(colors[k] for k in ids)
        q, rem = divmod(len(ids), palette)
        require(all(q <= counts.get(c, 0) <= q+bool(rem) for c in range(palette)),
                'initial type colors are not equitable')
    first = list(colors)
    at = [Counter() for _ in range(n)]
    for (a, b), c in zip(edges, colors):
        at[a][c] += 1
        at[b][c] += 1
    potential = sum(k*(k-1)//2 for counts in at for k in counts.values())
    initial_potential = potential
    cursor = Counter()
    trace = []
    # A swap creates no new conflict, so a single pass suffices.
    for idx, (u, v) in enumerate(edges):
        c = colors[idx]
        if at[u][c] == at[v][c] == 1:
            continue
        ids = by_type[types[idx]]
        chosen = None
        for step in range(len(ids)):
            pos = (cursor[types[idx]]+step) % len(ids)
            other = ids[pos]
            a, b = edges[other]
            t = colors[other]
            if not at[u][t] and not at[v][t] and not at[a][c] and not at[b][c]:
                chosen = other
                cursor[types[idx]] = pos+1
                break
        require(chosen is not None, 'no same-type repair candidate')
        a, b = edges[chosen]
        t = colors[chosen]
        before = potential
        for w, old in ((u,c),(v,c),(a,t),(b,t)):
            potential -= at[w][old]-1
            at[w][old] -= 1
        for w, new in ((u,t),(v,t),(a,c),(b,c)):
            require(at[w][new] == 0, 'repair creates a conflict')
            at[w][new] += 1
        colors[idx], colors[chosen] = t, c
        require(potential < before, 'nondecreasing repair potential')
        trace.append((idx, chosen, before, potential))
    require(potential == 0, 'unfinished repair')
    return {'initial': first, 'colors': colors, 'trace': trace,
            'initial_potential': initial_potential}


def affine_classes(dimension):
    """Classical affine F_3 fixture, used only for literal interior examples."""
    points = list(product(range(3), repeat=dimension))
    index = {p: i for i, p in enumerate(points)}
    answer = []
    for direction in points:
        if not any(direction) or next(x for x in direction if x) != 1:
            continue
        unseen, triples = set(range(len(points))), []
        while unseen:
            a = min(unseen)
            tri = tuple(sorted(index[tuple((x+t*y) % 3 for x,y in zip(points[a],direction))]
                               for t in range(3)))
            triples.append(tri)
            unseen.difference_update(tri)
        answer.append((direction, triples))
    return points, answer


def exterior_fixture(core_sizes, vertex_types, interior, labeled_edges,
                     neighborhoods, w_masses, cutoff, row_buffer, spoke_masses=None):
    """Complete exterior construction starting from supplied literal X pieces.

    Each (h, i, j) profile coordinate represents X_h H_i H_j. The supplied
    interior pieces replace the existential role-completion input in fixtures.
    """
    s = len(vertex_types)
    d = len(core_sizes)
    groups = [[v for v, t in enumerate(vertex_types) if t == h]
              for h in range(max(vertex_types)+1)]
    require(all(groups), 'empty exceptional type')
    offsets, n = [], 0
    for size in core_sizes:
        offsets.append(n)
        n += size
    triangles = [tuple(n+x for x in tri) for tri in interior]
    occupied = [[set() for _ in range(s)] for _ in range(d)]
    colorings = []
    for i, edges in enumerate(labeled_edges):
        cert = type_balanced_coloring(vertex_types, edges, core_sizes[i])
        for (x, y), c in zip(edges, cert['colors']):
            require(i in neighborhoods[vertex_types[x]] and
                    i in neighborhoods[vertex_types[y]], 'unsupported XXH')
            occupied[i][x].add(c)
            occupied[i][y].add(c)
            triangles.append((n+x, n+y, offsets[i]+c))
        colorings.append(cert)
    labeled_spokes = []
    for (h,part,label), mass in sorted((spoke_masses or {}).items()):
        require(part in neighborhoods[h] and mass >= 0, 'unsupported labeled spoke')
        vertices = groups[h]
        demand = Fraction(mass)//len(vertices)-row_buffer
        demand = demand if demand >= cutoff else 0
        if not demand:
            continue
        available = [set(range(core_sizes[part]))-occupied[part][x] for x in vertices]
        chosen, operations = allocate_spokes(available, core_sizes[part], demand)
        for x,row in zip(vertices,chosen):
            occupied[part][x].update(row)
        labeled_spokes.append({'type': (h,part,label), 'demand': demand,
                               'selected': [sorted(row) for row in chosen], 'operations': operations})
    quotas = {}
    for (h,i,j), mass in w_masses.items():
        require(i <= j and i in neighborhoods[h] and j in neighborhoods[h] and mass >= 0,
                'unsupported XHH')
        q = Fraction(mass)//len(groups[h])-row_buffer
        quotas[h,i,j] = q if q >= cutoff else 0
    forbidden = defaultdict(set)
    allocations, repairs = [], 0
    for (h,i,j), q in sorted(quotas.items(), key=lambda x:(x[1],x[0])):
        if q == 0:
            continue
        vertices = groups[h]
        selected, records = {}, []
        for part, demand in ([(i,2*q)] if i == j else [(i,q),(j,q)]):
            available = [set(range(core_sizes[part]))-occupied[part][x] for x in vertices]
            chosen, operations = allocate_spokes(available, core_sizes[part], demand)
            selected[part] = chosen
            records.append({'part': part, 'demand': demand,
                            'selected': [sorted(row) for row in chosen], 'operations': operations})
            for x, row in zip(vertices, chosen):
                occupied[part][x].update(row)
        pairings = []
        for k, x in enumerate(vertices):
            if i == j:
                both = sorted(offsets[i]+v for v in selected[i][k])
                left, right = both[:q], both[q:]
            else:
                left = [offsets[i]+v for v in selected[i][k]]
                right = [offsets[j]+v for v in selected[j][k]]
            pairs, count = avoiding_matching(left, right, forbidden)
            repairs += count
            pairings.append(pairs)
            for a, b in pairs:
                forbidden[a].add(b)
                forbidden[b].add(a)
                triangles.append((n+x, a, b))
        allocations.append({'type': (h,i,j), 'quota': q, 'spokes': records, 'pairings': pairings})
    return {'colorings': colorings, 'quotas': sorted(quotas.items()), 'labeled_spokes': labeled_spokes,
            'allocations': allocations, 'triangles': triangles, 'matching_repairs': repairs}
