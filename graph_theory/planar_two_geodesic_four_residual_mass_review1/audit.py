"""Independent four-residual geodesic-pair checker for order-16 graph6 streams.

Unlike the target checker, paths are generated by BFS level descent from
every source. No target code is imported. Python 3 standard library only.
"""
import argparse
from collections import deque
import hashlib
import json
from pathlib import Path

N = 16
FULL = (1 << N) - 1


def bits(mask):
    while mask:
        bit = mask & -mask
        yield bit.bit_length() - 1
        mask -= bit


def decode(raw):
    line = raw.rstrip(b'\r\n')
    assert len(line) == 21 and line[0] == 79
    data = []
    for char in line[1:]:
        assert 63 <= char <= 126
        data.extend((char - 63 >> j) & 1 for j in range(5, -1, -1))
    assert len(data) == 120
    adj = [0] * N
    k = 0
    for v in range(1, N):
        for u in range(v):
            if data[k]:
                adj[u] |= 1 << v
                adj[v] |= 1 << u
            k += 1
    assert sum(row.bit_count() for row in adj) == 84
    return tuple(adj)


def bfs(adj, start):
    d = [-1] * N
    d[start] = 0
    todo = deque([start])
    while todo:
        u = todo.popleft()
        for v in bits(adj[u]):
            if d[v] < 0:
                d[v] = d[u] + 1
                todo.append(v)
    assert min(d) >= 0 and max(d) <= 3
    return d


def all_path_masks(adj):
    masks = set()
    for source in range(N):
        d = bfs(adj, source)
        def grow(u, mask):
            masks.add(mask)
            for v in bits(adj[u]):
                if d[v] == d[u] + 1:
                    grow(v, mask | (1 << v))
        grow(source, 1 << source)
    return sorted(masks, key=lambda x: (-x.bit_count(), x))


def max_component(adj, removed):
    unseen = FULL & ~removed
    largest = 0
    while unseen:
        bit = unseen & -unseen
        unseen -= bit
        frontier = bit
        size = 0
        while frontier:
            vbit = frontier & -frontier
            frontier -= vbit
            size += 1
            u = vbit.bit_length() - 1
            fresh = adj[u] & unseen
            frontier |= fresh
            unseen &= ~fresh
        largest = max(largest, size)
    return largest


def witness(adj):
    paths = all_path_masks(adj)
    attempts = 0
    for i, p in enumerate(paths):
        for q in paths[i:]:
            attempts += 1
            if max_component(adj, p | q) <= 4:
                return len(paths), attempts, (p | q).bit_count()
    raise AssertionError('no four-residual geodesic pair')


def check(path):
    digest = hashlib.sha256()
    stats = {'records':0,'path_masks':0,'pair_attempts':0,
             'min_witness_vertices':N,'max_witness_vertices':0}
    with path.open('rb') as stream:
        for raw in stream:
            digest.update(raw)
            adj = decode(raw)
            paths, attempts, vertices = witness(adj)
            stats['records'] += 1
            stats['path_masks'] += paths
            stats['pair_attempts'] += attempts
            stats['min_witness_vertices'] = min(stats['min_witness_vertices'], vertices)
            stats['max_witness_vertices'] = max(stats['max_witness_vertices'], vertices)
    assert stats['records'] > 0
    stats['sha256'] = digest.hexdigest()
    return stats


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('graph6', type=Path, nargs='+')
    args = parser.parse_args()
    for path in args.graph6:
        print(json.dumps({'file':path.name, **check(path)}, sort_keys=True))


if __name__ == '__main__':
    main()
