"""Exact all-geodesic intersection-family gap and all-mass positive proof.

Only the standard library and the adjacent compact certificate are used.
Core routes are generated by unweighted BFS; positive metric gaps prove
the entire ambient catalog and its stability on a full-dimensional box.
"""
from collections import deque
from fractions import Fraction
from itertools import combinations
from pathlib import Path
import argparse
import hashlib
import json

HERE=Path(__file__).resolve().parent
ALL=(1<<32)-1


def graph(data):
    faces=[]
    for i in range(5):
        u,v=1+i,1+(i+1)%5;a,b=6+i,6+(i+1)%5
        faces.extend([(0,u,v),(v,u,a),(v,a,b),(11,b,a)])
    faces.sort(key=lambda F:tuple(sorted(F)))
    edges=sorted({tuple(sorted((u,v))) for F in faces for u,v in zip(F,F[1:]+F[:1])})
    core={(u,v):w for u,v,w in data['core_edges']};assert set(core)==set(edges)
    cost=dict(core);adj=[0]*32;triangles=[];parents={12+i:p for i,p in enumerate(data['parents'])}
    long=sum(core.values())+20*data['parent_length']+1
    for z,F in enumerate(faces,12):
        assert parents[z] in F
        for u in F:cost[u,z]=data['parent_length'] if u==parents[z] else long
        for u,v in zip(F,F[1:]+F[:1]):triangles.append((u,v,z))
    for u,v in cost:adj[u]|=1<<v;adj[v]|=1<<u
    darts=[(u,v) for F in triangles for u,v in zip(F,F[1:]+F[:1])]
    assert len(cost)==90 and len(triangles)==60 and 32-len(cost)+len(triangles)==2
    assert len(darts)==len(set(darts)) and all((v,u) in darts for u,v in darts)
    for v in range(32):
        link={}
        for F in triangles:
            if v in F:
                i=F.index(v);assert F[(i+1)%3] not in link;link[F[(i+1)%3]]=F[(i+2)%3]
        first=min(link);seen=set();u=first
        while u not in seen:seen.add(u);u=link[u]
        assert u==first and seen==set(link)==set(link.values())
        assert sum(1<<u for u in seen)==adj[v]
    return core,cost,adj,parents,long


def parts(adj,removed):
    left=ALL&~removed;out=[]
    while left:
        first=left&-left;left^=first;part=first;todo=first
        while todo:
            bit=todo&-todo;todo^=bit
            new=adj[bit.bit_length()-1]&left;left^=new;part|=new;todo|=new
        out.append(part)
    return out


def core_catalog(core):
    neighbors=[[] for _ in range(12)]
    for u,v in core:neighbors[u].append(v);neighbors[v].append(u)
    routes={};winners={};critical=[];comparisons=0
    for s in range(12):
        hops={s:0};queue=deque([s])
        while queue:
            u=queue.popleft()
            for v in neighbors[u]:
                if v not in hops:hops[v]=hops[u]+1;queue.append(v)
        assert max(hops.values())==3
        def visit(P):
            u=P[-1]
            if s<=u:routes.setdefault((s,u),[]).append(P)
            for v in sorted(neighbors[u]):
                if hops[v]==hops[u]+1:visit(P+[v])
        visit([s])
    assert sum(map(len,routes.values()))==162
    for endpoints,paths in routes.items():
        values=[sum(core[tuple(sorted(e))] for e in zip(P,P[1:])) for P in paths]
        value=min(values);assert values.count(value)==1;P=paths[values.index(value)];winners[endpoints]=P
        chosen={tuple(sorted(e)) for e in zip(P,P[1:])}
        for Q,other in zip(paths,values):
            if Q==P:continue
            alternate={tuple(sorted(e)) for e in zip(Q,Q[1:])}
            critical.append(Fraction(other-value,len(chosen^alternate)));comparisons+=1
    return winners,min(critical),comparisons


def full_catalog(winners,parents):
    paths=[]
    for a in range(32):
        for b in range(a,32):
            if a==b:paths.append([a]);continue
            u,v=parents.get(a,a),parents.get(b,b);P=winners[min(u,v),max(u,v)]
            if u>v:P=P[::-1]
            paths.append(([a] if a in parents else [])+P+([b] if b in parents else []))
    assert len(paths)==528 and all(len(P)==len(set(P)) for P in paths)
    return paths


def check_positive(data,adj,paths):
    catalog={tuple(P) for P in paths}|{tuple(P[::-1]) for P in paths}
    groups=[]
    for P,Q in data['positive_pairs']:
        assert tuple(P) in catalog and tuple(Q) in catalog
        groups.append(set(C for C in parts(adj,sum(1<<v for v in set(P+Q))) if C.bit_count()>4))
    dual=data['dual_sets'];assert len(dual)==4 and len(set(dual))==4
    assert all(sum(bool(C>>v&1) for C in dual)<=2 for v in range(32))
    forced=set();finished=False
    for step in data['positive_trace']:
        assert not finished
        if step['kind']=='fractional':
            assert {C for C,D in step['witnesses']}==set(dual)
            assert all(D in forced and D&C==D for C,D in step['witnesses']);finished=True;continue
        assert step['kind']=='force';group=groups[step['group']];blocked=set()
        for C,D in step['blockers']:
            assert C in group and D in forced and not C&D;blocked.add(C)
        assert group-blocked=={step['component']};forced.add(step['component'])
    assert finished
    return len(groups),len(forced)


def check_family(data,adj,paths):
    family=data['family'];assert family and len(set(family))==len(family)
    for C in family:
        assert 0<C<=ALL and parts(adj,ALL^C)==[C]
    for C,D in combinations(family,2):assert C&D
    masks=[sum(1<<v for v in P) for P in paths];checked=0
    for i,P in enumerate(masks):
        for Q in masks[i:]:
            assert any(not C&(P|Q) for C in family);checked+=1
    catalog={tuple(P) for P in paths}|{tuple(P[::-1]) for P in paths}
    triple=data['three_path_transversal'];assert len(triple)==3 and all(tuple(P) in catalog for P in triple)
    covered=sum(1<<v for v in set().union(*map(set,triple)));assert all(C&covered for C in family)
    return checked


def run():
    blob=(HERE/'certificate.json').read_bytes();data=json.loads(blob)
    core,cost,adj,parents,long=graph(data);winners,critical,comparisons=core_catalog(core)
    radius=Fraction(data['core_box_radius']);assert 0<radius<critical
    assert all(h*(max(core.values())+radius)<(h+1)*(min(core.values())-radius) for h in range(4))
    paths=full_catalog(winners,parents);pairs,forced=check_positive(data,adj,paths);negative=check_family(data,adj,paths)
    catalog_hash=hashlib.sha256(json.dumps(paths,separators=(',',':')).encode()).hexdigest()
    # The set-family claim must reject a path catalog augmented by a
    # nongeodesic whole-vertex sequence, which hits every member.
    try:check_family(data,adj,paths+[list(range(32))])
    except AssertionError:rejected=True
    else:raise AssertionError('invalid enlarged catalog accepted')
    return {'status':'PASS','vertices':32,'edges':90,'faces':60,'core_routes':162,
            'core_route_comparisons':comparisons,'critical_catalog_radius':str(critical),'certified_box_radius':str(radius),
            'ambient_geodesics':len(paths),'ambient_pairs_with_repetition':negative,'catalog_sha256':catalog_hash,
            'family_members':len(data['family']),'family_pair_intersections':len(data['family'])*(len(data['family'])-1)//2,
            'positive_pairs':pairs,'forced_heavy_sets':forced,'dual_terms':len(data['dual_sets']),
            'family_geodesic_transversal_number':3,'representative_long_length':long,
            'invalid_catalog_rejected':rejected,'certificate_sha256':hashlib.sha256(blob).hexdigest(),
            'scope':'Complete finite path-pair audit plus exact all-mass trace and written metric-box argument; no Problem31 counterexample.'}


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--write-expected',action='store_true');args=parser.parse_args();result=run()
    if args.write_expected:(HERE/'expected.json').write_text(json.dumps({'verify':result},indent=2)+'\n')
    print(json.dumps(result,sort_keys=True))
