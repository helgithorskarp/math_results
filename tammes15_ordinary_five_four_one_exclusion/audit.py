def actual_role(labels,spec,v):
    matches={t for index,t in spec['exact'].items() if labels[index]==v}
    if len(matches)>1:raise RuntimeError('Conflicting role in passing partition')
    return next(iter(matches)) if matches else 2

def append_words(spec,names,words):
    result=dict(spec);result['names']=spec['names']+names;result['words']=spec['words']+words
    number={n:i for i,n in enumerate(result['names'])}
    result['faces']=tuple(tuple(number[n] for n in w) for w in result['words'])
    return result

def ordinary_stars(labels,spec):
    positions={n:i for i,n in enumerate(spec['names'])}
    roles={n:actual_role(labels,spec,labels[positions[n]]) for n in ('L','K','M')}
    names=();words=()
    for n in ('L','K','M'):
        if roles[n] not in (0,1,2):raise RuntimeError('Invalid strip role')
        if roles[n]!=2:continue
        h='H'+n;names+=(h,)
        if n=='L':words+=(('L','K',h),('L',h,'P'))
        if n=='K':words+=(('K','M',h),('K',h,'L'))
        if n=='M':words+=(('M',h,'K'),('M','Q',h))
    return roles,append_words(spec,names,words)

def cells_and_links(labels,spec):
    if len(labels)!=len(spec['names']):raise RuntimeError('Incomplete audit forcing partition')
    cells={face_key(tuple(labels[i] for i in w)) for w in spec['faces']}
    corners=defaultdict(list);neighbor=defaultdict(set);links=defaultdict(lambda:defaultdict(set))
    for cell in cells:
        for i,v in enumerate(cell):
            a,b=cell[i-1],cell[(i+1)%len(cell)]
            corners[v].append(cell);neighbor[v].update((a,b));links[v][a].add(b);links[v][b].add(a)
    edges={v:set(ns) for v,ns in neighbor.items()}
    for a,b in spec['contact_edges']:
        x,y=labels[a],labels[b];edges.setdefault(x,set()).add(y);edges.setdefault(y,set()).add(x)
    return corners,neighbor,links,edges

def new_U_offenders(labels,spec):
    corners,neighbors,links,edges=cells_and_links(labels,spec);answer=set()
    for index,t in spec['exact'].items():
        v=labels[index]
        if t!=1 or len(corners[v])!=2 or any(len(cell)!=4 for cell in corners[v]):continue
        if sorted(len(ns) for ns in links[v].values())!=[1,1,2]:continue
        if 1 in edges[v] and 1 not in neighbors[v]:answer.add(spec['names'][index])
    return answer

def last_face(labels,spec):
    corners,neighbors,links,edges=cells_and_links(labels,spec)
    representatives={v:next(n for n,x in zip(spec['names'],labels) if x==v) for v in set(labels)}
    # This independent construction sews the missing cell to the two
    # boundary edges of an unoriented path, using source arc directions.
    oriented_arcs=set()
    for word in spec['faces']:
        cell=tuple(labels[i] for i in word)
        for i,a in enumerate(cell):oriented_arcs.add((a,cell[(i+1)%len(cell)]))
    for v in sorted(corners):
        if v in (0,1) or len(corners[v])!=3:continue
        t=actual_role(labels,spec,v);needed=t-sum(len(c)==3 for c in corners[v])
        if needed not in (0,1):raise RuntimeError('Wrong remaining T/Q role')
        ends=sorted(n for n,row in links[v].items() if len(row)==1)
        if len(ends)!=2 or sorted(len(row) for row in links[v].values())!=[1,1,2,2]:
            raise RuntimeError('Three known corners are not a four-neighbor path')
        a,b=ends
        if (v,a) in oriented_arcs:start,end=b,a
        elif (a,v) in oriented_arcs:start,end=a,b
        else:raise RuntimeError('Missing oriented boundary arc')
        name=representatives[v];x,y=representatives[start],representatives[end]
        if needed:words=((name,x,y),);names=()
        else:
            j='J'+str(len(spec['names']));names=(j,);words=((name,x,j,y),)
        return name,t,words,append_words(spec,names,words)
    return None

def cover(spec,expected,initial,raw_block_width=1):
    start=len(initial);states={initial} if check(initial,spec) else set();raw=0;boundaries=1
    saved=expected['passing_partitions_by_depth']
    if [list(p) for p in sorted(states)]!=saved.get(str(start),[]):raise RuntimeError('Initial partition differs')
    previous=start
    ends=list(range(start+raw_block_width,len(spec['names']),raw_block_width))
    if len(spec['names'])>start:ends.append(len(spec['names']))
    for end in ends:
        next_states=set();block_raw=0
        for prefix in sorted(states):
            for tail in product(range(end),repeat=end-previous):
                block_raw+=1
                if block_raw>200000:raise RuntimeError('INCOMPLETE: fixed200000rawblockbudget')
                labels=prefix+tail
                if check(labels,spec):next_states.add(normalize(labels))
        wanted=set(map(tuple,saved.get(str(end),[])))
        if next_states!=wanted:
            raise RuntimeError('Boundary '+str(end)+' differs surplus '+str(sorted(next_states-wanted)[:2])+' missing '+str(sorted(wanted-next_states)[:2]))
        raw+=block_raw;boundaries+=1;previous,states=end,next_states
    if [list(p) for p in sorted(states)]!=expected['survivors']:raise RuntimeError('Final partition differs')
    return sorted(states),raw,boundaries

def same_words(first,second):
    return {face_key(tuple(w)) for w in first}=={face_key(tuple(w)) for w in second}

