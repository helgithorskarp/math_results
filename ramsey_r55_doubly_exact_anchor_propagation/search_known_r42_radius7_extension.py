#!/usr/bin/env python3
"""Search exact catalog radius seven for a singleton-extension witness.

The target 42-vertex degree multiset is ``20^22 21^20``.  Every exact
seven-edge repair reaching it is generated by the cancellation decomposition
proved and tested in ``verify_known_r42_radius6_slack.py``.  Any repaired
Ramsey graph has 22 possible choices for the unique degree-20 vertex ``z``
outside the new vertex's red neighborhood.  For each choice this script tests
the two necessary and sufficient extension conditions: the other 21
degree-20 vertices contain no red K4, and the remaining 21 vertices contain
no blue K4.  A passing choice is independently expanded and checked on all
43 vertices.

A bounded run is scouting evidence only unless it emits a ``CERTIFIED``
witness.  An unbounded run that reaches its final PASS line exhausts the
selected catalog orientations.
"""

from __future__ import annotations

import argparse
import hashlib
import itertools

from verify_known_r42_bridge import (
    CATALOG_PATH,
    CATALOG_SHA256,
    TARGET_DEGREES,
    complement_adjacency,
    decode_short_graph6,
    degree_multiset,
)
from verify_known_r42_radius5 import (
    bit_adjacency,
    contains_clique,
    flip_graph_generator,
    self_test,
)
from verify_known_r42_radius6_saturated import (
    assignment_self_test,
    is_ramsey_after_local,
    local_repair_self_test,
)
from verify_known_r42_radius6_slack import (
    CACHE_REQUIREMENT_BLOCK,
    degree_compatible_flip_sets,
    slack_self_test,
    target_high_sets_through_cost,
    weak_compositions,
)


ORDER = 42
RADIUS = 7
TARGET_EDGES = 430


def apply_repairs(base_bits: list[int], additions, deletions) -> list[int]:
    adjacency = base_bits.copy()
    for first, second in (*additions, *deletions):
        adjacency[first] ^= 1 << second
        adjacency[second] ^= 1 << first
    return adjacency


def complement_bits(adjacency: list[int]) -> list[int]:
    mask = (1 << len(adjacency)) - 1
    return [
        mask ^ (1 << vertex) ^ row for vertex, row in enumerate(adjacency)
    ]


def contains_clique_in(adjacency: list[int], vertices: int, wanted: int) -> bool:
    """Test for a clique inside one specified vertex mask."""

    def search(candidates: int, remaining: int) -> bool:
        if candidates.bit_count() < remaining:
            return False
        if remaining == 1:
            return bool(candidates)
        while candidates.bit_count() >= remaining:
            vertex_bit = candidates & -candidates
            candidates ^= vertex_bit
            vertex = vertex_bit.bit_length() - 1
            if search(candidates & adjacency[vertex], remaining - 1):
                return True
        return False

    return search(vertices, wanted)


def extension_vertices(adjacency: list[int]) -> tuple[int, ...]:
    """Return every choice of z that permits the 43rd-vertex extension."""
    degrees = tuple(row.bit_count() for row in adjacency)
    if tuple(sorted(degrees)) != TARGET_DEGREES:
        raise AssertionError("wrong radius-seven target degrees")
    low_vertices = tuple(
        vertex for vertex, degree in enumerate(degrees) if degree == 20
    )
    if len(low_vertices) != 22:
        raise AssertionError("wrong number of degree-20 vertices")
    low_mask = sum(1 << vertex for vertex in low_vertices)
    all_mask = (1 << ORDER) - 1
    blue = complement_bits(adjacency)
    choices = []
    for z in low_vertices:
        red_side = low_mask ^ (1 << z)
        blue_side = all_mask ^ red_side
        if contains_clique_in(adjacency, red_side, 4):
            continue
        if contains_clique_in(blue, blue_side, 4):
            continue
        choices.append(z)
    return tuple(choices)


def extend_singleton(adjacency: list[int], z: int) -> list[int]:
    """Add vertex 42 red to all degree-20 vertices except z."""
    if len(adjacency) != ORDER:
        raise AssertionError("wrong base order")
    degrees = tuple(row.bit_count() for row in adjacency)
    red_side = tuple(
        vertex
        for vertex, degree in enumerate(degrees)
        if degree == 20 and vertex != z
    )
    if len(red_side) != 21:
        raise AssertionError("wrong singleton red side")
    extended = adjacency.copy()
    singleton = 0
    for vertex in red_side:
        extended[vertex] |= 1 << ORDER
        singleton |= 1 << vertex
    extended.append(singleton)
    return extended


def encode_short_graph6(adjacency: list[int]) -> str:
    order = len(adjacency)
    if not 0 <= order <= 62:
        raise ValueError("only short graph6 order headers are supported")
    bits = [
        bool(adjacency[first] & (1 << second))
        for second in range(1, order)
        for first in range(second)
    ]
    bits.extend([False] * (-len(bits) % 6))
    payload = []
    for start in range(0, len(bits), 6):
        value = sum(int(bits[start + offset]) << (5 - offset) for offset in range(6))
        payload.append(chr(63 + value))
    return chr(63 + order) + "".join(payload)


def validate_extension(adjacency: list[int], z: int) -> list[int]:
    """Expand one proposed witness and check the defining Ramsey property."""
    if contains_clique(adjacency) or contains_clique(complement_bits(adjacency)):
        raise AssertionError("42-vertex repair is not Ramsey")
    extended = extend_singleton(adjacency, z)
    if len(extended) != 43:
        raise AssertionError("wrong extension order")
    if tuple(sorted(row.bit_count() for row in extended)) != (20,) + (21,) * 42:
        raise AssertionError("wrong extension degree multiset")
    if contains_clique(extended) or contains_clique(complement_bits(extended)):
        raise AssertionError("proposed 43-vertex extension is not Ramsey")
    return extended


def extension_self_test() -> None:
    """Cross-check masked clique search and graph6 output literally."""
    order = 7
    edges = tuple(itertools.combinations(range(order), 2))
    for sample in range(64):
        adjacency = [0] * order
        for index, (first, second) in enumerate(edges):
            value = ((sample + 11) * 0x9E3779B1 + index * 0x85EBCA77) >> (
                index % 13
            ) & 1
            if value:
                adjacency[first] |= 1 << second
                adjacency[second] |= 1 << first
        chosen = sum(
            1 << vertex for vertex in range(order) if (sample + 3 * vertex) % 5
        )
        selected = tuple(
            vertex for vertex in range(order) if chosen & (1 << vertex)
        )
        for wanted in range(1, 5):
            literal = any(
                all(
                    adjacency[first] & (1 << second)
                    for first, second in itertools.combinations(vertices, 2)
                )
                for vertices in itertools.combinations(selected, wanted)
            )
            if contains_clique_in(adjacency, chosen, wanted) != literal:
                raise AssertionError((sample, chosen, wanted))
        encoded = encode_short_graph6(adjacency)
        decoded = decode_short_graph6(encoded)
        if bit_adjacency(decoded) != adjacency:
            raise AssertionError((sample, encoded))


def count_degree_compatible_flip_sets(
    adjacency, low_target: int, high_count: int, flip_count: int
) -> int:
    """Count the exact decomposition without scanning its Cartesian products."""
    degrees = tuple(sum(row) for row in adjacency)
    additions_for = flip_graph_generator(adjacency, False)
    deletions_for = flip_graph_generator(adjacency, True)
    requirement_index = 0
    count = 0
    for _, changes, endpoint_cost in target_high_sets_through_cost(
        degrees, low_target, high_count, 2 * flip_count
    ):
        cancellation_total = (2 * flip_count - endpoint_cost) // 2
        for cancellations in weak_compositions(cancellation_total, len(degrees)):
            if (
                requirement_index
                and requirement_index % CACHE_REQUIREMENT_BLOCK == 0
            ):
                additions_for.cache_clear()
                deletions_for.cache_clear()
            requirement_index += 1
            addition_requirements = tuple(
                max(change, 0) + cancellation
                for change, cancellation in zip(
                    changes, cancellations, strict=True
                )
            )
            deletion_requirements = tuple(
                max(-change, 0) + cancellation
                for change, cancellation in zip(
                    changes, cancellations, strict=True
                )
            )
            count += len(additions_for(addition_requirements)) * len(
                deletions_for(deletion_requirements)
            )
    return count


def count_self_test() -> None:
    """Compare the product count with literal generator lengths on K6."""
    order = 6
    adjacency = [[False] * order for _ in range(order)]
    for first, second in itertools.combinations(range(order), 2):
        adjacency[first][second] = adjacency[second][first] = (
            first + 2 * second
        ) % 3 == 0
    for flip_count in range(4):
        expected = sum(
            1
            for _ in degree_compatible_flip_sets(
                adjacency, 2, 2, flip_count
            )
        )
        actual = count_degree_compatible_flip_sets(
            adjacency, 2, 2, flip_count
        )
        if actual != expected:
            raise AssertionError((flip_count, actual, expected))


def run_self_tests() -> None:
    """Run the inherited repair tests and the radius-seven-specific tests."""
    self_test()
    assignment_self_test()
    local_repair_self_test()
    slack_self_test()
    extension_self_test()
    count_self_test()


def eligible_orientations(catalog, selected, selected_orientation):
    eligible = []
    for index, base in enumerate(catalog):
        if selected is not None and index not in selected:
            continue
        for orientation, adjacency in (
            ("base", base),
            ("complement", complement_adjacency(base)),
        ):
            if selected_orientation and orientation != selected_orientation:
                continue
            degrees = degree_multiset(adjacency)
            endpoint_lower_bound = sum(
                abs(observed - target)
                for observed, target in zip(degrees, TARGET_DEGREES, strict=True)
            )
            if endpoint_lower_bound % 2:
                raise AssertionError("nonintegral degree edit bound")
            lower_bound = endpoint_lower_bound // 2
            edge_count = sum(degrees) // 2
            edge_difference = TARGET_EDGES - edge_count
            if lower_bound > RADIUS:
                continue
            if abs(edge_difference) > RADIUS:
                continue
            if edge_difference % 2 != RADIUS % 2:
                continue
            eligible.append((index, orientation, edge_count, lower_bound, adjacency))
    return eligible


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--only-parent", type=int, action="append")
    parser.add_argument("--orientation", choices=("base", "complement"))
    parser.add_argument("--shard-count", type=int, default=1)
    parser.add_argument("--shard-index", type=int, default=0)
    parser.add_argument(
        "--candidate-limit",
        type=int,
        help="stop after this many repairs across the selected shard",
    )
    parser.add_argument(
        "--progress-every",
        type=int,
        help="emit a non-certificate progress line after this many candidates",
    )
    parser.add_argument("--stop-on-extension", action="store_true")
    parser.add_argument("--list-eligible", action="store_true")
    parser.add_argument("--count-only", action="store_true")
    args = parser.parse_args()
    if args.shard_count <= 0 or not 0 <= args.shard_index < args.shard_count:
        parser.error("require 0 <= shard-index < shard-count")
    if args.candidate_limit is not None and args.candidate_limit <= 0:
        parser.error("--candidate-limit must be positive")
    if args.progress_every is not None and args.progress_every <= 0:
        parser.error("--progress-every must be positive")

    run_self_tests()
    raw_catalog = CATALOG_PATH.read_bytes()
    if hashlib.sha256(raw_catalog).hexdigest() != CATALOG_SHA256:
        raise AssertionError("known R(5,5;42) catalog digest changed")
    catalog = [
        decode_short_graph6(line) for line in raw_catalog.decode("ascii").splitlines()
    ]
    if len(catalog) != 328:
        raise AssertionError("wrong catalog record count")
    selected = None if args.only_parent is None else set(args.only_parent)
    eligible = eligible_orientations(catalog, selected, args.orientation)
    eligible = [
        row for ordinal, row in enumerate(eligible)
        if ordinal % args.shard_count == args.shard_index
    ]
    if args.list_eligible:
        for index, orientation, edges, lower_bound, _ in eligible:
            print(
                f"parent={index} orientation={orientation} edges={edges} "
                f"degree_lower_bound={lower_bound}"
            )
        print(f"PASS selected_radius7_orientations={len(eligible)}")
        return
    if args.count_only:
        total = 0
        for index, orientation, edges, lower_bound, matrix in eligible:
            count = count_degree_compatible_flip_sets(matrix, 20, 20, RADIUS)
            total += count
            print(
                f"COUNT parent={index} orientation={orientation} edges={edges} "
                f"degree_lower_bound={lower_bound} candidates={count}",
                flush=True,
            )
        print(
            f"PASS counted_radius7_orientations={len(eligible)} "
            f"degree-compatible-candidates={total}"
        )
        return

    total_candidates = total_ramsey = total_extensions = 0
    base_orientation_count = complement_orientation_count = 0
    for index, orientation, edges, lower_bound, matrix in eligible:
        if orientation == "base":
            base_orientation_count += 1
        else:
            complement_orientation_count += 1
        base_bits = bit_adjacency(matrix)
        candidates = ramsey = extensions = 0
        for additions, deletions in degree_compatible_flip_sets(
            matrix, 20, 20, RADIUS
        ):
            candidates += 1
            total_candidates += 1
            if is_ramsey_after_local(
                base_bits, additions, deletions, TARGET_DEGREES
            ):
                ramsey += 1
                total_ramsey += 1
                repaired = apply_repairs(base_bits, additions, deletions)
                if contains_clique(repaired) or contains_clique(
                    complement_bits(repaired)
                ):
                    raise AssertionError("local and global Ramsey checks disagree")
                repaired_g6 = encode_short_graph6(repaired)
                print(
                    f"RAMSEY42 parent={index} orientation={orientation} "
                    f"additions={additions} deletions={deletions} "
                    f"graph6={repaired_g6}",
                    flush=True,
                )
                for z in extension_vertices(repaired):
                    extensions += 1
                    total_extensions += 1
                    extended = validate_extension(repaired, z)
                    print(
                        f"CERTIFIED R55_43 parent={index} "
                        f"orientation={orientation} z={z} "
                        f"graph6={encode_short_graph6(extended)}",
                        flush=True,
                    )
                    if args.stop_on_extension:
                        return
            if (
                args.candidate_limit is not None
                and total_candidates >= args.candidate_limit
            ):
                print(
                    f"PARTIAL candidate_limit={args.candidate_limit} "
                    f"candidates={total_candidates} ramsey42={total_ramsey} "
                    f"extensions={total_extensions}",
                    flush=True,
                )
                return
            if (
                args.progress_every is not None
                and total_candidates % args.progress_every == 0
            ):
                print(
                    f"PROGRESS parent={index} orientation={orientation} "
                    f"total_candidates={total_candidates} "
                    f"ramsey42={total_ramsey} extensions={total_extensions}",
                    flush=True,
                )
        print(
            f"parent={index} orientation={orientation} edges={edges} "
            f"degree_lower_bound={lower_bound} candidates={candidates} "
            f"ramsey42={ramsey} extensions={extensions}",
            flush=True,
        )
    print(
        f"PASS radius-seven orientations={len(eligible)} "
        f"base={base_orientation_count} complement={complement_orientation_count} "
        f"degree-compatible-candidates={total_candidates} "
        f"Ramsey42={total_ramsey} extensions={total_extensions}"
    )


if __name__ == "__main__":
    main()
