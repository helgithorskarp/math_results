def demand(condition, message):
    if not condition:
        raise ValueError(message)


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(',', ':')).encode()


def evaluate(coefficients, value):
    return sum(Q(a) * value ** i for i, a in enumerate(coefficients))


def determinant(matrix):
    n = len(matrix)
    result = Q(0)
    for order in permutations(range(n)):
        inversions = sum(order[i] > order[j] for i in range(n) for j in range(i + 1, n))
        term = Q((-1) ** inversions)
        for i, j in enumerate(order):
            term *= matrix[i][j]
        result += term
    return result


def bernstein_identity(coefficients, bernstein, positive):
    degree = len(coefficients) - 1
    demand(degree >= 0 and len(bernstein) == degree + 1, 'Bernstein length')
    numbers = list(map(Q, bernstein))
    demand(all(x > 0 if positive else x < 0 for x in numbers), 'strict closed-band Bernstein signs')
    # Both sides have degree<=degree; degree+1 distinct evaluations prove identity.
    for j in range(degree + 1):
        x = Q(j, degree + 1)
        value = sum(numbers[i] * comb(degree, i) * x ** i * (1 - x) ** (degree - i)
                    for i in range(degree + 1))
        demand(value == evaluate(coefficients, LOW + (HIGH - LOW) * x), 'Bernstein representation identity')


def intrinsic_at(r):
    def reflected(a, b, old):
        return tuple(r * (a[i] + b[i]) - old[i] for i in range(3))
    left = {1: (Q(1), Q(0), Q(0)), 2: (Q(0), Q(1), Q(0)), 4: (Q(0), Q(0), Q(1))}
    for new, a, b, old in ((10, 1, 2, 4), (8, 2, 4, 1), (13, 2, 8, 4), (12, 1, 10, 2)):
        left[new] = reflected(left[a], left[b], left[old])
    right = {0: (Q(1), Q(0), Q(0)), 5: (Q(0), Q(1), Q(0)), 11: (Q(0), Q(0), Q(1))}
    for new, a, b, old in ((6, 0, 11, 5), (7, 0, 5, 11), (9, 5, 11, 0)):
        right[new] = reflected(right[a], right[b], right[old])
    c = r / (2 - r)
    metric = [[Q(1) if i == j else c for j in range(3)] for i in range(3)]
    def dot(a, b):
        return sum(a[i] * metric[i][j] * b[j] for i in range(3) for j in range(3))
    for points in (left, right):
        for vector in points.values():
            demand(dot(vector, vector) == 1, 'independent exact unit identity')
    dots = {(side, a, b): dot(points[a], points[b])
            for side, points in (('left', left), ('right', right))
            for a, b in combinations(sorted(points), 2)}
    return dots


def audit_gram(data):
    expected_keys = {('left', a, b) for a, b in combinations(L, 2)} | {('right', a, b) for a, b in combinations(R, 2)}
    rows = data['intrinsic_pair_table']
    demand(len(rows) == 36, 'complete 36-pair table')
    indexed = {(row['side'], *row['pair']): row for row in rows}
    demand(set(indexed) == expected_keys, 'all pair keys and uniqueness')
    for (side, a, b), row in indexed.items():
        demand(len(row['numerator']) <= 6 and row['numerator'], 'dot numerator degree<=5')
        contact = (a, b) in (LE if side == 'left' else RE)
        demand(row['contact'] is contact, 'literal contact table')
        if contact:
            demand(row['numerator'] == ['0', '1'], 'contact numerator=r')
        else:
            numerator = list(map(Q, row['numerator']))
            gap = [Q(0)] * max(2, len(numerator))
            gap[1] = 1
            for i, value in enumerate(numerator):
                gap[i] -= value
            while gap and gap[-1] == 0:
                gap.pop()
            bernstein_identity(gap, row['gap_bernstein'], True)
    # Intrinsic numerator degree<=5. These 6 distinct r values prove every identity.
    for j in range(6):
        r = Q(j, 8)
        dots = intrinsic_at(r)
        for key, row in indexed.items():
            demand(evaluate(row['numerator'], r) == (2 - r) * dots[key], 'direct metric dot identity')
    return indexed


def all_aliases():
    for size in range(7):
        for domain in combinations(R, size):
            for image in permutations(L, size):
                yield dict(zip(domain, image))


def locally_possible(alias):
    named = lambda x: alias.get(x, x)
    faces = [tuple(named(x) for x in face) for face in T + (PENT,)]
    if any(len(set(face)) < len(face) for face in faces):
        return False
    if len({tuple(sorted(face)) for face in faces[:9]}) != 9:
        return False
    edges = {tuple(sorted((face[i - 1], face[i]))) for face in faces for i in range(len(face))}
    vertices = sorted({x for edge in edges for x in edge})
    adj = {x: tuple(y for y in vertices if tuple(sorted((x, y))) in edges) for x in vertices}
    if max(map(len, adj.values())) > 5:
        return False
    if max(Counter(x for face in faces[:9] for x in face).values()) >= 5:
        return False
    corners = {x: [] for x in vertices}
    for face in faces:
        for i, x in enumerate(face):
            corners[x].append((face[i - 1], face[(i + 1) % len(face)]))
    for x in vertices:
        if len(set(corners[x])) != len(corners[x]):
            return False
        neighbors = adj[x]
        possible = False
        for suffix in permutations(neighbors[1:]):
            order = (neighbors[0],) + suffix
            successive = {(order[i - 1], order[i]) for i in range(len(order))}
            if set(corners[x]) <= successive:
                possible = True
                break
        if not possible:
            return False
        if len(corners[x]) == len(neighbors) and (x not in faces[-1] or len(neighbors) < 4):
            return False
    inverse = {b: a for a, b in alias.items()}
    for a, b in edges:
        if a in L and b in L and (a, b) not in LE:
            return False
        u, v = sorted((inverse.get(a, a), inverse.get(b, b)))
        if u in R and v in R and (u, v) not in RE:
            return False
    return True


def audit_aliases(data):
    decisions, survivors = [], []
    for alias in all_aliases():
        good = locally_possible(alias)
        key = tuple(alias.get(r, r) for r in R)
        decisions.append((key, good))
        if good:
            survivors.append({str(a): b for a, b in alias.items()})
    total = sum(comb(6, k) * factorial(7) // factorial(7 - k) for k in range(7))
    demand(len(decisions) == len({key for key, _ in decisions}) == total == 37633, 'complete unique independent alias domain')
    survivors.sort(key=lambda row: tuple(row.get(str(r), r) for r in R))
    demand(survivors == data['aliases']['complete_local_survivors'], 'entry-level accepted-map list')
    digest = hashlib.sha256(canonical(sorted(decisions))).hexdigest()
    demand(digest == data['aliases']['all_map_decision_sha256'], 'all 37,633 individual decisions')
    demand(data['aliases']['raw_maps'] == total, 'domain total')
    counters = data['aliases']['rejection_counts']
    demand(all(type(x) is int and x >= 0 for x in counters.values())
           and sum(counters.values()) == total and counters['retained'] == len(survivors), 'producer rejection summary totals')
    demand(data['aliases']['global_embedding_enumeration_used'] is False, 'local proof scope')
    for row in survivors:
        demand(not row or row.get('6') in (4, 8, 13), 'all aliases covered by one of three Gram cases')
    return digest, survivors


def closure_from_projected_grams(P, Qn, U, radius, V, W, Z):
    # Determinants of (a,b,u) and (a,u,v) vanish in the tangent plane.
    f = [Qn, -2 * U * W, P * W * W + radius * U * U - P * Qn * radius]
    g = [radius, -2 * V * Z, radius * Z * Z + P * V * V - P * radius * radius]
    return determinant([[*f, 0], [0, *f], [*g, 0], [0, *g]])


def audit_closures(data):
    cases = data['closure_cases']
    demand([row['alias'] for row in cases] == [[6, 4], [6, 8], [6, 13]], 'all three closure cases, in order')
    degrees = []
    for row in cases:
        reduced = list(map(Q, row['reduced_coefficients']))
        demand(reduced and reduced[-1] != 0 and all(a.denominator == 1 for a in reduced), 'literal integer polynomial')
        bernstein_identity(reduced, row['reduced_bernstein'], False)
        content = row['content']
        demand(type(content) is int and content > 0, 'positive integer factor content')
        roots = []
        for factor in row['linear_factors']:
            root, multiplicity = Q(factor['root']), factor['multiplicity']
            demand(root in (Q(0), Q(1), Q(2), Q(-1)), 'outside factor roots')
            demand(not LOW <= root <= HIGH and type(multiplicity) is int and multiplicity > 0, 'nonzero closed-band factors')
            roots.extend([root] * multiplicity)
        degree = len(reduced) - 1 + len(roots)
        demand(degree == row['closure_degree'] and degree <= 60, 'degree bound for reconstruction')
        degrees.append(degree)
    # Each true numerator determinant has degree<=60 (PROOF.md). Independent
    # evaluation at61 distinct points proves each complete factor identity.
    for j in range(61):
        r, d = Q(j, 64), Q(2) - Q(j, 64)
        dots = intrinsic_at(r)
        k = d * dots['right', 6, 7]
        demand(k == d * dots['right', 6, 9] == d * dots['right', 7, 9], 'right outer Gram identity')
        demand(k == r * (2 * r * r + 2 * r - 3), 'credited right outer formula')
        for row in cases:
            vertex = row['alias'][1]
            a = d * dots['left', *sorted((vertex, 10))]
            b = d * dots['left', *sorted((vertex, 12))]
            P, Qn, U = d * d - a * a, d * d - b * b, r * d - a * b
            radius, V = d * d - k * k, k * d - k * k
            W, Z = r * d - b * k, r * d - a * k
            determinant_value = closure_from_projected_grams(P, Qn, U, radius, V, W, Z)
            reconstruction = Q(row['content']) * evaluate(row['reduced_coefficients'], r)
            for factor in row['linear_factors']:
                reconstruction *= (r - Q(factor['root'])) ** factor['multiplicity']
            demand(determinant_value == reconstruction, '61-point Sylvester/factor interpolation identity')
    return degrees


def planar_controls():
    vectors = [(Q(0), Q(1)), (Q(3, 5), Q(4, 5)), (Q(-5, 13), Q(12, 13)),
               (Q(8, 17), Q(15, 17)), (Q(7, 25), Q(-24, 25))]
    dot = lambda a, b: sum(x * y for x, y in zip(a, b))
    count, degenerate, mutations = 0, 0, 0
    for a, b, u, v in product(vectors, repeat=4):
        P, Qn, U = dot(a, a), dot(b, b), dot(a, b)
        radius, V, W, Z = dot(u, u), dot(u, v), dot(b, u), dot(a, v)
        demand(dot(v, v) == radius, 'equal-radius control')
        demand(closure_from_projected_grams(P, Qn, U, radius, V, W, Z) == 0, 'consistent planar Gram control')
        count += 1
        degenerate += P * Qn == U * U or radius * radius == V * V
        mutations += closure_from_projected_grams(P, Qn, U, radius, V, W + Q(1, 97), Z) != 0
    demand((count, degenerate, mutations) == (625, 225, 625), 'complete planar and damage controls')
    return {'consistent': count, 'degenerate': degenerate, 'altered_cross_dot_rejected': mutations}


