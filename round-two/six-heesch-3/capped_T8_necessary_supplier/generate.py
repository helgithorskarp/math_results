def contains(poly, point):
    return all(check.g.turn(v, poly[(i + 1) % len(poly)], point) >= 0
               for i, v in enumerate(poly))


def strict(poly, point):
    return all(check.g.turn(v, poly[(i + 1) % len(poly)], point) > 0
               for i, v in enumerate(poly))


def clip(poly, other):
    """Closed rational convex clipping; used only to FIND strict witnesses."""
    result = tuple(tuple(Fraction(v) for v in p) for p in poly)
    for i, a in enumerate(other):
        z = other[(i + 1) % len(other)]
        if not result:
            break
        output = []
        previous = result[-1]
        previous_value = check.g.turn(a, z, previous)
        for current in result:
            value = check.g.turn(a, z, current)
            if (previous_value >= 0) != (value >= 0):
                t = previous_value / (previous_value - value)
                output.append(tuple(previous[k] + t * (current[k] - previous[k])
                                    for k in range(2)))
            if value >= 0:
                output.append(current)
            previous, previous_value = current, value
        result = tuple(output)
    return result


def interior_point(candidate, blocker):
    for i, a in enumerate(candidate):
        for j, z in enumerate(blocker):
            if not check.g.boxes_meet(check.g.box(a), check.g.box(z), False):
                continue
            intersection = clip(a, z)
            if len(intersection) < 3 or check.g.twice_area(intersection) <= 0:
                continue
            point = tuple(sum(p[k] for p in intersection) / len(intersection)
                          for k in range(2))
            if strict(a, point) and strict(z, point):
                return i, j, [str(v) for v in point]
    raise ValueError('proposed blocker has no certified positive interior overlap')



