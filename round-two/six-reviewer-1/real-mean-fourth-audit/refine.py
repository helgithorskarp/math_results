"""Fresh fifth-normal budgets and an explicit eta-analytic inward family.

All records are generated by our independent kernel, not author inputs.
"""
from fractions import Fraction as Q
import sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parent))
from field import E,W,need
from intervals import physical_cosine
from check import run,pa,ps,rec,pc,enclosure
import json,hashlib


def decode(poly):return tuple(E(v)for v in poly)


def refine(damage=None):
    baseline=run();unit=run(fifth_center=1);checks=[];cb=physical_cosine()
    def equal(a,b,name):need(a==b,name);checks.append(name)
    for j in range(10):
        b=baseline['primitive_eta0_to5_by_z_power'][j]
        u=unit['primitive_eta0_to5_by_z_power'][j]
        for n in range(5):equal(b[n],u[n],'all lower primitive columns '+str((j,n)))
        change=pa(decode(u[5]),ps(decode(b[5]),-1))
        expected=pc(9)if j==0 else pc(-9)if j==8 else ()
        equal(change,expected,'literal fifth-center primitive '+str(j))
    bounds={};budget=[];root_responses=[]
    for j in range(9):
        z=W**j;A=1-z.real()
        b=baseline['all_nine_original_roots_eta0_to5'][j]
        u=unit['all_nine_original_roots_eta0_to5'][j]
        for n in range(5):equal(b[n],u[n],'all lower original roots '+str((j,n)))
        equal(pa(decode(u[5]),ps(decode(b[5]),-1)),pc(1-z),'whole fifth root response '+str(j))
        b=baseline['all_nine_half_normals_eta0_to5'][j]
        u=unit['all_nine_half_normals_eta0_to5'][j]
        for n in range(5):equal(b[n],u[n],'all lower original normals '+str((j,n)))
        equal(pa(decode(u[5]),ps(decode(b[5]),-1)),pc(-A),'whole fifth normal response '+str(j))
        root_responses.append({'root':(1-z).record(),'normal':(-A).record()})
        if j in [3,4,5,6]:
            coefficients=ps(decode(b[5]),1/A);rows=[]
            for k,v in enumerate(coefficients):
                box=enclosure(v,cb);absolute=max(abs(box.lo),abs(box.hi))
                upper=(absolute.numerator+absolute.denominator-1)//absolute.denominator
                if damage=='underpay' and j==3 and k==0:upper=0
                need(Q(upper)>=absolute,'entire fifth-normal coefficient enclosure '+str((j,k)))
                while len(budget)<=k:budget.append(0)
                budget[k]=max(budget[k],upper)
                rows.append({'field':v.record(),'interval':box.record(),'absolute_integer_upper':upper})
                checks.append('fifth-normal coefficient enclosure '+str((j,k)))
            bounds[str(j)]=rows
    f=baseline['direct_first_power_eta0_to5'];fu=unit['direct_first_power_eta0_to5']
    for n in range(5):equal(f[n],fu[n],'all lower FIRST coefficients '+str(n))
    equal(pa(decode(fu[5]),ps(decode(f[5]),-1)),pc(8),'whole fifth-center FIRST response')
    # For every real R>=0 and |mu|<=R, triangle bounds yield q5/A <= sum U_k R^k.
    tau=list(budget);tau[0]+=1
    if damage=='slack':tau[0]-=2
    need(tau[0]-budget[0]==1 and tau[1:]==budget[1:],'uniform fifth inward surplus one')
    c=__import__('check').constants();mu_star=-Q(3,8)*c['L']
    tau16=sum(a*16**k for k,a in enumerate(tau))
    f5=decode(f[5]);d16=sum((v*mu_star**k for k,v in enumerate(f5)),E(0))+8*tau16
    dbox=enclosure(d16,cb)
    need(Q(-71)<dbox.lo<=dbox.hi<Q(-70),'negative exact fifth coefficient between minus71 and minus70')
    checks.append('negative exact fifth coefficient between minus71 and minus70')
    out={'complete':True,'baseline':baseline,'unit_center':unit,
         'all_nine_fifth_center_responses':root_responses,
         'all_four_active_fifth_normal_budgets':bounds,
         'uniform_budget_integer_coefficients':budget,
         'tau_R_integer_coefficients':tau,
         'tau_16':tau16,'mu_star_first_fifth_coefficient':d16.record(),
         'mu_star_first_fifth_coefficient_interval':dbox.record(),
         'refinement_check_names':checks}
    return out


if __name__=='__main__':
    import argparse
    from pathlib import Path
    p=argparse.ArgumentParser();p.add_argument('--output');p.add_argument('--damage');a=p.parse_args()
    result=refine(a.damage);raw=json.dumps(result,sort_keys=True,separators=(',',':')).encode()
    if a.output:Path(a.output).write_bytes(raw)
    print(json.dumps({'complete':True,'base_checks_each':len(result['baseline']['check_names']),
                     'new_checks':len(result['refinement_check_names']),'tau_R':result['tau_R_integer_coefficients'],
                     'tau_16':result['tau_16'],'whole_bytes':len(raw),'sha256':hashlib.sha256(raw).hexdigest()},sort_keys=True))
