"""Fresh full-cover replay plus exactly integrated clipping: gap2^-17.

The whole coefficient record is regenerated by own check.run, never loaded
from a stored/private record. Current author programs are not inputs.
"""
import argparse
from fractions import Fraction as Q
import hashlib
import json
from math import comb
from pathlib import Path
import sys


def insist(ok,label):
    if not ok:raise ValueError(label)


def main():
    p=argparse.ArgumentParser();p.add_argument('--damage');p.add_argument('--record',type=Path);args=p.parse_args()
    root=Path(__file__).resolve().parent
    seal=json.loads((root/'PRIMARY_SEAL.json').read_text())
    insist(set(seal['files'])=={'check.py','arithmetic.py','literal.py','COVER.json','EXPECTED.json'},
           'complete base five-file seal')
    insist(all(hashlib.sha256((root/n).read_bytes()).hexdigest()==h
               for n,h in seal['files'].items()),'refinement preimport base source pin')
    sys.path.insert(0,str(root))
    from check import run
    from arithmetic import encode,mul,integrate
    from verify import identical
    summary,raw=run(root/'COVER.json')
    insist(identical(encode(summary),json.loads((root/'EXPECTED.json').read_text())),
           'entire regenerated base coefficient record and typed summary')
    records=json.loads(raw)['leaves']
    eps=Q(1,2**16)if args.damage=='gap-overreach'else Q(1,2**17)
    h=Q(27,40);b=Q(5,9);m=Q(40,67)
    # The differentiated slot itself retains r_j>=m along the radial segment.
    mass=(8+eps-m)/7
    def weighted(a,c):
        first=[Q(1)]
        for _ in range(7):first=mul(first,[a,c])
        second=[Q(comb(7,j))*a**(7-j)*c**j for j in range(8)]
        if args.damage=='lost-terminal':first[-1]=Q(0)
        insist(first==second,'all eight exact seven-factor coefficients')
        value=integrate([Q(0)]+first)
        independent=sum((second[j]/(j+2)for j in range(8)),Q(0))
        insist(value==independent,'entire weighted seven-factor integral')
        return first,value
    j_coeff,j_integral=weighted(h,b*mass)
    o_coeff,o_integral=weighted(Q(1),h*mass)
    LJ=b*j_integral;LO=9*h*o_integral
    insist(LJ<Q(3,5)and LO<59,'fresh integrated Lipschitz ceilings')
    ratios=[Q(comb(8,j))/(8*m)**j for j in range(9)]
    A=sum(v*eps**j for j,v in enumerate(ratios))
    insist(A==(1+eps/(8*m))**8,'complete full ratio eighth power')
    loss=A-1+59*eps
    if args.damage=='wrong-product-direction':loss=1-A+59*eps
    insist(loss==sum(ratios[j]*eps**j for j in range(1,9))+59*eps,
           'clipped product ratio loss direction')
    origin=[];product=[];polar=[]
    for row in records:
        status=row['status']
        if status=='polar-excluded':polar.append(1-Q(row['standard']['integral']))
        elif status=='energy-polar-excluded':polar.append(1-Q(row['coupled']['integral_upper']))
        else:
            score=max(Q(v['score'])for v in row['mean'])if 'mean'in row else Q(row['origin']['score'])
            if 'product-origin'in status:product.append(score-Q(row['product']['upper']))
            else:origin.append(score-1)
    insist((len(origin),len(product),len(polar))==(109,28,103),'all defining surplus classes')
    insist(Q(3,5)*eps<min(polar)and loss<min(origin)and loss<min(product),
           'refined gap against every entire defining leaf')
    insist(1-Q(3,5)*eps>Q(49,50),'refined clipped root-entry margin')
    insist(min(origin)>Q(1,2000)and min(product)>Q(1,400)and min(polar)>Q(1,40000),
           'fresh rational lower witnesses for whole leaf surpluses')
    insist(loss<Q(1,2000)and Q(3,5)*eps<Q(1,40000),'refined simple rational gap payments')
    result={'agent':'six-reviewer-1','role':'independent mathematical reviewer','result':'PASS',
            'marked_annulus':['2/3','27/40'],'actual_gap':eps,'gap_factor_over_target':256,
            'remaining_seven_mean_upper':mass,'J_coefficients':j_coeff,'O_coefficients':o_coeff,
            'J_exact_Lipschitz':LJ,'O_exact_Lipschitz':LO,'J_ceiling':Q(3,5),'O_ceiling':59,
            'all9_ratio_coefficients':ratios,'ratio_upper':A,'origin_loss_upper':loss,
            'all109_origin_surpluses':origin,'all28_product_surpluses':product,
            'all103_polar_surpluses':polar,
            'least_origin_surplus':min(origin),'least_product_surplus':min(product),
            'least_polar_surplus':min(polar),'base_record_bytes':len(raw),
            'base_record_sha256':hashlib.sha256(raw).hexdigest(),
            'trusted_analytic_boundary':'Ordinary written channel, clipping and Banach bridges; unformalized.'}
    # Full lists are generated privately; public stdout is compact, while checks
    # above compare every leaf and complete coefficient/integral before extrema.
    compact={k:v for k,v in result.items()if not k.startswith('all109_')and
             not k.startswith('all28_')and not k.startswith('all103_')}
    full=json.dumps(encode(result),sort_keys=True,separators=(',',':')).encode()
    if args.record:args.record.write_bytes(full)
    compact['refinement_record_bytes']=len(full)
    compact['refinement_record_sha256']=hashlib.sha256(full).hexdigest()
    print(json.dumps(encode(compact),sort_keys=True,indent=2))


if __name__=='__main__':main()
