"""Independent exact integer binomial proof on separate cube coefficients.

Input polynomials are regenerated by this reviewer's definition-level Gram
and exterior determinant. No researcher executable or expected record input.
Each raw Q coefficient is shifted separately, without a dense5-variable
load-shift expansion. Integer dictionaries implement all binomial transforms.
"""
from fractions import Fraction
from math import comb,lcm
from hashlib import sha256
import json

TERM_GUARD=30000


def require(ok,label):
    if not ok:raise ValueError(label)


def canonical(p,den=1):
    return {'den':den,'terms':[(list(k),str(v)) for k,v in sorted(p.items())]}


def digest(p,den=1):
    return sha256(json.dumps(canonical(p,den),separators=(',',':')).encode()).hexdigest()


def decode(terms):
    d=1;source={}
    for exps,c in terms:
        exps=tuple(exps);value=Fraction(c)
        require(len(exps)==5 and all(type(e)is int and e>=0 for e in exps),'whole polynomial exponent domain')
        require(exps not in source and value,'unique nonzero polynomial terms')
        source[exps]=value;d=lcm(d,value.denominator)
    p={e:int(v*d) for e,v in source.items()}
    require(len(p)<=TERM_GUARD,'fixed raw polynomial term guard')
    return p,d


def add(p,e,v):
    out=p.get(e,0)+v
    if out:p[e]=out
    else:p.pop(e,None)


def shear(p,variable,other,scale):
    """Replace x_variable by x_variable+scale*x_other, in4 variables."""
    out={}
    for exps,c in p.items():
        exponent=exps[variable]
        for retained in range(exponent+1):
            e=list(exps);e[variable]=retained;e[other]+=exponent-retained
            add(out,tuple(e),c*comb(exponent,retained)*scale**(exponent-retained))
    require(len(out)<=TERM_GUARD,'fixed sheared polynomial term guard')
    return out


def translate(p,variable,offset=1):
    """Replace one variable by itself+1, using exact binomial coefficients."""
    out={}
    for exps,c in p.items():
        exponent=exps[variable]
        for retained in range(exponent+1):
            e=list(exps);e[variable]=retained
            add(out,tuple(e),c*comb(exponent,retained)*offset**(exponent-retained))
    require(len(out)<=TERM_GUARD,'fixed translated polynomial term guard')
    return out


def shift(p):
    # Original coordinate order(t,D,a,u) becomes(T,B,V,U):
    # a=V+2D,u=U+t,D=B+t, thenB+=1,t+=1.
    p=shear(p,2,1,2)
    p=shear(p,3,0,1)
    p=shear(p,1,0,1)
    p=translate(p,1)
    return translate(p,0)


def unshift(p):
    p=translate(p,0,-1)
    p=translate(p,1,-1)
    p=shear(p,1,0,-1)
    p=shear(p,3,0,-1)
    return shear(p,2,1,-2)


def prove(terms,label):
    p,d=decode(terms);groups={}
    for exps,c in p.items():groups.setdefault(exps[0],{})[exps[1:]]=c
    records=[]
    for degree,coefficient in sorted(groups.items()):
        shifted=shift(coefficient)
        require(unshift(shifted)==coefficient,'WHOLE inverse binomial shift identity: '+label+'/'+str(degree))
        require(shifted and all(v>=0 for v in shifted.values()),'ALL shifted coefficients nonnegative: '+label+'/'+str(degree))
        records.append({'Q_degree':degree,'raw_terms':len(coefficient),
                        'shifted_terms':len(shifted),'shifted_degree':max(sum(e) for e in shifted),
                        'minimum_coefficient':str(min(shifted.values())),
                        'origin_constant':str(shifted.get((0,0,0,0),0)),
                        'whole_coefficients_sha256':digest(shifted,d),'whole_inverse_shift_exact':True})
    require(groups and 0 in groups,'Q0 coefficient present')
    constant=shift(groups[0]).get((0,0,0,0),0)
    require(constant>0,'strict full-origin polynomial positivity: '+label)
    return {'raw_terms':len(p),'raw_common_denominator':d,'raw_polynomial_sha256':digest(p,d),
            'Q_degree':max(groups),'coefficient_lemmas':records,
            'shifted_terms':sum(r['shifted_terms'] for r in records),
            'largest_shifted_polynomial':max(r['shifted_terms'] for r in records),
            'strict_origin_constant':str(constant)}


def run(functions):
    return {label:{side:prove(value[side],label+'/'+side) for side in ('numerator','denominator')} for label,value in functions.items()}
