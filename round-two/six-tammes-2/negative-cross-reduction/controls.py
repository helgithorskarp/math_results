"""Seven damaged root/coverage certificates and direct arithmetic controls.

These audit root/pole metadata and a small generated exclusion trace. They
do not claim a separate derivation of the geometric factorization.
"""
from fractions import Fraction as Q
from pathlib import Path
import argparse,copy,json
import audit,intervals as e,packing
HERE=Path(__file__).resolve().parent
def require(ok,message):
 if not ok:raise ValueError(message)
def rejected(function,data,label):
 try:function(data)
 except (ValueError,ArithmeticError,KeyError,IndexError):return label
 raise ValueError('damaged certificate accepted: '+label)
def run(trace):
 data=json.loads((HERE/'certificate.json').read_text())
 audit.verify(data);packing.replay(1,trace)
 results=[]
 bad=copy.deepcopy(data);bad['loci']['-1']['factors'][0]['real_roots_at_lo']=1
 results.append(rejected(audit.verify,bad,'false real-root count'))
 bad=copy.deepcopy(data);bad['loci']['-1']['factors'][0]['discriminant_locus'][0]['factors'][0]['coefficients']=[0]
 results.append(rejected(audit.verify,bad,'zero exceptional-locus factor'))
 bad=copy.deepcopy(data);bad['loci']['-1']['factors'].pop()
 results.append(rejected(audit.verify,bad,'omitted orientation factor'))
 bad=copy.deepcopy(data);bad['interval']=['14/25','3/5']
 results.append(rejected(audit.verify,bad,'false closed domain'))
 bad=copy.deepcopy(trace);bad[0][3]=bad[0][2]
 results.append(rejected(lambda v:packing.replay(1,v),bad,'lost root bracket'))
 bad=copy.deepcopy(trace);bad.pop()
 results.append(rejected(lambda v:packing.replay(1,v),bad,'missing final parameter piece'))
 bad=copy.deepcopy(trace);bad[0][4]=str(-Q(bad[0][4]))
 results.append(rejected(lambda v:packing.replay(1,v),bad,'false packing-gap bound'))
 for x,y,lo,hi in [(e.I(-2,3),e.I(-3,5),Q(-10),Q(15))]:
  a,b=(x*y).fractions();require(a<=lo and b>=hi,'multiplication outward at all endpoint extrema')
 a,b=(e.I(-2,3)/e.I(7,9)).fractions()
 require(a<=Q(-2,7) and b>=Q(3,7),'division outward with signed numerator')
 for c in [Q(1,3),Q(-1,3),Q(7,11),Q(-23,17)]:
  a,b=e.I(c).fractions();require(a<=c<=b,'signed rational-to-dyadic outward conversion')
 for p,n in [([1,0,0,0,1],0),([-1,0,0,0,1],2),([4,0,-5,0,1],4),([0,-1,0,1],3),([0,1],1)]:
  require(audit.real_roots(p)==n,'known exact real-root control')
 return {'status':'CONTROLS_PASSED','damaged_certificates_rejected':results,
         'arithmetic_endpoint_controls_passed':True,'known_real_root_counts':5}
if __name__=='__main__':
 p=argparse.ArgumentParser(description=__doc__)
 p.add_argument('--trace',type=Path,required=True,help='local trace generated by packing.py --branch 1')
 args=p.parse_args();print(json.dumps(run(json.loads(args.trace.read_text())),sort_keys=True))
