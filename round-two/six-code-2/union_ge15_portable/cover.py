"""Source-only positive point cover. six-code-2, researcher.

Enumerates the subgroup generated by four supplied actual permutations;
its size is checked as output, never assumed to be the full automorphism
order. Only representative coordinates and the literal design are inputs.
An independent point-set/domain algorithm audits the generated packet.
"""
import argparse
from collections import deque
import hashlib
import json
from pathlib import Path
import resource
import time
from physical_helpers import encoded, operations_guard, require


def main():
    parser = argparse.ArgumentParser()
    for name in ('parent', 'spec', 'work'):
        parser.add_argument('--' + name, type=Path, required=True)
    args = parser.parse_args()
    require(not args.work.exists(), 'new source-only cover directory required')
    args.work.mkdir(parents=True)
    start, states = time.monotonic(), 0

    def guard():
        operations_guard()
        require(time.monotonic() - start < 60 and states <= 2_000_000,
                'INCOMPLETE original60s/two-million positive point-cover states')

    raw = args.parent.read_bytes()
    spec = json.loads(args.spec.read_bytes())
    require(hashlib.sha256(raw).hexdigest() == spec['literal_parent_sha256'],
            'exact source-only literalD input')
    words = tuple(sorted(json.loads(raw)['words']))
    require(len(words) == len(set(words)) == 68 and
            all(type(w) is int and 0 <= w < 1 << 17 and w.bit_count() == 5 for w in words),
            'encoded literalD word domain')
    lookup = {w: i for i, w in enumerate(words)}
    point_lists = [tuple(v for v in range(17) if w >> v & 1) for w in words]

    def induced(permutation):
        require(len(permutation) == 18 and all(type(v) is int for v in permutation) and
                sorted(permutation) == list(range(18)) and permutation[17] == 17,
                'encoded actual y-fixed bijection')
        images = [sum(1 << permutation[v] for v in ps) for ps in point_lists]
        require(set(images) == set(words), 'encoded whole literalD image')
        return tuple(lookup[w] for w in images)

    generators = tuple(tuple(p) for p in spec['point_generators'])
    for g in generators:
        induced(g)
    identity = tuple(range(18))
    maps, seen, queue = [identity], {identity}, deque([identity])
    while queue:
        permutation = queue.popleft()
        for g in generators:
            states += 1
            new = tuple(g[permutation[v]] for v in range(18))
            if new not in seen:
                seen.add(new)
                maps.append(new)
                queue.append(new)
        if states % 1024 == 0:
            guard()
    require(len(maps) == spec['expected_generated_actual_maps'], 'generated actual-map count differs')
    actions = []
    for p in maps:
        states += 1
        actions.append(induced(p))
        if states % 1024 == 0:
            guard()
    all_targets, cases = set(), []
    for case in spec['cases']:
        canonical = tuple(lookup[w] for w in case['hole_words'])
        targets = {}
        for map_id, action in enumerate(actions):
            states += 1
            target = tuple(sorted(action[i] for i in canonical))
            targets.setdefault(target, map_id)
            if states % 1024 == 0:
                guard()
        require(len(targets) == case['targets'], 'positive representative target count differs')
        require(not all_targets & set(targets), 'positive representative images overlap')
        all_targets.update(targets)
        cases.append({'component': case['component'], 'hole_words': case['hole_words'],
                      'union_points': case['union_points'],
                      'targets': [list(target) + [targets[target]] for target in sorted(targets)]})
    require(len(all_targets) == spec['physical_targets'], 'positive whole target count differs')
    guard()
    packet = {'agent': 'six-code-2', 'role': 'researcher',
              'status': 'COMPLETE_POSITIVE_ACTUAL_POINT_MAPS_NO_PACKING_ABSENCE',
              'parent_sha256': hashlib.sha256(raw).hexdigest(),
              'parent_words': words, 'point_maps': maps, 'cases': cases,
              'generated_map_count': len(maps), 'target_count': len(all_targets),
              'full_automorphism_order_assumed': False, 'minimal_orbits_assumed': False}
    b = encoded(packet)
    (args.work / 'COVER.json').write_bytes(b)
    result = {'agent': 'six-code-2', 'role': 'researcher', 'status': packet['status'],
              'cases': len(cases), 'maps': len(maps), 'targets': len(all_targets),
              'states': states, 'cover_sha256': hashlib.sha256(b).hexdigest(), 'cover_bytes': len(b),
              'original_seconds': 60, 'original_states': 2000000}
    (args.work / 'EXACT_RESULT.json').write_bytes(encoded(result))
    execution = {'seconds': time.monotonic() - start,
                 'peak_RSS_kib': resource.getrusage(resource.RUSAGE_SELF).ru_maxrss}
    (args.work / 'EXECUTION.json').write_bytes(encoded(execution))
    print(json.dumps(result | execution, sort_keys=True))


if __name__ == '__main__':
    main()
