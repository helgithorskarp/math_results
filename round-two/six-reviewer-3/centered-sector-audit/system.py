"""Independent literal critical products, anchored primitives and circle rows."""
from fractions import Fraction as F
from exact_numbers import convolution,power,evaluate,chebyshev
from third import T


def anchored_integral(derivative_poly,a):
    p=[T(0)]+[x/F(i+1) for i,x in enumerate(derivative_poly)]
    p[0]-=evaluate(p,a)
    return p


def circle(p,t):
    ts=chebyshev([0,1]);us=chebyshev([0,2])
    real=sum((a*evaluate(ts[j],t) for j,a in enumerate(p)),T(0))
    imag=sum((p[j]*evaluate(us[j-1],t) for j in range(1,len(p))),T(0))
    return imag,real


def system(eta,v,c):
    x,y,opening,xi3,xi4,omega=v;r=eta*x;s=eta*y;a=1-eta
    small=power([-r,T(1)],6);heavy=[s*s+eta*opening,-2*s,T(1)]
    # The primitive is independently generated by integrating the literal
    # derivative factor product, rather than using the author's Q template.
    p=anchored_integral([9*t for t in convolution(small,heavy)],a)
    divided_split=anchored_integral([-9*t for t in convolution(power([-r,T(1)],4),heavy)],a)
    phases=[T(-F(1,2))+eta*xi3,T(-c)+eta*xi4]
    unit=[circle(p,t) for t in phases];force=[circle(divided_split,t) for t in phases]
    W=1+eta*omega;distance=1-eta*(1+y);A=1-eta*(1+x)
    G=[unit[0][0],unit[1][0],unit[0][1],unit[1][1],W*W-distance*distance-eta*opening]
    U=[force[0][0],force[1][0],force[0][1],force[1][1],T(0)]
    return G,U,{'poly':p,'divided_split':divided_split,'A':A,'W':W,'phases':phases}
