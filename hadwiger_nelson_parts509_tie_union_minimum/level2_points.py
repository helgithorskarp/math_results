#!/usr/bin/env python3
"""Exact level-2 completion points around a pool P of Q3 points (tie-union points).

base = V ∪ P (V = Parts-509 vertices, P = pool points given by ambient index 509+q).
A level-2 point is a point of the plane, not in V ∪ Q3(G), at unit distance from >= 3 points of base.
Because every such point has >= 3 unit neighbours in base ⊂ K², it is the circumcentre of three of
them and lies in K² (K = Q(√3,√5,√11)); and since it is not in V ∪ Q3(G) ∪ Q2(G)-with-3-nbrs... more
precisely: a point with >= 3 neighbours in base that has >= 3 neighbours in V alone is in Q3(G) and is
excluded; every remaining level-2 point has a neighbour a ∈ P, hence is generated by the pair (a, b) for
each of its other neighbours b.  We therefore enumerate the K-rational intersections of the unit circles
around a ∈ P and b ∈ base \ {a}: rho² = (4 − d²)/(4 d²) must be a square in K (exact recursive test).
The neighbour set within base of a generated point is exactly the union of its generating pairs (every
neighbour b pairs with a).  An independent exact rescan of every level-2 point against all of base checks
this.  Finally the new unit-distance edges P2–Q3(G) and P2–P2 are found by a float screen (|d²−1| < 1e-6,
far above the double-precision error for these bounded coordinates) followed by exact confirmation.

Output: level2_points.json with exact coordinates, neighbour lists (ambient indices), and the new edges;
ambient indices of level-2 points are 1667 + position.
"""
import os, json, sys, time, importlib.util
from fractions import Fraction
from pathlib import Path
from multiprocessing import Pool
HN = Path(os.environ.get('HN_SCRATCH', '/scratch/agents/researcher-4/hn'))
sys.path.insert(0, str(HN))
import kfield as kf
BASE = Path('/home/helgithorskarp_gmail_com/math_results/hadwiger_nelson_parts509_criticality')
K = 3
FOUR = kf.const(K, 4); HALF = Fraction(1, 2); ONE = kf.one(K)
N = 509; NQ3 = 1158; AMB = N + NQ3

spec = importlib.util.spec_from_file_location('parts509', BASE / 'parts509.py')
parts = importlib.util.module_from_spec(spec); spec.loader.exec_module(parts)
V = parts.parse_points(BASE / 'parts509.vtx')
comp = json.loads((HN / 'completion_points.json').read_text())
Q3 = [(kf.from_strings(r['x']), kf.from_strings(r['y'])) for r in comp['points']]
ALL = V + Q3                      # ambient index -> exact point
KEY = {p: i for i, p in enumerate(ALL)}
assert len(KEY) == AMB


def d2(p, q):
    dx = kf.sub(p[0], q[0]); dy = kf.sub(p[1], q[1])
    return kf.add(kf.mul(dx, dx, K), kf.mul(dy, dy, K))


def intersections(a, b):
    """K-rational intersection points of the unit circles around a and b (exact), or []."""
    dd = d2(a, b)
    if kf.is_zero(dd):
        return []
    rho2 = kf.mul(kf.sub(FOUR, dd), kf.inv(kf.scale(dd, 4), K), K)
    r = kf.field_sqrt(rho2, K)
    if r is None:
        return []
    dx = kf.sub(a[0], b[0]); dy = kf.sub(a[1], b[1])
    mx = kf.scale(kf.add(a[0], b[0]), HALF); my = kf.scale(kf.add(a[1], b[1]), HALF)
    rwx = kf.mul(r, kf.neg(dy), K); rwy = kf.mul(r, dx, K)
    return [(kf.add(mx, kf.scale(rwx, s)), kf.add(my, kf.scale(rwy, s))) for s in (1, -1)]


def gen_row(args):
    ai, base_idx = args
    a = ALL[ai]
    out = {}
    for bi in base_idx:
        if bi == ai:
            continue
        for q in intersections(a, ALL[bi]):
            out.setdefault(q, set()).update((ai, bi))
    return ai, out


def rescan(args):
    q, base_idx = args
    return sorted(bi for bi in base_idx if d2(q, ALL[bi]) == ONE)


def exact_unit(args):
    q, others = args
    return [j for j, p in others if d2(q, p) == ONE]


def main():
    union = json.loads(Path(sys.argv[1]).read_text())
    tag = sys.argv[2]
    P = sorted(union['added_points'])
    base_idx = list(range(N)) + P
    t0 = time.time()
    print(f'pool P: {len(P)} points; base = V ∪ P: {len(base_idx)} points', flush=True)
    merged = {}
    with Pool(3) as pool:
        for ai, out in pool.imap_unordered(gen_row, [(ai, base_idx) for ai in P]):
            for q, gens in out.items():
                merged.setdefault(q, set()).update(gens)
    print(f'K-rational circle intersections: {len(merged)} distinct points ({time.time()-t0:.0f}s)', flush=True)
    # sanity: every pool point a is generated by exactly its base neighbourhood... (a itself is on the circles of its neighbours only if generated by pairs (a', b) with a' another pool point) -- skip; check V/Q3 points recovered consistently
    known = {q: gens for q, gens in merged.items() if q in KEY}
    new = {q: gens for q, gens in merged.items() if q not in KEY}
    lvl2 = [(q, sorted(gens)) for q, gens in new.items() if len(gens) >= 3]
    hist = {}
    for q, gens in new.items():
        hist[len(gens)] = hist.get(len(gens), 0) + 1
    print(f'known points regenerated: {len(known)}; new points: {len(new)} with neighbour histogram {dict(sorted(hist.items()))}; level-2 (>=3 nbrs): {len(lvl2)} ({time.time()-t0:.0f}s)', flush=True)
    # independent exact rescan
    with Pool(3) as pool:
        scans = pool.map(rescan, [(q, base_idx) for q, _ in lvl2], chunksize=16)
    mism = sum(1 for (q, gens), sc in zip(lvl2, scans) if sc != gens)
    print(f'exact rescan mismatches: {mism} ({time.time()-t0:.0f}s)', flush=True)
    assert mism == 0
    # consistency check on regenerated known points: their generated neighbour sets must be subsets of true neighbourhoods (checked exactly)
    bad = 0
    for q, gens in list(known.items())[:2000]:
        for bi in gens:
            if bi != KEY[q] and d2(q, ALL[bi]) != ONE:
                bad += 1
    print(f'known-point generator consistency (2000 sampled): bad={bad}', flush=True)
    assert bad == 0
    lvl2.sort(key=lambda t: (-len(t[1]), kf.to_float(t[0][0]), kf.to_float(t[0][1])))
    pts = [q for q, _ in lvl2]
    # new edges: P2 - Q3 and P2 - P2 via float screen + exact confirmation
    import numpy as np
    fl = np.array([[kf.to_float(q[0]), kf.to_float(q[1])] for q in pts])
    q3f = np.array([[kf.to_float(q[0]), kf.to_float(q[1])] for q in Q3])
    cand_pq = []
    for i in range(len(pts)):
        dd = ((q3f - fl[i]) ** 2).sum(axis=1)
        js = np.nonzero(np.abs(dd - 1) < 1e-6)[0]
        if len(js):
            cand_pq.append((i, [(N + int(j), Q3[int(j)]) for j in js]))
    cand_pp = []
    for i in range(len(pts)):
        dd = ((fl[i + 1:] - fl[i]) ** 2).sum(axis=1)
        js = np.nonzero(np.abs(dd - 1) < 1e-6)[0]
        if len(js):
            cand_pp.append((i, [(AMB + i + 1 + int(j), pts[i + 1 + int(j)]) for j in js]))
    with Pool(3) as pool:
        r_pq = pool.map(exact_unit, [(pts[i], others) for i, others in cand_pq], chunksize=16)
        r_pp = pool.map(exact_unit, [(pts[i], others) for i, others in cand_pp], chunksize=16)
    edges_pq = sorted((AMB + i, j) for (i, _), js in zip(cand_pq, r_pq) for j in js)
    edges_pp = sorted((AMB + i, j) for (i, _), js in zip(cand_pp, r_pp) for j in js)
    n_cand = sum(len(o) for _, o in cand_pq) + sum(len(o) for _, o in cand_pp)
    print(f'float candidates {n_cand}; exact new edges: P2-Q3 {len(edges_pq)}, P2-P2 {len(edges_pp)} ({time.time()-t0:.0f}s)', flush=True)
    records = []
    for i, (q, gens) in enumerate(lvl2):
        records.append({'index': AMB + i, 'x': kf.to_strings(q[0]), 'y': kf.to_strings(q[1]),
                        'x_float': kf.to_float(q[0]), 'y_float': kf.to_float(q[1]),
                        'nbrs_base': gens, 'nbrs_P': [g for g in gens if g >= N]})
    deg = {}
    for r in records:
        # degree in V ∪ Q3 ∪ P2 = base nbrs (V and P) + other Q3 nbrs + P2 nbrs
        deg[r['index']] = len(r['nbrs_base'])
    for a, b in edges_pq:
        deg[a] += 1
    for a, b in edges_pp:
        deg[a] += 1; deg[b] += 1
    out = {'pool': P, 'union_file': sys.argv[1], 'level2_count': len(records), 'points': records,
           'edges_P2_Q3': edges_pq, 'edges_P2_P2': edges_pp,
           'note': 'ambient indices: V 0..508, Q3 509..1666 (completion_points order), level-2 points 1667.. in this order; nbrs_base lists V and pool neighbours (exact, rescanned); edges_P2_Q3 / edges_P2_P2 exact (float screen tol 1e-6 then exact confirmation)'}
    (HN / 'level2' / f'level2_{tag}.json').write_text(json.dumps(out))
    dh = {}
    for v in deg.values():
        dh[v] = dh.get(v, 0) + 1
    print(f'level-2 degree histogram within V ∪ Q3 ∪ P2: {dict(sorted(dh.items()))}; wrote level2_{tag}.json ({time.time()-t0:.0f}s)', flush=True)


if __name__ == '__main__':
    main()
