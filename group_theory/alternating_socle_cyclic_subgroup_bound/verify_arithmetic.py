#!/usr/bin/env python3
"""Exact audit for the alternating-socle cyclic-subgroup bound.

This script is not part of the universal proof.  It checks the finite table,
the analytic inequalities on a configurable finite range, and independently
enumerates all cyclic subgroups of A_5 from the permutation definition.
"""

from __future__ import annotations

import argparse
import math
from itertools import permutations


Permutation = tuple[int, ...]


def is_prime(value: int) -> bool:
    if value < 2:
        return False
    if value % 2 == 0:
        return value == 2
    divisor = 3
    while divisor * divisor <= value:
        if value % divisor == 0:
            return False
        divisor += 2
    return True


def prime_tables(limit: int) -> tuple[list[bool], list[int], list[int]]:
    """Return a sieve, prefix prime counts, and largest-prime prefixes."""
    sieve = [True] * (limit + 1)
    if limit >= 0:
        sieve[0] = False
    if limit >= 1:
        sieve[1] = False
    for prime in range(2, math.isqrt(limit) + 1):
        if sieve[prime]:
            start = prime * prime
            sieve[start : limit + 1 : prime] = [False] * (
                (limit - start) // prime + 1
            )

    counts: list[int] = []
    largest: list[int] = []
    count = 0
    last = 0
    for value, prime in enumerate(sieve):
        if prime:
            count += 1
            last = value
        counts.append(count)
        largest.append(last)
    return sieve, counts, largest


def single_prime_cycle_subgroups(n: int, prime: int) -> int:
    """Number of order-prime subgroups generated by one prime-cycle."""
    if not (3 <= prime <= n and is_prime(prime)):
        raise ValueError("prime must be an odd prime at most n")
    return math.comb(n, prime) * math.factorial(prime - 2)


def compose(left: Permutation, right: Permutation) -> Permutation:
    """Return left after right, with permutations represented by images."""
    return tuple(left[right[index]] for index in range(len(left)))


def inverse_count(permutation: Permutation) -> int:
    return sum(
        permutation[left] > permutation[right]
        for left in range(len(permutation))
        for right in range(left + 1, len(permutation))
    )


def cyclic_subgroup(generator: Permutation) -> frozenset[Permutation]:
    identity = tuple(range(len(generator)))
    members = {identity}
    current = generator
    while current != identity:
        if current in members:
            raise AssertionError("permutation powers repeated before identity")
        members.add(current)
        current = compose(generator, current)
    return frozenset(members)


def count_a5_cyclic_subgroups() -> int:
    even_permutations = (
        permutation
        for permutation in permutations(range(5))
        if inverse_count(permutation) % 2 == 0
    )
    subgroups = {cyclic_subgroup(permutation) for permutation in even_permutations}
    return len(subgroups)


BOUNDARY = (
    (6, 5, 36, 32),
    (7, 7, 120, 64),
    (8, 7, 960, 64),
    (9, 7, 4_320, 64),
    (10, 7, 14_400, 64),
    (11, 11, 362_880, 128),
    (12, 11, 4_354_560, 128),
    (13, 13, 39_916_800, 256),
    (14, 13, 558_835_200, 256),
    (15, 13, 4_191_264_000, 256),
)


def verify(limit: int) -> None:
    if limit < 16:
        raise ValueError("limit must be at least 16")

    a5_count = count_a5_cyclic_subgroups()
    assert a5_count == 32
    prime_sieve, prime_counts, largest_primes = prime_tables(limit)

    for n, prime, expected_count, expected_threshold in BOUNDARY:
        count = single_prime_cycle_subgroups(n, prime)
        threshold = 1 << (prime_counts[n] + 2)
        assert count == expected_count
        assert threshold == expected_threshold
        assert count > threshold

    equality_cases: list[int] = []
    for n in range(5, limit + 1):
        threshold = 1 << (prime_counts[n] + 2)
        if n == 5:
            lower_bound = a5_count
        else:
            prime = largest_primes[n]
            lower_bound = single_prime_cycle_subgroups(n, prime)
        assert lower_bound >= threshold
        if lower_bound == threshold:
            equality_cases.append(n)

    factorial_index = 7
    factorial_bound = math.factorial(factorial_index)
    for n in range(16, limit + 1):
        target_index = n // 2 - 1
        while factorial_index < target_index:
            factorial_index += 1
            factorial_bound *= factorial_index
        coarse_threshold = 1 << ((n + 1) // 2 + 2)
        assert factorial_bound >= coarse_threshold

        m = n // 2
        assert any(prime_sieve[prime] for prime in range(m + 1, 2 * m))

    assert equality_cases == [5]

    print(f"independent_A5_cyclic_subgroups={a5_count}")
    print(f"boundary_rows_checked={len(BOUNDARY)}")
    print(f"arithmetic_range_checked=5..{limit}")
    print(f"analytic_range_checked=16..{limit}")
    print("equality_cases_in_arithmetic_range=5")
    print("VERIFIED")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--limit", type=int, default=10_000)
    return parser.parse_args()


if __name__ == "__main__":
    arguments = parse_args()
    verify(arguments.limit)
