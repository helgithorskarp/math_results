#!/usr/bin/env python3
"""Literal, exact finite controls for the central prime-boundary lemma.

This is author-side supporting computation, not an independent internal
check and not an enumeration of all group extensions. Standard library;
one process; no floating point enters any mathematical comparison.
"""

from __future__ import annotations

import argparse
from collections import Counter
from fractions import Fraction
from itertools import permutations, product
import json
from math import prod
from pathlib import Path


def require(condition: bool, message: str) -> None:
    if not condition:
        raise RuntimeError(message)


def compose(x: tuple[int, ...], y: tuple[int, ...]) -> tuple[int, ...]:
    return tuple(x[y[i]] for i in range(5))


def even(x: tuple[int, ...]) -> bool:
    return sum(x[i] > x[j] for i in range(5) for j in range(i + 1, 5)) % 2 == 0


def phi(n: int) -> int:
    result, residue, divisor = n, n, 2
    while divisor * divisor <= residue:
        if residue % divisor == 0:
            result -= result // divisor
            while residue % divisor == 0:
                residue //= divisor
        divisor += 1
    if residue > 1:
        result -= result // residue
    return result


def omega(n: int) -> int:
    count, divisor = 0, 2
    while divisor * divisor <= n:
        if n % divisor == 0:
            count += 1
            while n % divisor == 0:
                n //= divisor
        divisor += 1
    return count + (n > 1)


class Model:
    def __init__(self) -> None:
        self.perms = tuple(x for x in permutations(range(5)) if even(x))
        self.index = {x: i for i, x in enumerate(self.perms)}
        self.identity = self.index[tuple(range(5))]
        self.mul = tuple(
            tuple(self.index[compose(x, y)] for y in self.perms)
            for x in self.perms
        )
        self.inv = tuple(
            next(j for j in range(60) if self.mul[i][j] == self.identity)
            for i in range(60)
        )
        require(len(self.perms) == 60, "A5 permutation model has wrong size")

    def structural_controls(self) -> dict:
        center = [
            x for x in range(60)
            if all(self.mul[x][y] == self.mul[y][x] for y in range(60))
        ]
        commutators = {
            self.mul[self.mul[self.mul[x][y]][self.inv[x]]][self.inv[y]]
            for x in range(60) for y in range(60)
        }
        closure, frontier = {self.identity}, [self.identity]
        while frontier:
            x = frontier.pop()
            for y in commutators:
                z = self.mul[x][y]
                if z not in closure:
                    closure.add(z)
                    frontier.append(z)
        require(center == [self.identity], "Concrete A5 center is not trivial")
        require(len(closure) == 60, "Concrete A5 is not perfect")
        return {"order": 60, "center_size": len(center),
                "derived_subgroup_size": len(closure)}

    def fixture(self, name: str, moduli: tuple[int, ...],
                expected_count: int, expected_eta: int,
                coset_coordinates: tuple[tuple[int, ...], ...] = ()) -> dict:
        coordinates = tuple(product(*(range(m) for m in moduli)))
        coordinate_index = {x: i for i, x in enumerate(coordinates)}
        abelian_order = prod(moduli)
        zero = tuple(0 for _ in moduli)
        identity_id = self.identity * abelian_order + coordinate_index[zero]
        group_order = 60 * abelian_order
        require(group_order <= 20580, "Fixture exceeds documented finite scope")
        subgroups: set[frozenset[int]] = set()
        order_histogram: Counter[int] = Counter()
        sampled_orders: dict[tuple[int, ...], int] = {}

        # Every subgroup is generated by some element; powers are literal
        # group elements, with no product-count or lcm formula used here.
        for generator_perm in range(60):
            for generator_coordinates in coordinates:
                perm_id, current_coordinates = self.identity, zero
                members = {identity_id}
                while True:
                    perm_id = self.mul[perm_id][generator_perm]
                    current_coordinates = tuple(
                        (x + y) % m for x, y, m in
                        zip(current_coordinates, generator_coordinates, moduli)
                    )
                    element_id = perm_id * abelian_order + coordinate_index[current_coordinates]
                    if element_id == identity_id:
                        break
                    require(element_id not in members, "Power loop repeated before identity")
                    members.add(element_id)
                    require(len(members) <= group_order, "Power loop did not terminate")
                element_order = len(members)
                order_histogram[element_order] += 1
                subgroups.add(frozenset(members))
                if generator_perm == self.identity and generator_coordinates in coset_coordinates:
                    sampled_orders[generator_coordinates] = element_order

        require(sum(order_histogram.values()) == group_order, "Wrong element census")
        weight_sum = sum(
            (Fraction(number, phi(order)) for order, number in order_histogram.items()),
            Fraction(0),
        )
        count = len(subgroups)
        eta = Fraction(count, 2 ** omega(group_order))
        require(weight_sum == count, "Literal subgroup count and exact weight sum disagree")
        require(count == expected_count, f"Unexpected count for {name}: {count}")
        require(eta == expected_eta, f"Unexpected eta for {name}: {eta}")
        require(len(sampled_orders) == len(coset_coordinates), "Incomplete sampled lift coset")
        return {
            "name": name, "moduli": list(moduli), "order": group_order,
            "cyclic_subgroups": count, "generator_weight_sum": str(weight_sum),
            "omega": omega(group_order), "eta": str(eta),
            "element_order_histogram": dict(sorted(order_histogram.items())),
            "quotient_generator_coset_orders": [sampled_orders[x] for x in coset_coordinates],
        }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    model = Model()
    controls = model.structural_controls()
    specifications = [
        ("A5", (), 32, 4, ()),
        ("A5 x C7", (7,), 64, 4, ()),
        ("A5 x C49", (49,), 96, 6, tuple((1 + 7*k,) for k in range(7))),
        ("A5 x C7 x C7", (7, 7), 288, 18, tuple((1, k) for k in range(7))),
        ("A5 x C77", (77,), 128, 4, ()),
        ("A5 x C343", (343,), 128, 8, ()),
        ("A5 x C49 x C7", (49, 7), 512, 32, ()),
    ]
    fixtures = [model.fixture(*specification) for specification in specifications]
    require(fixtures[2]["quotient_generator_coset_orders"] == [49] * 7,
            "C49 extension should have seven order-49 lifts of an order-7 generator")
    require(fixtures[3]["quotient_generator_coset_orders"] == [7] * 7,
            "C7 x C7 extension should have seven order-7 lifts")
    result = {
        "status": "all exact finite controls passed",
        "scope": "supporting fixtures only; uniform proof and independent internal check separate",
        "a5_structural_controls": controls,
        "fixtures": fixtures,
    }
    output = json.dumps(result, indent=2, sort_keys=True) + "\n"
    if args.output:
        args.output.write_text(output, encoding="utf-8")
    else:
        print(output, end="")


if __name__ == "__main__":
    main()
