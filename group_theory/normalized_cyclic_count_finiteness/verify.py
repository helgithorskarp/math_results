import json
from collections import Counter
from fractions import Fraction
from itertools import permutations, product
from math import gcd, prod
from pathlib import Path


def require(condition, message):
    if not condition:
        raise ValueError(message)


def factor(n):
    require(n >= 1, "factor requires a positive integer")
    result, p = {}, 2
    while p * p <= n:
        while n % p == 0:
            result[p] = result.get(p, 0) + 1
            n //= p
        p += 1
    if n > 1:
        result[n] = result.get(n, 0) + 1
    return result


def phi(n):
    return prod((p - 1) * p ** (a - 1) for p, a in factor(n).items())


def omega(n):
    return len(factor(n))


def digest(data):
    raw = json.dumps(data, sort_keys=True, separators=(",", ":")).encode()
    return hashlib.sha256(raw).hexdigest()


class Group:
    def __init__(self, label, elements, identity, multiply):
        self.label = label
        self.elements = list(elements)
        index = {x: i for i, x in enumerate(self.elements)}
        self.n = len(self.elements)
        require(len(index) == self.n, "duplicate elements")
        self.one = index[identity]
        self.table = [[index[multiply(x, y)] for y in self.elements]
                      for x in self.elements]
        n, one, t = self.n, self.one, self.table
        self.inverse = []
        for x in range(n):
            require(t[x][one] == x == t[one][x], "identity law")
            inverses = [y for y in range(n) if t[x][y] == one == t[y][x]]
            require(len(inverses) == 1, "inverse law")
            self.inverse.append(inverses[0])
        # Exhaustive associativity for small fixtures; larger fixtures are
        # cyclic, permutation, matrix, or verified semidirect constructions.
        if n <= 32:
            for x, y, z in product(range(n), repeat=3):
                require(t[t[x][y]][z] == t[x][t[y][z]], "associativity")
        self.cyclic, self.orders = set(), []
        generators = Counter()
        for x in range(n):
            powers, y = {one}, x
            while y != one:
                require(y not in powers, "power walk repeated before identity")
                powers.add(y)
                y = t[y][x]
            subgroup = frozenset(powers)
            self.cyclic.add(subgroup)
            self.orders.append(len(subgroup))
            generators[subgroup] += 1
        for subgroup, count in generators.items():
            require(count == phi(len(subgroup)), "generator multiplicity")
        self.c = len(self.cyclic)
        require(sum(Fraction(1, phi(e)) for e in self.orders) == self.c,
                "literal cyclic sets disagree with element formula")
        self.eta = Fraction(self.c, 2 ** omega(n))

    def generated(self, seeds):
        t = self.table
        gens = list(seeds)
        result, todo = {self.one}, [self.one]
        while todo:
            x = todo.pop()
            for g in gens:
                y = t[x][g]
                if y not in result:
                    result.add(y)
                    todo.append(y)
        return frozenset(result)

    def normal_subgroups(self):
        """Complete enumeration for this fixture by joins of normal closures.

        Each normal subgroup is generated by the conjugacy classes of its
        elements. Products of normal subgroups are their joins.
        """
        t, n = self.table, self.n
        conjugacy_classes = {frozenset(t[t[x][g]][self.inverse[x]]
                                      for x in range(n)) for g in range(n)}
        closures = {self.generated(c) for c in conjugacy_classes}
        first = frozenset({self.one})
        found, todo = {first}, [first]
        while todo:
            a = todo.pop()
            for b in closures:
                joined = frozenset(t[x][y] for x in a for y in b)
                if joined not in found:
                    found.add(joined)
                    todo.append(joined)
        for a in found:
            require(all(t[t[x][g]][self.inverse[x]] in a
                        for g in a for x in range(n)), "normality")
            require(self.generated(a) == a, "subgroup closure")
        return sorted(found, key=lambda a: (len(a), tuple(sorted(a))))

    def quotient(self, normal):
        t = self.table
        cosets = sorted({frozenset(t[x][v] for v in normal)
                         for x in range(self.n)}, key=lambda a: min(a))
        lookup = {x: i for i, c in enumerate(cosets) for x in c}
        require(len(lookup) == self.n, "coset partition")
        reps = [min(c) for c in cosets]
        return Group("quotient", range(len(cosets)), lookup[self.one],
                     lambda i, j: lookup[t[reps[i]][reps[j]]])


def cyclic(n):
    return Group(f"C{n}", range(n), 0, lambda a, b: (a + b) % n)


def perm_group(n, even=False):
    elements = [x for x in permutations(range(n))
                if not even or sum(x[i] > x[j] for i in range(n)
                                   for j in range(i + 1, n)) % 2 == 0]
    return Group(("A" if even else "S") + str(n), elements, tuple(range(n)),
                 lambda a, b: tuple(a[b[i]] for i in range(n)))


def direct(a, b):
    return Group(a.label + "x" + b.label, product(range(a.n), range(b.n)),
                 (a.one, b.one), lambda x, y:
                 (a.table[x[0]][y[0]], b.table[x[1]][y[1]]))


def quaternion(m):
    # Q_(4m): x^(2m)=1, y^2=x^m, y*x*y^-1=x^-1.
    return Group(f"Q{4*m}", product(range(2 * m), range(2)), (0, 0),
                 lambda a, b: ((a[0] + (-1) ** a[1] * b[0]
                                 + m * a[1] * b[1]) % (2 * m),
                                (a[1] + b[1]) % 2))


def scalar_extension(m, h, actions):
    require(gcd(m, h.n) == 1, "extension requires coprime orders")
    require(len(actions) == h.n, "missing scalar actions")
    require(actions[h.one] == 1, "identity scalar")
    for i, j in product(range(h.n), repeat=2):
        require(gcd(actions[i], m) == 1, "nonunit scalar")
        require(actions[h.table[i][j]] == actions[i] * actions[j] % m,
                "scalar action is not a homomorphism")
    return Group(f"C{m}:({h.label};{','.join(map(str, actions))})",
                 product(range(m), range(h.n)), (0, h.one), lambda x, y:
                 ((x[0] + actions[x[1]] * y[0]) % m,
                  h.table[x[1]][y[1]]))


def linear_extension(q, d, matrix):
    ident = tuple(int(i == j) for i in range(d) for j in range(d))

    def matmul(a, b):
        return tuple(sum(a[i*d+k] * b[k*d+j] for k in range(d)) % q
                     for i in range(d) for j in range(d))

    powers, x = [ident], matrix
    while x != ident:
        require(x not in powers, "matrix power failed")
        powers.append(x)
        x = matmul(x, matrix)
    n = len(powers)
    require(gcd(q, n) == 1, "matrix complement is not coprime")

    def action(a, v):
        return tuple(sum(a[i*d+j] * v[j] for j in range(d)) % q
                     for i in range(d))

    def multiply(x, y):
        w = action(powers[x[1]], y[0])
        return tuple((v + z) % q for v, z in zip(x[0], w)), (x[1]+y[1]) % n

    g = Group(f"F{q}^{d}:C{n}", product(product(range(q), repeat=d), range(n)),
              ((0,) * d, 0), multiply)
    cv = 1 + (q ** d - 1) // (q - 1)
    for h in range(n):
        e = n // gcd(n, h)
        vectors = list(product(range(q), repeat=d))
        fixed = sum(action(powers[h], v) == v for v in vectors)
        actual = Counter(g.orders[i] for i, (_, k) in enumerate(g.elements)
                         if h == k)
        predicted = Counter({e: q ** d // fixed})
        if q ** d != q ** d // fixed:
            predicted[q * e] = q ** d - q ** d // fixed
        require(actual == predicted, "linear coset orders")
        require(sum(Fraction(count, phi(order)) for order, count in actual.items())
                >= Fraction(cv, phi(e)), "linear coset lower bound")
    return g


def bounds(k):
    require(k >= 1, "K must be at least one")
    primes = [p for p in range(2, int(4*k-2) + 1) if factor(p) == {p: 1}]
    allowed, rows = set(primes), []
    for q in range(2, int(2*k-2) + 1):
        if factor(q) != {q: 1}:
            continue
        i = 2
        while q * (i - 1) <= 2*k - 2:
            n = q ** i - 1
            factors = factor(n)
            require(prod(p ** a for p, a in factors.items()) == n,
                    "factorization product")
            allowed.update(factors)
            rows.append([q, i, n, sorted(factors.items())])
            i += 1
    return {"K": str(k), "B": max(allowed), "A": int(2*k-1),
            "exceptional_primes": sorted(allowed), "power_rows": rows}


def run():
    s3, s4, a4 = perm_group(3), perm_group(4), perm_group(4, True)
    c2, c3, c5 = cyclic(2), cyclic(3), cyclic(5)
    q8 = quaternion(2)
    fixtures = [cyclic(n) for n in [1, 4, 8, 9, 12, 30, 60, 289]]
    fixtures += [direct(c2, c2), direct(direct(c2, c2), c2),
                 direct(c3, c3), direct(cyclic(9), c3),
                 q8, quaternion(4), s3, s4, a4,
                 direct(s3, c5), direct(a4, c5), direct(q8, c3),
                 direct(a4, cyclic(17)), direct(s3, cyclic(19))]
    fixtures += [linear_extension(2, 2, (0, 1, 1, 1)),
                 linear_extension(2, 3, (0, 0, 1, 1, 0, 1, 0, 1, 0)),
                 linear_extension(3, 2, (0, 2, 1, 0)),
                 linear_extension(5, 2, (0, 4, 1, 4))]
    fixtures += [scalar_extension(13, c2, [1, 12]),
                 scalar_extension(17, c2, [1, 16])]
    normal_records, group_records = [], []
    for g in fixtures:
        normals = g.normal_subgroups()
        for l in normals:
            cl = sum(u <= l for u in g.cyclic)
            q = g.quotient(l)
            require(q.eta <= g.eta, f"quotient eta: {g.label}")
            if len(l) != g.n:
                require(g.c - cl >= Fraction(2 ** omega(g.n), 2),
                        f"relative deficit: {g.label}")
            fs = factor(len(l))
            if len(fs) == 1:
                p, d = next(iter(fs.items()))
                if (d >= 2 and all(g.orders[x] in (1, p) for x in l)
                        and all(g.table[x][y] == g.table[y][x]
                                for x in l for y in l)):
                    require(g.eta >= Fraction(p * (d-1) + 2, 2),
                            "elementary abelian rank constraint")
            normal_records.append([g.label, sorted(l), cl, q.n, q.c])
        central = frozenset({g.one})
        bound = bounds(g.eta)
        for p, a in factor(g.n).items():
            cyclic_sylows = [u for u in g.cyclic if len(u) == p ** a]
            is_central = (len(cyclic_sylows) == 1 and
                          all(g.table[x][y] == g.table[y][x]
                              for x in cyclic_sylows[0] for y in range(g.n)))
            require(p <= bound["B"] or is_central, "large-prime conclusion")
            if is_central:
                central = frozenset(g.table[x][y]
                                    for x in central for y in cyclic_sylows[0])
        core = g.quotient(central)
        require(all(p <= bound["B"] and a <= bound["A"]
                    for p, a in factor(core.n).items()), "core order bound")
        delta = prod(Fraction(a+1, 2) for a in factor(len(central)).values())
        require(core.eta * delta == g.eta, "core factor multiplicativity")
        group_records.append([g.label, g.n, g.c, str(g.eta), len(normals),
                              core.n, len(central)])

    extension_records = []
    for p, a in [(3, 1), (3, 2), (3, 3), (5, 1), (5, 2),
                 (7, 1), (7, 2), (11, 1), (13, 1), (2, 1), (2, 3)]:
        m = p ** a
        for b in range(1, 9):
            if gcd(m, b) != 1:
                continue
            h = cyclic(b)
            for u in range(1, m):
                if gcd(u, m) != 1 or pow(u, b, m) != 1:
                    continue
                actions = [pow(u, i, m) for i in range(b)]
                g = scalar_extension(m, h, actions)
                l = {i for i in range(b) if actions[i] == 1}
                cl = sum(c <= l for c in h.cyclic)
                predicted = (a+1)*h.c + (m-a-1)*(h.c-cl)
                require(g.c == predicted, "normal cyclic Sylow formula")
                if len(l) < b:
                    require(g.eta >= Fraction(m+a+1, 4), "Sylow penalty")
                extension_records.append([p, a, h.label, u, g.n, g.c, cl])

    # Nonabelian complements with nonfaithful scalar actions.
    for h in [s3, q8, s4]:
        kernels = [l for l in h.normal_subgroups() if len(l)*2 == h.n]
        for l in kernels:
            for p in [5, 7]:
                if h.n % p == 0:
                    continue
                actions = [1 if i in l else p-1 for i in range(h.n)]
                g = scalar_extension(p, h, actions)
                cl = sum(c <= l for c in h.cyclic)
                require(g.c == 2*h.c + (p-2)*(h.c-cl),
                        "nonabelian complement formula")
                require(g.eta >= Fraction(p+2, 4), "nonabelian penalty")
                extension_records.append([p, 1, h.label, sorted(l), g.n, g.c, cl])

    # Formula hypotheses must be enforced, including in optimized Python.
    rejected = []
    for label, call in [
        ("noncoprime", lambda: scalar_extension(9, c3, [1, 4, 7])),
        ("invalid_action", lambda: scalar_extension(5, c2, [1, 2])),
        ("invalid_K", lambda: bounds(Fraction(1, 2))),
    ]:
        try:
            call()
        except ValueError:
            rejected.append(label)
        else:
            raise ValueError("negative control accepted: " + label)

    bound_records = [bounds(k) for k in [Fraction(1), Fraction(5, 4),
                                       Fraction(2), Fraction(4), Fraction(59, 8)]]
    require(bound_records[-2]["B"] == 13, "cyclic threshold prime ceiling")
    require(bound_records[-1]["B"] == 127, "subgroup threshold prime ceiling")
    d26 = fixtures[-2]
    require(d26.c == 15 and d26.eta == Fraction(15, 4), "sharp D26 witness")
    require(fixtures[-1].eta == Fraction(19, 4), "D34 outside-threshold control")
    require(all(g.table[x][y] == g.table[y][x] for g in fixtures[:7]
                for x in range(g.n) for y in range(g.n)), "cyclic fixtures")
    return {"scope": "finite controls; universal proof in PROOF.md",
            "fixture_count": len(fixtures), "fixtures": group_records,
            "normal_pair_count": len(normal_records),
            "normal_pair_digest": digest(normal_records),
            "scalar_extension_count": len(extension_records),
            "scalar_extension_digest": digest(extension_records),
            "bounds": bound_records, "rejected_inputs": rejected}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--expect", type=Path)
    args = parser.parse_args()
    result = run()
    # JSON round trip normalizes tuples exactly as in the compact fixture file.
    result = json.loads(json.dumps(result))
    if args.expect:
        require(result == json.loads(args.expect.read_text()),
                "output differs from expected evidence")
    print(json.dumps(result, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
