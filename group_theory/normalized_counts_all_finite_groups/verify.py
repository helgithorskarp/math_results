#!/usr/bin/env python3
"""Exact finite controls for PROOF.md, using only Python's standard library.

This is not an all-groups census or a proof of the three imported theorems.
Explicit checks remain enabled under python -O.
"""

import argparse
import hashlib
import json
from collections import Counter
from fractions import Fraction
from itertools import permutations, product
from math import ceil, gcd, prod
from pathlib import Path


def require(condition, message):
    if not condition:
        raise ValueError(message)


def factor(n):
    require(isinstance(n, int) and n >= 1, "positive integer required")
    result, p = {}, 2
    while p * p <= n:
        while n % p == 0:
            result[p] = result.get(p, 0) + 1
            n //= p
        p += 1
    if n > 1:
        result[n] = result.get(n, 0) + 1
    return result


def omega(n):
    return len(factor(n))


def phi(n):
    return prod((p - 1) * p ** (a - 1) for p, a in factor(n).items())


def digest(data):
    return hashlib.sha256(json.dumps(
        data, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


GAMMA = Fraction(16**6, 30030)


def bounds(k):
    require(isinstance(k, (int, Fraction)), "K must be an exact rational")
    k = Fraction(k)
    require(k >= 1, "K must be at least one")
    d = ceil(GAMMA * k**4)
    e = int(2*k) ** int(k)
    t = ceil(4*d*(k-1) + 2)
    return {"K": str(k), "D": d, "A": int(2*k-1),
            "E": e, "T_ceiling": t, "B": max(d, e, t)}


class Group:
    """A finite group given by a reproducible concrete multiplication law."""

    def __init__(self, label, elements, identity, multiply):
        self.label = label
        self.elements = list(elements)
        index = {x: i for i, x in enumerate(self.elements)}
        self.n = len(self.elements)
        require(len(index) == self.n, "duplicate elements")
        self.one = index[identity]
        self.table = [[index[multiply(x, y)] for y in self.elements]
                      for x in self.elements]
        n, one, t = self.n, self.one, self.table
        self.inverse = []
        for x in range(n):
            require(t[x][one] == x == t[one][x], "identity law")
            inverses = [y for y in range(n) if t[x][y] == one == t[y][x]]
            require(len(inverses) == 1, "inverse law")
            self.inverse.append(inverses[0])
        # For larger fixtures, associativity follows from their explicit
        # permutation, matrix, direct-product, or validated semidirect laws.
        if n <= 32:
            for x, y, z in product(range(n), repeat=3):
                require(t[t[x][y]][z] == t[x][t[y][z]], "associativity")
        self.cyclic, self.orders = set(), []
        generators = Counter()
        for x in range(n):
            powers, y = {one}, x
            while y != one:
                require(y not in powers, "power walk repeated")
                powers.add(y)
                y = t[y][x]
            subgroup = frozenset(powers)
            self.cyclic.add(subgroup)
            self.orders.append(len(subgroup))
            generators[subgroup] += 1
        for subgroup, count in generators.items():
            require(count == phi(len(subgroup)), "generator multiplicity")
        self.c = len(self.cyclic)
        require(sum(Fraction(1, phi(e)) for e in self.orders) == self.c,
                "literal cyclic sets disagree with element-order sum")
        self.eta = Fraction(self.c, 2**omega(n))
        self._normals = None
        self._solvable = {}

    def generated(self, seeds):
        t, gens = self.table, list(seeds)
        result, todo = {self.one}, [self.one]
        while todo:
            x = todo.pop()
            for g in gens:
                y = t[x][g]
                if y not in result:
                    result.add(y)
                    todo.append(y)
        return frozenset(result)

    def normal_subgroups(self):
        """Enumerate all normal subgroups by joins of normal closures.

        A normal subgroup is generated by the conjugacy classes it contains;
        the product of two normal subgroups is their join.
        """
        if self._normals is not None:
            return self._normals
        t, n = self.table, self.n
        classes = {frozenset(t[t[x][g]][self.inverse[x]]
                             for x in range(n)) for g in range(n)}
        closures = {self.generated(c) for c in classes}
        first = frozenset({self.one})
        found, todo = {first}, [first]
        while todo:
            a = todo.pop()
            for b in closures:
                joined = frozenset(t[x][y] for x in a for y in b)
                if joined not in found:
                    found.add(joined)
                    todo.append(joined)
        for a in found:
            require(all(t[t[x][g]][self.inverse[x]] in a
                        for g in a for x in range(n)), "normality")
            require(self.generated(a) == a, "subgroup closure")
        self._normals = sorted(found, key=lambda a: (len(a), tuple(sorted(a))))
        return self._normals

    def solvable(self, subgroup):
        subgroup = frozenset(subgroup)
        if subgroup in self._solvable:
            return self._solvable[subgroup]
        t, inv, h = self.table, self.inverse, subgroup
        while len(h) > 1:
            commutators = {t[t[t[inv[x]][inv[y]]][x]][y] for x in h for y in h}
            derived = self.generated(commutators)
            require(derived <= h, "derived subgroup escaped")
            if derived == h:
                self._solvable[subgroup] = False
                return False
            h = derived
        self._solvable[subgroup] = True
        return True

    def radical(self):
        solvables = [h for h in self.normal_subgroups() if self.solvable(h)]
        r = max(solvables, key=len)
        require(all(h <= r for h in solvables), "solvable radical maximum")
        return r

    def quotient(self, normal):
        require(normal in self.normal_subgroups(), "quotient kernel not normal")
        t = self.table
        cosets = sorted({frozenset(t[x][v] for v in normal)
                         for x in range(self.n)}, key=lambda a: min(a))
        lookup = {x: i for i, c in enumerate(cosets) for x in c}
        require(len(lookup) == self.n, "coset partition")
        reps = [min(c) for c in cosets]
        q = Group("quotient", range(len(cosets)), lookup[self.one],
                  lambda i, j: lookup[t[reps[i]][reps[j]]])
        q.projection = lookup
        return q

    def cyclic_count_in(self, subgroup):
        return sum(c <= subgroup for c in self.cyclic)


def cyclic(n):
    return Group(f"C{n}", range(n), 0, lambda a, b: (a+b) % n)


def perm_group(n, even=False):
    elements = [x for x in permutations(range(n))
                if not even or parity(x) == 0]
    return Group(("A" if even else "S") + str(n), elements, tuple(range(n)),
                 lambda a, b: tuple(a[b[i]] for i in range(n)))


def parity(x):
    return sum(x[i] > x[j] for i in range(len(x))
               for j in range(i+1, len(x))) % 2


def direct(a, b):
    return Group(a.label + "x" + b.label, product(range(a.n), range(b.n)),
                 (a.one, b.one), lambda x, y:
                 (a.table[x[0]][y[0]], b.table[x[1]][y[1]]))


def sl2_5():
    elements = [a for a in product(range(5), repeat=4)
                if (a[0]*a[3]-a[1]*a[2]) % 5 == 1]
    return Group("SL2(5)", elements, (1, 0, 0, 1), lambda a, b:
                 ((a[0]*b[0]+a[1]*b[2]) % 5,
                  (a[0]*b[1]+a[1]*b[3]) % 5,
                  (a[2]*b[0]+a[3]*b[2]) % 5,
                  (a[2]*b[1]+a[3]*b[3]) % 5))


def gl3_2():
    def determinant(a):
        return (a[0]*(a[4]*a[8]-a[5]*a[7])
                - a[1]*(a[3]*a[8]-a[5]*a[6])
                + a[2]*(a[3]*a[7]-a[4]*a[6])) % 2
    elements = [a for a in product(range(2), repeat=9) if determinant(a)]
    return Group("GL3(2)", elements, (1, 0, 0, 0, 1, 0, 0, 0, 1),
                 lambda a, b: tuple(
                     sum(a[3*i+k]*b[3*k+j] for k in range(3)) % 2
                     for i in range(3) for j in range(3)))


def scalar_extension(m, h, actions):
    require(gcd(m, h.n) == 1, "extension requires coprime orders")
    require(len(actions) == h.n and actions[h.one] == 1, "invalid actions")
    for i, j in product(range(h.n), repeat=2):
        require(gcd(actions[i], m) == 1, "nonunit scalar")
        require(actions[h.table[i][j]] == actions[i]*actions[j] % m,
                "scalar action is not a homomorphism")
    return Group(f"C{m}:{h.label}", product(range(m), range(h.n)),
                 (0, h.one), lambda x, y:
                 ((x[0]+actions[x[1]]*y[0]) % m, h.table[x[1]][y[1]]))


def affine_a5(a5):
    """Even-weight vectors in F2^5, with the coordinate action of A5."""
    vectors = [v for v in range(32) if v.bit_count() % 2 == 0]
    actions = [{v: sum(((v >> i) & 1) << h[i] for i in range(5))
                for v in vectors} for h in a5.elements]
    for i, j, v in product(range(a5.n), range(a5.n), vectors):
        require(actions[a5.table[i][j]][v] == actions[i][actions[j][v]],
                "permutation module action")
    return Group("F2^4:A5", product(vectors, range(a5.n)), (0, a5.one),
                 lambda x, y: (x[0] ^ actions[x[1]][y[0]],
                               a5.table[x[1]][y[1]]))


def scalar_prime_power_control(p, a, h):
    """Literal powers for a prime-power kernel with the S5 sign action."""
    m = p**a
    require(factor(p) == {p: 1} and a >= 1 and gcd(m, h.n) == 1,
            "prime-power control hypotheses")
    actions = [1 if parity(x) == 0 else m-1 for x in h.elements]
    for i, j in product(range(h.n), repeat=2):
        require(actions[h.table[i][j]] == actions[i]*actions[j] % m,
                "prime-power scalar action")
    one, cyclic_sets, orders = (0, h.one), set(), []
    for x in product(range(m), range(h.n)):
        seen, y = {one}, x
        while y != one:
            require(y not in seen, "prime-power power walk")
            seen.add(y)
            y = ((y[0]+actions[y[1]]*x[0]) % m, h.table[y[1]][x[1]])
        cyclic_sets.add(frozenset(seen))
        orders.append(len(seen))
    count = len(cyclic_sets)
    require(sum(Fraction(1, phi(o)) for o in orders) == count,
            "prime-power element-order sum")
    l = {i for i in range(h.n) if actions[i] == 1}
    cl = h.cyclic_count_in(l)
    require(count == (a+1)*h.c + (m-a-1)*(h.c-cl), "prime-power identity")
    k = Fraction(count, 2**omega(m*h.n))
    d = bounds(k)["D"]
    require(k >= Fraction(a+1, 2) + Fraction(m-a-1, 4*d),
            "prime-power Sylow penalty")
    return {"group": f"C{m}:S5(sign)", "order": m*h.n,
            "cyclic_count": count, "eta": str(k),
            "centralizer_count": cl,
            "order_histogram": sorted(Counter(orders).items())}


def product_cyclic_control(a, b):
    """Literal cyclic sets in a product, without a quadratic product table.

    Also works for noncoprime orders. No multiplicativity assumption is used.
    """
    one = (a.one, b.one)
    cyclic_sets, orders = set(), []
    for x in product(range(a.n), range(b.n)):
        seen, y = {one}, x
        while y != one:
            require(y not in seen, "product power walk")
            seen.add(y)
            y = (a.table[y[0]][x[0]], b.table[y[1]][x[1]])
        cyclic_sets.add(frozenset(seen))
        orders.append(len(seen))
    count = len(cyclic_sets)
    require(sum(Fraction(1, phi(o)) for o in orders) == count,
            "product cyclic count")
    return {"group": a.label+"x"+b.label, "order": a.n*b.n,
            "cyclic_count": count,
            "eta": str(Fraction(count, 2**omega(a.n*b.n))),
            "order_histogram": sorted(Counter(orders).items())}


def arithmetic_controls():
    primes = (2, 3, 5, 7, 11, 13)
    require(GAMMA == prod(Fraction(16, p) for p in primes), "gamma")
    # All integers in this range, and the squarefree equality witness.
    for n in range(1, 10001):
        require(Fraction(16**omega(n), n) <= GAMMA, "arithmetic inequality")
    require(Fraction(16**omega(30030), 30030) == GAMMA, "gamma sharp witness")
    thresholds = [Fraction(1), Fraction(5, 4), Fraction(2),
                  Fraction(4), Fraction(59, 8), Fraction(8)]
    rows = [bounds(k) for k in thresholds]
    rank_cases = []
    for k in thresholds:
        e = bounds(k)["E"]
        for q in range(2, int(2*k-2)+1):
            if factor(q) != {q: 1}:
                continue
            for d in range(2, int(k)+1):
                if q*(d-1) <= 2*k-2:
                    require(q**d - 1 < e, "GL prime ceiling")
                    rank_cases.append([str(k), q, d, q**d-1, e])
    return rows, {"integer_range": [1, 10000], "equality_integer": 30030,
                  "rank_case_count": len(rank_cases),
                  "rank_case_digest": digest(rank_cases)}


def run():
    a5, s5 = perm_group(5, True), perm_group(5)
    c2, c7 = cyclic(2), cyclic(7)
    sign7 = [1 if parity(x) == 0 else 6 for x in s5.elements]
    twist = scalar_extension(7, s5, sign7)
    # label, concrete group, independently specified radical order, cyclic count
    fixtures = [
        ("trivial", cyclic(1), 1, 1),
        ("S3", perm_group(3), 6, 5),
        ("A4", perm_group(4, True), 12, 8),
        ("A5", a5, 1, 32),
        ("S5", s5, 1, 67),
        ("SL2(5)", sl2_5(), 2, 49),
        ("GL3(2)", gl3_2(), 1, 79),
        ("A5xC2", direct(a5, c2), 2, 64),
        ("A5xC7", direct(a5, c7), 7, 64),
        ("S5xC2", direct(s5, c2), 2, None),
        ("C7:S5(sign)", twist, 7, 309),
        ("F2^4:A5", affine_a5(a5), 16, None),
    ]
    records, relatives, quotients, triples, lucchini = [], [], [], [], []
    nonsolvable_normal_pairs = 0
    for label, g, radical_order, expected_c in fixtures:
        normals = g.normal_subgroups()
        radical = g.radical()
        require(len(radical) == radical_order, "radical fixture: "+label)
        if expected_c is not None:
            require(g.c == expected_c, "cyclic fixture: "+label)
        q = g.quotient(radical)
        require(len(q.radical()) == 1, "quotient radical")
        require(q.eta <= g.eta, "radical quotient monotonicity")
        require(q.n <= GAMMA * g.eta**4, "quartic radical-index bound")
        # Exercise the exact imported inequality for every cyclic subgroup of Q.
        for h in sorted(q.cyclic, key=lambda z: (len(z), sorted(z))):
            centralizer = [x for x in range(q.n)
                           if all(q.table[x][y] == q.table[y][x] for y in h)]
            require(len(h)*len(centralizer) <= q.n, "Lucchini cyclic measure")
            lucchini.append([label, sorted(h), len(centralizer)])
        require(max(q.orders)**2 <= q.n, "radical-free maximum order")
        require(q.c**2 >= q.n, "radical-free cyclic count")
        r_index = g.n // len(radical)
        lower = Fraction(1, 2**(omega(r_index)+1))
        for l in normals:
            cl = g.cyclic_count_in(l)
            if len(l) < g.n:
                delta = Fraction(g.c-cl, 2**omega(g.n))
                require(delta >= lower, "arbitrary relative bound")
                require(lower >= Fraction(1, 2*r_index), "coarse relative bound")
                nonsolvable = not g.solvable(l)
                nonsolvable_normal_pairs += nonsolvable
                relatives.append([label, sorted(l), cl, str(delta),
                                  str(lower), nonsolvable])
        for n in normals:
            if not g.solvable(n):
                continue
            u = g.quotient(n)
            require(g.eta >= u.eta, "solvable-kernel quotient monotonicity")
            quotients.append([label, sorted(n), u.n, u.c, str(u.eta)])
            for l in normals:
                if len(l) == g.n or not n <= l:
                    continue
                j = {u.projection[x] for x in l}
                cl, cj = g.cyclic_count_in(l), u.cyclic_count_in(j)
                before = Fraction(g.c-cl, 2**omega(g.n))
                after = Fraction(u.c-cj, 2**omega(u.n))
                require(before >= after, "relative solvable-kernel monotonicity")
                triples.append([label, sorted(n), sorted(l),
                                str(before), str(after)])
        # The coarse final core theorem, including central factor removal.
        b = bounds(g.eta)
        central = frozenset({g.one})
        for p, a in factor(g.n).items():
            sylows = [h for h in g.cyclic if len(h) == p**a]
            is_central = len(sylows) == 1 and all(
                g.table[x][y] == g.table[y][x]
                for x in sylows[0] for y in range(g.n))
            require(p <= b["B"] or is_central, "large-prime conclusion")
            require(a <= b["A"], "prime exponent bound")
            if is_central:
                central = frozenset(g.table[x][y]
                                    for x in central for y in sylows[0])
        core = g.quotient(central)
        delta = prod(Fraction(a+1, 2) for a in factor(len(central)).values())
        require(core.eta * delta == g.eta, "central cyclic core normalization")
        records.append({"group": label, "order": g.n, "cyclic_count": g.c,
                        "eta": str(g.eta), "radical_order": len(radical),
                        "radical_quotient_cyclic_count": q.c,
                        "normal_subgroups": len(normals),
                        "central_cyclic_factor_order": len(central),
                        "core_order": core.n,
                        "order_histogram": sorted(Counter(g.orders).items())})

    # A nonsolvable centralizer kernel: C7:S5 with sign action has L=A5.
    l = {i for i, x in enumerate(s5.elements) if parity(x) == 0}
    require(not s5.solvable(l), "centralizer is nonsolvable")
    cl = s5.cyclic_count_in(l)
    require(cl == 32 and twist.c == 2*s5.c + (7-2)*(s5.c-cl),
            "cyclic Sylow identity with nonsolvable centralizer")
    k, d = twist.eta, bounds(twist.eta)["D"]
    require(k >= 1 + Fraction(7-2, 4*d), "general Sylow penalty")

    # Larger prime-power kernels and a semisimple direct product are checked
    # by literal powers without allocating their full multiplication tables.
    products = [product_cyclic_control(a5, b)
                for b in [a5, cyclic(49), direct(c7, c7)]]
    require(products[0]["order"] <= GAMMA*Fraction(products[0]["eta"])**4,
            "semisimple product radical bound")
    require(products[1]["cyclic_count"] == 3*a5.c, "prime-power decoration")
    require(products[2]["cyclic_count"] == 9*a5.c, "rank-two coprime kernel")

    bound_rows, arithmetic = arithmetic_controls()
    rejected = []
    for label, call in [
        ("noncoprime", lambda: scalar_extension(5, s5, [1]*s5.n)),
        ("nonhomomorphic", lambda: scalar_extension(7, c2, [1, 2])),
        ("K_below_one", lambda: bounds(Fraction(1, 2))),
        ("floating_K", lambda: bounds(1.5)),
    ]:
        try:
            call()
        except ValueError:
            rejected.append(label)
        else:
            raise ValueError("negative control accepted: "+label)
    require(nonsolvable_normal_pairs > 0, "nonsolvable normal controls missing")
    return {
        "scope": "exact finite controls; universal argument is PROOF.md",
        "gamma": str(GAMMA), "fixture_count": len(records), "fixtures": records,
        "relative_pair_count": len(relatives),
        "nonsolvable_normal_pair_count": nonsolvable_normal_pairs,
        "relative_pair_digest": digest(relatives),
        "solvable_quotient_count": len(quotients),
        "solvable_quotient_digest": digest(quotients),
        "relative_triple_count": len(triples),
        "relative_triple_digest": digest(triples),
        "lucchini_cyclic_checks": len(lucchini),
        "lucchini_cyclic_digest": digest(lucchini),
        "nonsolvable_scalar_extension": {
            "group": "C7:S5(sign)", "order": twist.n,
            "cyclic_count": twist.c, "complement_count": s5.c,
            "centralizer_count": cl, "centralizer": "A5"},
        "nonsolvable_prime_power_extension": scalar_prime_power_control(7, 2, s5),
        "product_controls": products, "bounds": bound_rows,
        "arithmetic": arithmetic, "rejected_inputs": rejected,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--expect", type=Path)
    args = parser.parse_args()
    result = json.loads(json.dumps(run()))
    if args.expect:
        require(result == json.loads(args.expect.read_text()),
                "output differs from expected evidence")
    print(json.dumps(result, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
