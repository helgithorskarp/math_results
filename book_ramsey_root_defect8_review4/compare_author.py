#!/usr/bin/env python3
"""Optional passive comparison after the standalone reviewer proof.

Inputs are private runtime exports, regenerated by the documented commands.
They are not premises of audit.py. This comparison checks all original count
entries and inclusion of every original representative mask/defect tuple.
The full original placement and trace audit belongs to the author checker.
"""
import argparse
import json
from pathlib import Path

from incidence import need


def run(original, reviewer):
    lookup = {(c['profile'], c['w']): c for c in reviewer}
    forms = stars = assignments = 0
    for case in original['cases']:
        spec = case['spec']
        own = lookup[spec['profile'], spec['weight']]
        need([r['counts'] for r in case['records']] == [r['counts'] for r in own['records']], 'all original incidence entries')
        for author, rebuilt in zip(case['records'], own['records']):
            bylabel = [set((m, tuple(g)) for m, g in row) for row in rebuilt['literal_active_defects']]
            for word in author['local_domains']:
                rep = word['representative']
                for group in word['stars']:
                    for mask in group['masks']:
                        need((mask, tuple(group['g'])) in bylabel[rep], 'author mask and defect belongs to relaxed domain')
                        stars += 1
            forms += 1
            assignments += len(author['defect_assignments'])
    need((forms, stars, assignments) == (143, 12693, 475), 'complete passive comparison census')
    return {'incidence_vectors_compared': forms, 'incidence_entries_compared': 64*forms,
            'author_permitted_representative_mask_and_defect_pairs_checked_in_relaxed_domain': stars,
            'author_assignments_counted': assignments, 'all_agree': True,
            'trust_boundary': 'Passive comparison after standalone reviewer proof; no author records or code determine the reviewer domain.'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--author-records', type=Path, required=True)
    parser.add_argument('--reviewer-records', type=Path, required=True)
    args = parser.parse_args()
    print(json.dumps(run(json.loads(args.author_records.read_text()),
                         json.loads(args.reviewer_records.read_text())), indent=2, sort_keys=True))
