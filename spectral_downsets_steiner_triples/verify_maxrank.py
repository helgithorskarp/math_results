"""Exact validation of MAXRANK_PROOF.md; Python 3.11+, stdlib only.

The all-orders result follows from the written proof, not sample extrapolation.
Input orbit coverage is regenerated by the existing exact enumeration helpers.
"""
from fractions import Fraction as F
from pathlib import Path
import argparse
import json
import sys

from certificates import (affine_sts9, capped_steiner_certificate,
                          cyclic_sts13, fano_blocks, steiner_certificate)
from maxrank_certificates import (fano_baseline, maximal_steiner_certificate,
                                  maximal_two9_certificate)
from verify import (check_definition, exact_psd_rank, fano_coverage,
                    matrix_hash, rejects)
from verify_two9 import complete_cohort, decode


def slack(Q, gap=F(0)):
    n = len(Q)
    return [[F(n if i == j else 0)-Q[i][j]
             -gap*(F(i == j)-F(1, n))
             for j in range(n)] for i in range(n)]


def star_vectors(D, s, v):
    return [[F(bool(a & (1 << i)))-F(s, len(D)) for a in D]
            for i in range(v)]


def gram(vectors):
    return [[sum(a*b for a, b in zip(x, y)) for y in vectors]
            for x in vectors]


def check_case(label, capped, ordinary, repaired, v):
    D, s, Qc = capped
    Do, so, Qo = ordinary
    Dr, sr, Q, metadata = repaired
    assert (D, s) == (Do, so) == (Dr, sr)
    n = len(D)
    assert all(sum(bool(a & (1 << i)) for a in D) == s for i in range(v))
    check_definition(D, s, Qc, psd=False)
    check_definition(D, s, Qo, psd=False)
    rank = check_definition(D, s, Q)
    assert rank == n-v
    print(label, "lower rank", rank, file=sys.stderr, flush=True)
    upper_rank = exact_psd_rank(slack(Q))
    half_rank = exact_psd_rank(slack(Qc, F(1, 2)))
    quarter_rank = exact_psd_rank(slack(Q, F(1, 4)))
    assert upper_rank == half_rank == quarter_rank == n-1
    assert all(x == 1 for x in Qc[0])
    stars = star_vectors(D, s, v)
    w = [F(a == 0)-F(1, n) for a in D]
    assert exact_psd_rank(gram(stars)) == v
    assert exact_psd_rank(gram(stars+[w])) == v+1
    for i in range(n):
        assert sum(Qc[i][j]*w[j] for j in range(n)) == 0
        ordinary_action = sum(Qo[i][j]*w[j] for j in range(n))
        assert ordinary_action == Qo[i][0]-1
        assert sum(Q[i][j]*w[j] for j in range(n)) == F(metadata["epsilon"])*ordinary_action
    component = 0 if v == 7 else 1
    assert Qo[component][0]-1 != 0
    trace = sum(Qo[i][i] for i in range(n))
    assert trace == F(metadata["ordinary_trace"]) >= n
    assert F(metadata["epsilon"]) == F(1, 4)/trace
    print(label, "upper and both quantitative buffers pass", file=sys.stderr, flush=True)
    return {"label": label, "N": n, "s": s, "rank_Q": rank,
            "rank_upper": upper_rank, "input_half_buffer_rank": half_rank,
            "output_quarter_buffer_rank": quarter_rank,
            "epsilon": metadata["epsilon"], "ordinary_trace": str(trace),
            "ordinary_w_component": str(Qo[component][0]-1),
            "new_empty_diagonal_Q": str(Q[0][0]),
            "matrix_sha256": matrix_hash(Q)}


def product_parameters(factors):
    """Only arithmetic examples; no dense product matrix is generated."""
    n = 1
    for N, s, r in factors:
        n *= N
    p = max(F(s, N) for N, s, r in factors)
    largest = sum(r for N, s, r in factors if F(s, N) == p)
    size = n*p
    assert size.denominator == 1
    return {"N": n, "s": int(size), "rank_Q": n-largest,
            "largest_coordinate_stars": largest}


def run():
    result = {"single_system_examples": [], "two_system_examples": []}
    instances = [(7, fano_blocks()), (9, affine_sts9()), (13, cyclic_sts13())]
    for v, blocks in instances:
        capped = capped_steiner_certificate(v, blocks)
        ordinary = fano_baseline(blocks) if v == 7 else steiner_certificate(v, [blocks])
        repaired = maximal_steiner_certificate(v, blocks)
        result["single_system_examples"].append(
            check_case("STS"+str(v), capped, ordinary, repaired, v))
        if v == 7:
            D, s, Q, metadata = repaired
            result["STS7_coverage"] = fano_coverage(D, s, Q)
    data = json.loads(Path(__file__).with_name("two9_certificates.json").read_text())
    first = tuple(data["first_blocks"])
    reps, cohort = complete_cohort(first)
    assert [list(rep) for rep, size, p in reps] == [c["second_blocks"] for c in data["cases"]]
    result["two_system_coverage"] = cohort
    for i, case in enumerate(data["cases"]):
        D, Qc = decode(first, case)
        ordinary = steiner_certificate(9, [first, case["second_blocks"]])
        result["two_system_examples"].append(
            check_case("twoSTS9-case"+str(i), (D, 17, Qc), ordinary,
                       maximal_two9_certificate(i), 9))

    # Specific controls for the rank repair and its scope.
    D, s, Qc = capped_steiner_certificate(9, affine_sts9())
    def unrepaired_is_not_maximal():
        assert exact_psd_rank(Qc) == len(D)-9
    rejects(unrepaired_is_not_maximal)
    Do, so, Qo = steiner_certificate(9, [affine_sts9()])
    assert Qo[0][0] == 379 > len(Do)
    rejects(lambda: exact_psd_rank(slack(Qo)))
    D, s, Q, metadata = maximal_steiner_certificate(7, fano_blocks())
    bad = [row[:] for row in Q]
    bad[0][0] += 1
    rejects(lambda: check_definition(D, s, bad))
    rejects(lambda: maximal_steiner_certificate(3, [7]))
    result["rejection_controls"] = 4

    result["product_parameter_examples"] = {
        "STS7_times_STS9": product_parameters([(36, 10, 7), (58, 13, 9)]),
        "STS9_times_twoSTS9": product_parameters([(58, 13, 9), (70, 17, 9)]),
        "twoSTS9_squared": product_parameters([(70, 17, 9)]*2),
        "exception_times_STS7": product_parameters([(32, 11, 6), (36, 10, 7)])}
    example = result["product_parameter_examples"]["exception_times_STS7"]
    assert example == {"N": 1152, "s": 396, "rank_Q": 1146, "largest_coordinate_stars": 6}
    assert F(35, 96)*example["N"] == 420 == F(35, 33)*example["s"]
    result["exception_mixed_dual_arithmetic"] = {"N": 1152, "s": 396,
        "fractional_lower_bound": "420", "ratio_lower_bound": "35/33"}
    return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = run()
    if args.check:
        assert output == json.loads(Path(__file__).with_name("maxrank_expected.json").read_text())
    print(json.dumps(output, indent=2, sort_keys=True))
