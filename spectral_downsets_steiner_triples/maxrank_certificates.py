def fano_baseline(blocks):
    """Transport the retained balanced Fano certificate by congruence.

    Complete STS(7) coverage is regenerated by the verifier, not inferred
    from finding a permutation for one input.
    """
    check_sts(7, blocks)
    target = tuple(sorted(blocks))
    original = fano_blocks()
    D, s, Q = fano_certificate()
    for p in permutations(range(7)):
        if tuple(sorted(relabel(a, p) for a in original)) == target:
            indices = sorted(range(len(D)),
                             key=lambda i: (D[i].bit_count(), relabel(D[i], p)))
            return ([relabel(D[i], p) for i in indices], s,
                    [[Q[i][j] for j in indices] for i in indices])
    raise ValueError("STS(7) is outside the verified relabelling orbit")


def mix_certificates(capped, ordinary):
    """Quantitative convex repair, assuming the proved input hypotheses.

    The capped input has gap at least 1/2 on the constant complement.
    The ordinary input is PSD. epsilon=1/(4 Tr(ordinary)) gives gap>=1/4.
    Positivity and the claimed ranks are checked separately by the verifier.
    """
    D, s, Qc = capped
    Do, so, Qo = ordinary
    assert D == Do and s == so
    n = len(D)
    trace = sum(Qo[i][i] for i in range(n))
    epsilon = F(1, 4) / trace
    assert 0 < epsilon < 1
    Q = [[(1-epsilon)*Qc[i][j]+epsilon*Qo[i][j]
          for j in range(n)] for i in range(n)]
    return D, s, Q, {"epsilon": str(epsilon), "ordinary_trace": str(trace)}


def maximal_steiner_certificate(v, blocks):
    """Any STS(v), v>=7: capped H with rank Q=N-v, upper rank N-1."""
    check_sts(v, blocks)
    if v < 7:
        raise ValueError("the maximal-star rank theorem assumes v>=7")
    capped = capped_steiner_certificate(v, blocks)
    ordinary = fano_baseline(blocks) if v == 7 else steiner_certificate(v, [blocks])
    return mix_certificates(capped, ordinary)


def maximal_two9_certificate(case_index):
    """One of the two complete STS(9)-pair representatives: rank Q=61."""
    if case_index not in (0, 1):
        raise ValueError("require one of the two verified pair representatives")
    data = json.loads(Path(__file__).with_name("two9_certificates.json").read_text())
    first = data["first_blocks"]
    second = data["cases"][case_index]["second_blocks"]
    D, Q = decode(first, data["cases"][case_index])
    return mix_certificates((D, 17, Q), steiner_certificate(9, [first, second]))
