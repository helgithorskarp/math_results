"""Check the zigzag cover/tiling fixtures and reproduce its corona exclusion.

The universal radius-five input is generated by equivalence_certificate.py.
This adapter checks its new witnesses, independently audits every candidate
pair, and generates or solves the complete third-corona input for the example.
"""
import argparse
import hashlib
from itertools import combinations
import json
from pathlib import Path
import resource
import sys
import time

import color_state as cs
import equivalence_certificate as ec
import equivalence_state as es
import hex_domain as hd
import marked_corona


HERE = Path(__file__).resolve().parent


def fixtures():
    instance, checks = ec.checked_instance(HERE/'zigzag4_directed_cover_tiling.json')
    cover = json.loads((HERE/'zigzag4_twocolor_radius4.cover.json').read_text())
    corona = json.loads((HERE/'zigzag4_twocolor_depth2.witness.json').read_text())
    if (cover['tile'] != instance['tile'] or corona['tile'] != instance['tile']
            or cover['colors'] != corona['colors'] or cover['signs'] != corona['signs']
            or cover['radius'] != 4 or corona['depth'] != 2):
        raise ValueError('inconsistent sharpness fixtures')
    blocked = [any(cover['colors'][i] != cover['colors'][j]
                   or cover['signs'][i] != -cover['signs'][j]
                   for i, j in motif['checks']['matching_port_pairs'])
               for motif in instance['motifs']]
    if not all(blocked):
        raise ValueError('the example admits one of the periodic motifs')
    result = {'ports': len(hd.boundary(instance['tile'])), 'motifs': len(checks),
              'determinants': [x['determinant'] for x in checks],
              'boundary_incidences': [x['boundary_incidences'] for x in checks],
              'radius4_cover': cs.check_cover(cover),
              'two_coronas': cs.check_corona(corona),
              'example_excludes_all_motifs': True}
    return instance, corona, result


def audit(instance, Circuit):
    tile, radius = instance['tile'], instance['radius']
    _, candidates, incidences, stats = cs.cover_geometry(tile, radius, Circuit)
    actual, omitted = es.contact_inventory(tile, candidates, incidences)
    records = [{'turns': 0, 'translation': [0, 0]}] + candidates
    # Dense all-pair cell adjacency and inverse rotation decoding are separate
    # from the edge-hash/forward-port inventory used by the CNF generator.
    footprints = [cs.placement(tile, record) for record in records]
    original = {edge: i for i, edge in enumerate(hd.boundary(tile))}
    expected, pair_count = set(), 0
    for a, b in combinations(range(len(records)), 2):
        ac, ai = footprints[a]
        bc, bi = footprints[b]
        pair_count += 1
        if ac & bc:
            continue
        for u in ac:
            for dx, dy in hd.NEIGHBORS:
                v = u[0]+dx, u[1]+dy
                if v in bc:
                    i, j = original[ai(u), ai(v)], original[bi(v), bi(u)]
                    expected.add((a, b, min(i, j), max(i, j)))
    if actual != sorted(expected):
        raise ValueError('forward and inverse contact inventories disagree')
    return {'geometry': stats, 'candidate_pair_cases': pair_count,
            'contacts': len(actual), 'overlapping_contact_pairs_omitted': omitted,
            'sorted_contact_inventory_sha256': hashlib.sha256(
                json.dumps(actual, separators=(',', ':')).encode()).hexdigest()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('mode', choices=['check', 'audit', 'generate-third', 'exclude-third'])
    parser.add_argument('--unmarked-source', type=Path,
                        default=HERE.parent/'heesch_polyomino_euler_cnf')
    parser.add_argument('--output-dir', type=Path)
    args = parser.parse_args()
    instance, corona, checked = fixtures()
    if args.mode == 'check':
        print(json.dumps(checked, sort_keys=True, indent=2))
        return
    marked_corona.check_encoding_dependencies(args.unmarked_source)
    sys.path.insert(0, str(args.unmarked_source.resolve()))
    from circuit import Circuit
    if args.mode == 'audit':
        checked['contact_audit'] = audit(instance, Circuit)
        print(json.dumps(checked, sort_keys=True, indent=2))
        return
    if args.output_dir is None:
        parser.error('--output-dir is required for generated files')
    started = time.monotonic()
    circuit, _, stats = cs.build_corona(corona['tile'], 3, corona['colors'],
                                        corona['signs'], Circuit)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    prefix = args.output_dir/'zigzag4_twocolor_depth3'
    cnf = prefix.with_suffix('.cnf')
    circuit.write_dimacs(cnf)
    stats.update(cnf_sha256=hashlib.sha256(cnf.read_bytes()).hexdigest(),
                 assumptions='none', result='GENERATED')
    if args.mode == 'exclude-third':
        from pysat.solvers import Solver
        from pysat import __version__
        stats.update(python_sat=__version__, solver='glucose4', conflict_budget=20000)
        with Solver(name='glucose4', bootstrap_with=circuit.clauses, with_proof=True) as solver:
            solver.conf_budget(20000)
            result = solver.solve_limited()
            stats.update(result='SAT' if result else 'UNSAT; independent proof checking required'
                         if result is False else 'UNKNOWN', solver_stats=solver.accum_stats())
            if result is False:
                proof = prefix.with_suffix('.drat')
                proof.write_text('\n'.join(solver.get_proof())+'\n')
                stats.update(proof_bytes=proof.stat().st_size,
                             proof_sha256=hashlib.sha256(proof.read_bytes()).hexdigest())
    stats.update(seconds=round(time.monotonic()-started, 3),
                 peak_rss_kib=resource.getrusage(resource.RUSAGE_SELF).ru_maxrss)
    prefix.with_suffix('.summary.json').write_text(json.dumps(stats, sort_keys=True, indent=2)+'\n')
    print(json.dumps(stats, sort_keys=True, indent=2), flush=True)


if __name__ == '__main__':
    main()
