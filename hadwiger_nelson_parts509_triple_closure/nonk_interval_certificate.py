#!/usr/bin/env python3
"""Rigorous error certificate for the float screen over the non-K intersection points (README, trust boundary).

The non-K layer of the delete-4-add-3 closure screens candidate unit pairs among the non-K points with a
binary64 annulus test (|d - 1| < 1e-7) before exact confirmation.  Completeness of that screen needs the
binary64 coordinates (computed by two_neighbour_points.nonk_row from 50-digit mpmath values) to be close
to the true coordinates.  This script proves that with exact rational arithmetic only:

  p = m + s t n, m, n in K^2, t = sqrt(rho), rho in K  (K = Q(sqrt3, sqrt5, sqrt11), vertex pair (i, j));
  kfield.real_bounds encloses the real embedding of every element of K in a rational interval (isqrt-based
  enclosures of sqrt3, sqrt5, sqrt11 with 10^-DIGITS resolution); sqrt(rho) is enclosed with isqrt on the
  rational bounds; sums and products are combined by rational interval arithmetic.

For every non-K point (labels regenerated by nonk_row, identical code path to the closure) the script checks
that the binary64 coordinates lie inside the enclosure widened by 2^-45, and records the maximal enclosure
width W and the maximal deviation E of a float from the enclosure midpoint.  Consequence: for two screened
points whose true distance is exactly 1, the true distance of the stored float points is within 2(W+E) of 1,
and the binary64 hypot of coordinates bounded by 4 adds at most a few ulps (< 1e-14); every true unit pair
therefore has float distance within 1e-13 of 1, far inside the 1e-7 annulus.
usage: python nonk_interval_certificate.py [--digits 40] [--workers 4]   -> nonk_interval_certificate.json
"""
import json, sys, time, argparse, importlib.util
from fractions import Fraction
from math import isqrt
from pathlib import Path
from multiprocessing import Pool
HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location('tnp', HERE / 'two_neighbour_points.py')
tnp = importlib.util.module_from_spec(spec); sys.modules['tnp'] = tnp; spec.loader.exec_module(tnp)
kf = tnp.kf; ecp = tnp.ecp
KK = 3; FOUR = kf.const(KK, 4); HALF = Fraction(1, 2)
DIG = 40


def sqrt_bounds_frac(lo, hi, digits):
    """Rational enclosure of sqrt on the rational interval [lo, hi], 0 < lo <= hi."""
    S = 10 ** digits
    a = isqrt((lo.numerator * S * S) // lo.denominator)      # <= sqrt(lo) * S
    b = isqrt((hi.numerator * S * S) // hi.denominator) + 1  # >  sqrt(hi) * S
    return Fraction(a, S), Fraction(b, S)


def imul(a, b):
    c = (a[0] * b[0], a[0] * b[1], a[1] * b[0], a[1] * b[1])
    return min(c), max(c)


def enclose(i, j, s):
    pts = ecp.POINTS
    xi, yi = pts[i]; xj, yj = pts[j]
    dx = kf.sub(xi, xj); dy = kf.sub(yi, yj)
    dd = kf.add(kf.mul(dx, dx, KK), kf.mul(dy, dy, KK))
    rho = kf.mul(kf.sub(FOUR, dd), kf.inv(kf.scale(dd, 4), KK), KK)
    mx = kf.scale(kf.add(xi, xj), HALF); my = kf.scale(kf.add(yi, yj), HALF)
    nx, ny = kf.neg(dy), dx
    rb = kf.real_bounds(rho, KK, DIG)
    assert rb[0] > 0
    tb = sqrt_bounds_frac(rb[0], rb[1], DIG)
    st = tb if s > 0 else (-tb[1], -tb[0])
    ex = imul(st, kf.real_bounds(nx, KK, DIG)); mxb = kf.real_bounds(mx, KK, DIG)
    ey = imul(st, kf.real_bounds(ny, KK, DIG)); myb = kf.real_bounds(my, KK, DIG)
    return (mxb[0] + ex[0], mxb[1] + ex[1]), (myb[0] + ey[0], myb[1] + ey[1])


def work(i):
    _, rows = tnp.nonk_row(i)
    W = Fraction(0); E = Fraction(0); bad = 0; n = 0
    for j, s, fx, fy in rows:
        ex, ey = enclose(i, j, s); n += 1
        for (lo, hi), f in ((ex, fx), (ey, fy)):
            W = max(W, hi - lo); mid = (lo + hi) / 2; E = max(E, abs(Fraction(f) - mid))
            if not (lo - Fraction(1, 2 ** 45) <= Fraction(f) <= hi + Fraction(1, 2 ** 45)):
                bad += 1
    return n, W, E, bad


def main():
    global DIG
    ap = argparse.ArgumentParser(); ap.add_argument('--digits', type=int, default=40); ap.add_argument('--workers', type=int, default=4)
    args = ap.parse_args(); DIG = args.digits
    t0 = time.time(); n = 0; W = Fraction(0); E = Fraction(0); bad = 0; done = 0
    with Pool(args.workers, initializer=ecp.init) as pool:
        for cnt, w, e, b in pool.imap_unordered(work, range(509), chunksize=4):
            n += cnt; W = max(W, w); E = max(E, e); bad += b; done += 1
            if done % 100 == 0:
                print(f'{done}/509 vertex rows, {n} points: max width {float(W):.3e}, max float deviation {float(E):.3e}, outside {bad}  ({time.time()-t0:.0f}s)', flush=True)
    print(f'DONE {n} non-K points: max enclosure width W = {float(W):.3e}, max float deviation E = {float(E):.3e}, coordinates outside the 2^-45-widened enclosure: {bad}  ({time.time()-t0:.0f}s)', flush=True)
    (HERE / 'nonk_interval_certificate.json').write_text(json.dumps({'points': n, 'digits': DIG, 'max_width': str(W), 'max_width_float': float(W),
        'max_float_deviation': str(E), 'max_float_deviation_float': float(E), 'outside_widened_enclosure': bad, 'widening': '2^-45', 'seconds': round(time.time() - t0)}, indent=1))


if __name__ == '__main__':
    main()
