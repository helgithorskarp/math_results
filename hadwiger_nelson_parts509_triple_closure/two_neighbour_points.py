#!/usr/bin/env python3
"""Two-neighbour completion points of the Parts-509 graph and the extra triples
needed for the delete-4-add-3 closure.

Q2K: K-rational points (K = Q(sqrt3,sqrt5,sqrt11)) outside V at unit distance
from exactly two vertices.  Exact unit incidences Q2K-Q3 and Q2K-Q2K are found
by a conservative float screen (|d-1| < 1e-7, float error << 1e-10) followed by
exact confirmation in K.  Non-K intersection points (the two points of a
vertex pair whose rho^2 is not a square in K) are screened for unit pairs among
themselves with a rigorous tolerance; a unit triangle among them would need
exact confirmation (none expected by the algebra in the README).
"""
from __future__ import annotations
import importlib.util, json, sys, time
from fractions import Fraction
from pathlib import Path
from multiprocessing import Pool
import numpy as np
import mpmath as mp

HERE = Path(__file__).resolve().parent
_CAND = [HERE.parent, Path.home() / 'math_results']
PAIRDIR = next(p / 'hadwiger_nelson_parts509_pair_closure' for p in _CAND if (p / 'hadwiger_nelson_parts509_pair_closure' / 'pair_certificate.json').exists())
SWAPDIR = next(p / 'hadwiger_nelson_parts509_swap_closure' for p in _CAND if (p / 'hadwiger_nelson_parts509_swap_closure' / 'swap_certificate.json').exists())
sys.path.insert(0, str(SWAPDIR))
import kfield as kf
spec = importlib.util.spec_from_file_location('ecp', SWAPDIR / 'enumerate_completion_points.py')
ecp = importlib.util.module_from_spec(spec); sys.modules['ecp'] = ecp; spec.loader.exec_module(ecp)
K = 3
TOL = 1e-7
mp.mp.dps = 50
SQ = {p: mp.sqrt(p) for p in kf.PRIMES}


def to_mp(x):
    total = mp.mpf(0)
    for mask, a in enumerate(x):
        if not a:
            continue
        v = mp.mpf(a.numerator) / a.denominator
        for bit in range(K):
            if (mask >> bit) & 1:
                v *= SQ[kf.PRIMES[bit]]
        total += v
    return total


def d2_exact(p, q):
    dx = kf.sub(p[0], q[0]); dy = kf.sub(p[1], q[1])
    return kf.add(kf.mul(dx, dx, K), kf.mul(dy, dy, K))


ONE = kf.one(K)
FOUR = kf.const(K, 4)


def nonk_row(i):
    """Non-K intersection points generated by vertex pairs (i, j), j > i, as
    50-digit floats: list of (j, sign, x, y)."""
    pts = ecp.POINTS
    xi, yi = pts[i]
    out = []
    for j in range(i + 1, len(pts)):
        xj, yj = pts[j]
        dx = kf.sub(xi, xj); dy = kf.sub(yi, yj)
        d2 = kf.add(kf.mul(dx, dx, K), kf.mul(dy, dy, K))
        num = kf.sub(FOUR, d2)
        sg = kf.sign(num)
        if sg <= 0:
            continue                     # d >= 2: tangent (K-rational midpoint) or empty
        rho2 = kf.mul(num, kf.inv(kf.scale(d2, 4), K), K)
        if kf.field_sqrt(rho2, K) is not None:
            continue                     # K-rational: handled by the census
        r = mp.sqrt(to_mp(rho2))
        mx = (to_mp(xi) + to_mp(xj)) / 2; my = (to_mp(yi) + to_mp(yj)) / 2
        wx = -to_mp(dy) * r; wy = to_mp(dx) * r
        for s in (1, -1):
            out.append((j, s, float(mx + s * wx), float(my + s * wy)))
    return i, out


def unit_pairs_float(P, Q=None, tol=TOL):
    """All index pairs (i, j) with | |P_i - Q_j| - 1 | < tol (P, Q float arrays).
    Cell grid of size h; offsets covering the unit annulus."""
    same = Q is None
    if same:
        Q = P
    h = 0.05
    cellsP = {}
    for idx, (x, y) in enumerate(P):
        cellsP.setdefault((int(np.floor(x / h)), int(np.floor(y / h))), []).append(idx)
    cellsQ = cellsP if same else {}
    if not same:
        for idx, (x, y) in enumerate(Q):
            cellsQ.setdefault((int(np.floor(x / h)), int(np.floor(y / h))), []).append(idx)
    R = int(np.ceil((1 + tol) / h)) + 1
    offsets = []
    for ox in range(-R, R + 1):
        for oy in range(-R, R + 1):
            # min and max distance between points of cell (0,0) and cell (ox,oy)
            mnx = max(0, abs(ox) - 1) * h; mny = max(0, abs(oy) - 1) * h
            mxx = (abs(ox) + 1) * h; mxy = (abs(oy) + 1) * h
            dmin = np.hypot(mnx, mny); dmax = np.hypot(mxx, mxy)
            if dmin <= 1 + tol and dmax >= 1 - tol:
                offsets.append((ox, oy))
    out = []
    for (cx, cy), ids in cellsP.items():
        A = P[ids]
        for ox, oy in offsets:
            jds = cellsQ.get((cx + ox, cy + oy))
            if not jds:
                continue
            B = Q[jds]
            d = np.hypot(A[:, None, 0] - B[None, :, 0], A[:, None, 1] - B[None, :, 1])
            ii, jj = np.nonzero(np.abs(d - 1) < tol)
            for a, b in zip(ii, jj):
                i, j = ids[a], jds[b]
                if same and i >= j:
                    continue
                out.append((int(i), int(j)))
    return sorted(set(out))


def main():
    t0 = time.time()
    parts = ecp.load_parts()
    points = parts.parse_points(ecp.BASE / 'parts509.vtx')
    n = len(points)
    vertex_index = {p: i for i, p in enumerate(points)}
    merged = {}
    with Pool(6, initializer=ecp.init) as pool:
        for i, rp, out in pool.imap_unordered(ecp.row, range(n), chunksize=4):
            for q, gens in out.items():
                merged.setdefault(q, set()).update(gens)
    q2k = sorted(((q, tuple(sorted(g))) for q, g in merged.items() if q not in vertex_index and len(g) == 2),
                 key=lambda t: (kf.to_float(t[0][0]), kf.to_float(t[0][1])))
    print(f'K-points with exactly two vertex neighbours: {len(q2k)}  ({time.time()-t0:.0f}s)', flush=True)
    comp = json.loads((SWAPDIR / 'completion_points.json').read_text())
    q3 = [((kf.from_strings(eval(r['x'])) if isinstance(r['x'], str) else kf.from_strings(r['x']),
            kf.from_strings(eval(r['y'])) if isinstance(r['y'], str) else kf.from_strings(r['y'])), tuple(r['neighbors']))
          for r in comp['points']]
    for (q, nb) in q3[:50]:
        for v in nb:
            assert d2_exact(q, points[v]) == ONE
    P2 = np.array([[kf.to_float(q[0]), kf.to_float(q[1])] for q, _ in q2k])
    P3 = np.array([[kf.to_float(q[0]), kf.to_float(q[1])] for q, _ in q3])
    # exact rescan of a sample of Q2K points against all vertices (must give exactly the 2 generators)
    for (q, nb) in q2k[::97]:
        sc = [v for v in range(n) if d2_exact(q, points[v]) == ONE]
        assert tuple(sc) == nb, (sc, nb)
    # --- screens + exact confirmation
    c23 = unit_pairs_float(P2, P3)
    adj23 = sorted((i, j) for i, j in c23 if d2_exact(q2k[i][0], q3[j][0]) == ONE)
    c22 = unit_pairs_float(P2)
    adj22 = sorted((i, j) for i, j in c22 if d2_exact(q2k[i][0], q2k[j][0]) == ONE)
    print(f'Q2K-Q3 candidates {len(c23)} exact {len(adj23)}; Q2K-Q2K candidates {len(c22)} exact {len(adj22)}  ({time.time()-t0:.0f}s)', flush=True)
    nb3 = {}
    for i, j in adj23:
        nb3.setdefault(i, []).append(j)
    nb2 = {}
    for i, j in adj22:
        nb2.setdefault(i, []).append(j); nb2.setdefault(j, []).append(i)
    qq = set(tuple(e) for e in json.loads((PAIRDIR / 'ambient_w3_edges.json').read_text())['edges'])
    N = n
    def q3adj(a, b):
        return (min(a, b) + N, max(a, b) + N) in qq
    type_ii = []
    for p, lst in nb3.items():
        lst = sorted(lst)
        for x in range(len(lst)):
            for y in range(x + 1, len(lst)):
                type_ii.append([p, lst[x], lst[y], int(q3adj(lst[x], lst[y]))])
    type_iiia = []
    for (p1, p2) in adj22:
        common = sorted(set(nb3.get(p1, [])) & set(nb3.get(p2, [])))
        for a3 in common:
            type_iiia.append([p1, p2, a3])
    adj22set = set(adj22)
    type_iiib = []
    for (p1, p2) in adj22:
        for p3 in nb2.get(p1, []):
            if p3 > p2 and (p2, p3) in adj22set:
                type_iiib.append([p1, p2, p3])
    print(f'type ii {len(type_ii)}  type iiia {len(type_iiia)}  type iiibK {len(type_iiib)}', flush=True)
    # --- non-K intersection points
    nonk = []
    with Pool(6, initializer=ecp.init) as pool:
        for i, out in pool.imap_unordered(nonk_row, range(n), chunksize=4):
            for j, s, x, y in out:
                nonk.append((i, j, s, x, y))
    PN = np.array([[x, y] for _, _, _, x, y in nonk])
    print(f'non-K intersection points: {len(nonk)}  ({time.time()-t0:.0f}s)', flush=True)
    cNN = unit_pairs_float(PN)
    nbN = {}
    for i, j in cNN:
        nbN.setdefault(i, set()).add(j); nbN.setdefault(j, set()).add(i)
    triN = []
    for i, j in cNN:
        for k in nbN[i] & nbN[j]:
            if k > j:
                triN.append([i, j, k])
    cN2 = unit_pairs_float(PN, P2)
    cN3 = unit_pairs_float(PN, P3)
    print(f'non-K unit-pair candidates {len(cNN)}, candidate triangles {len(triN)}; non-K vs Q2K candidates {len(cN2)}, vs Q3 {len(cN3)}  ({time.time()-t0:.0f}s)', flush=True)
    out = {
        'tolerance': TOL,
        'q2k': [{'x': kf.to_strings(q[0]), 'y': kf.to_strings(q[1]), 'neighbors': list(nb),
                 'q3_nbrs': sorted(nb3.get(i, [])), 'q2k_nbrs': sorted(nb2.get(i, []))} for i, (q, nb) in enumerate(q2k)],
        'q2k_count': len(q2k), 'adj_q2k_q3': adj23, 'adj_q2k_q2k': adj22,
        'type_ii': type_ii, 'type_iiia': type_iiia, 'type_iiibK': type_iiib,
        'nonk_points': len(nonk), 'nonk_unit_pair_candidates': cNN, 'nonk_candidate_triangles': triN,
        'nonk_vs_q2k_candidates': cN2, 'nonk_vs_q3_candidates': cN3,
        'nonk_labels': [[i, j, s] for i, j, s, _, _ in nonk] if len(cNN) else None,
    }
    (HERE / 'q2k_extra.json').write_text(json.dumps(out))
    print(f'wrote q2k_extra.json  total {time.time()-t0:.0f}s', flush=True)


if __name__ == '__main__':
    main()
